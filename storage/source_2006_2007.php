<p align="left"><b>26.kolo 24.06. Maleč 0:2 Sobíňov (0:1)<br>
naše góly: Z.Němec, J.Ondráček (T.Štěrba 2x (?))<br>
</b>V posledním kole této sezóny jsme zajížděli na hřiště Malče s
pocitem pohody, neboť už jsme díky sobotním zápasům věděli, že z třetí
třídy budou postupovat do okresního přeboru dva týmy. Nicméně jsme i tak
byli odhodláni vyhrát, neboť každý přeci ví, že první místo je lepší
než druhé a končit úspěšnou sezónu jinak než vítězstvím by se také
moc nehodilo. O našem odhodlání svědčila situace hned ze 30.sekundy zápasu,
kdy se do obrovské šance dostal Madri, který ovšem tváří v tvář domácímu
gólmanovi zaváhal. O chvíli později se do další velké šance dostal Cafua,
jeho křížná střela ovšem minula levou tyč domácí svatyně. První gól
tak z podobné pozice vstřelil v sedmé minutě Reno, který po pěkné akci zůstal
na chvilku osamocen za zády domácích beků a přesnou střelou rozvlnil síť.
Zatímco prvních dvacet minut jsme byli jasně lepším týmem, začala se Maleč
ke konci prvního poločasu dostávat do tempa- výsledkem jejich snahy bylo několik
