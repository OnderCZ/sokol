<p class="auto-style7"><strong>13. kolo Sobíňov 3:0 Maleč (0:0)<br />
</strong>střelci: 50. Zrzavý Tomáš, 60. Kafka Pavel, 82. Zrzavý Tomáš <br />
V prvním poločase posledního domácího utkání podzimní části sezóny se hrála z 
obou stran nezáživná nakopávaná s velkým množstvím ztrát a nepřesností. Maleč 
velmi záhy nastřádala možnost zahrávat asi pět rohových kopů, obrana Sobíňova 
ale odolala. Oba týmy si pak vypracovaly spíše náznaky šancí, jedinou opravdu 
tutovou šanci měla těsně před koncem poločasu Maleč, naštěstí pro Sobíňov se 
skvělým reflexem blýsknul gólman Veselý a tak se do kabin šlo stejně jako minulý 
týden za bezbrankového stavu.<br />
Sobíňov do druhého poločasu lehce přeskupil sestavu a začal ho tlakem, který 
vedl až ke šťastné vedoucí brance. Němec byl faulován kousek od velkého vápna a 
z nařízeného přímého kopu Zrzavý doslova procpal míč gólmanovi hostí mezi 
rukama- 1:0 pro domácí. O zhruba pět minut později mohlo být ještě veseleji, 
když po sporné situaci odpískal rozhodčí penaltu ve prospěch Sobíňova, gólman 
hostí Buršík ale napravil svou předchozí chybu a penaltu kapitána Říčana dokázal 
vyrazit. O tři minuty zřejmě lehce v rámci kompenzace odpískal rozhodčí po další 
nejasné situaci penaltu i na druhé straně. Ani za hosty ale neuspěl kapitán 
Koláček, jehož ránu výtečný Veselý též vyrazil. Další branka tak padla až v 
šedesáté minutě. Kafka dal vzpomenou na své o hodně let mladší já, na půlící 
čáře obral o míč váhajícího beka hostí a svoje sólo přes půl hřiště proměnil 
střelou podél gólmana v druhý gól Sobíňova- 2:0. Sobíňov pak měl i další šance k 
navýšení náskoku. Krásnou individuální akci předvedl například M.Ondráček, který 
prošel přes tři bránící hráče, svou střelu ale pak bohužel zamířil jen do boční 
sítě branky hostí. Deset minut před koncem musel odstoupit pro zranění stoper 
Štěrba, který špatně došlápl na kotník. Sobíňov už ale utkání relativně v pohodě 
dohrál a naopak ještě přidal Malči třetí gól, když po chybě obrany propadl 
dlouhý míč Koutníka až k Zrzavému, který poté přehodil gólmana hostí a dodržel 
tak svou parádní "normu" z posledních dvou zápasů, kdy pokaždé dvakrát skóroval.<br />
<em>sestava: P.Veselý - I.Koutník, T.Štěrba (P.Kodým), M.Vopršal, J.Brabec - 
M.Ondráček, D.Říčan, S.Ondráček, P.Kafka - T.Zrzavý, Z.Němec<br />
reportáž napsal: P.Kafka</em><br />
</p>
<p class="auto-style7"><strong>12. kolo Keřkov 2:3 Sobíňov (0:0)<br />
