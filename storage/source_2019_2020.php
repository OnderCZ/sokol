<p class="auto-style7"><strong>11. kolo Sobíňov 6:1 Lípa "B" (2:0)<br />
</strong>střelci: 15. Zrzavý Tomáš, 45. Jelínek Milan, 50. Ondráček Marek, 61. 
Zrzavý Tomáš, 64. Říčan Daniel, 89. Ondráček Marek - 66. Souček Pavel (pen.) <br />
Oproti minulému týdnu bylo na hřišti asi o patnáct stupňů tepleji a hezké počasí 
jakoby nahrávalo hostům, kteří byli v&nbsp;prvních deseti minutách lepším týmem. 
Sobíňov zaspal v&nbsp;kabině a mohl být rád, že hned ze začátku utkání jednou nebo 
dvakrát neinkasoval. Naopak se mu podařilo jít do vedení, když Říčan vybojoval 
míč, krásnou uličkou ho poslal na Zrzavého a ten v&nbsp;pádu na dlouhou nohu mířil 
přesně podél gólmana- 1:0. Hosté poměrně slušně kombinovali a zkoušeli překonat 
obranu domácích rychlými míči za obranu, i díky velmi dobře zahrávanému ofsajd 
systému ale Sobíňov odolával. Z&nbsp;úplně nenápadné akce na samém konci poločasu 
naopak skóroval podruhé- dlouhý nákop Koutníka mířící k&nbsp;rohovému praporku 
nepohlídal bek Lípy, o míč ho tam obral M.Ondráček a po centru do vápna se pak 
přesně trefil už potřetí na podzim Jelínek. Druhý poločas začal Sobíňov 
v&nbsp;podobném stylu jako skončil ten první. V&nbsp;50. minutě si naskočil na rohový kop 
Jelínka M.Ondráček a bylo to 3:0. V&nbsp;61. minutě podskočil stoper Lípy dlouhý 
nákop Koutníka a Zrzavý zakončil přesně- 4:0. O tři minuty později sice Kafka 
neproměnil jasnou šanci kdy sám proti gólmanovi trefil jen tyčku, odražený míč 
ale uklidil do sítě Říčan a bylo to 5:0. O dvě minuty se hosté dočkali čestného 
úspěchu, když se z&nbsp;penalty nemýlil Souček- 5:1, ale v&nbsp;68. minutě předvedl zkrat 
hostující stoper Bouda, za zápasnický chvat dostal červenou kartu a zápas tím 
víceméně definitivně skončil. Poslední, už jen kosmetickou změnu skóre tak 
přinesla spolupráce trojice Kafka, Říčan a M.Ondráček, kterou proměnil posledně 
jmenovaný hráč v&nbsp;šestou branku v&nbsp;síti hostí- 6:1. Konečné skóre neodpovídá úplně 
dění na hřišti, hosté ale svoje šance na rozdíl od domácích nedokázali 
proměňovat. Sobíňov se díky povedené sérii zápasů (4 výhry v řadě při skóre 
17:3) dostal v tabulce celkem nahoru, samozřejmě budeme jen rádi, když se nám ze 
zbývajících třech zápasů s těžkými soupeři povede ještě nějaké body přidat.<br />
