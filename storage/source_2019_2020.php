<p class="auto-style7"><strong>10. kolo Rozsochatec "B" 1:4 Sobíňov (1:3)<br />
</strong>střelci: 45. Pleskač Ivan&nbsp;-&nbsp;16. Říčan Daniel, 21. Kafka Pavel, 44. 
Jelínek Milan, 49. Kafka Pavel<br />
Do Rozsochatce jsme odjeli pouze v jedenácti hráčích do pole, a jelikož venku 
