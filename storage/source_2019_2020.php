<p class="auto-style7"><strong>01. kolo Habry "B" 4:2 Sobíňov (2:1)<br />
</strong>střelci: 15. Melechovský Josef, 44. Bernat Michal, 53. Melechovský 
Josef, 61. Lacina Jakub - 19. Zrzavý Tomáš, 48. Zrzavý Tomáš<br />
Poslední podzimní zápas jsme odehráli v&nbsp;sobotním dopoledni na hřišti prvního 
týmu tabulky. Zkušená rezerva Habrů ukazovala od začátku, proč vede naši soutěž- 
důrazně napadala naši rozehrávku už na naší polovině, nenechávala nás vůbec 
kombinovat a my jsme tak hráli poměrně hodně času zataženi před svým vápnem a 
bez držení míče. Ze stálého tlaku si domácí vytvářeli i šance, hodně toho ale 
dokázal pochytat gólman Veselý. Dost akcí na poslední chvíli zhatila i naše 
obrana, přestože hrála v&nbsp;trochu improvizovaném složení kvůli zranění obvyklého 
stopera Štěrby, na jehož místě nastoupil M.Vopršal a vedl si tam též slušně. 
V&nbsp;patnácté minutě už jsme ovšem inkasovali, zaslouženou první branku domácích 
trefil Melechovský. Po čtyřech minutách jsme ale v&nbsp;podstatě z&nbsp;ničeho dokázali 
vyrovnat. Dlouhý nákop prodloužil za sebe hlavou M.Ondráček, za obranou vyplaval 
úplně osamocený Zrzavý, který potvrdit skvělou střeleckou formu posledních 
zápasů a tvrdou ranou prostřelil gólmana- 1:1. Domácí to na chvilku trochu 
zabrzdilo, ale poté se zápas opět vrátil do starých kolejí, kdy jsme se víceméně 
neustále jen bránili. Když už to vypadalo, že s&nbsp;notnou dávkou štěstí dohrajeme 
poločas na remízu, dostali domácí možnost zahrávat snad už asi sedmý nebo osmý 
rohový kop. I tentokrát ho naše obrana dokázala napoprvé odvrátit, míč se ale 
dostal před velké vápno přímo k Bernatovi, který krásným halfvolejem na zadní 
tyč nedal nedal Veselému sebemenší šanci- 2:1 pro domácí.<br />
Zápas se pak definitivně lámal na začátku druhého poločasu. Zrzavý sice nejprve 
opět využil hezkého míče za obranu od O.Starého a vyrovnal na 2:2 (vstřelil tak 
osmou branku z&nbsp;posledních čtyřech zápasů), nadějnou remízu jsme ale drželi jen 
pět minut a poté jsme po zbytečně ztrátě míče inkasovali na 2:3. Po chvíli 
v&nbsp;naší síti přibyl ještě čtvrtý gól a bylo po zápase. Domácí pak ještě 
nedokázali proměnit další vyložené šance typu 4 hráči sami před gólmanem. Na 
naší straně stojí za zmínku snad jen střela Kafky ze střední vzdálenosti a 
Zrzavého šance při které mu míč nesedl na nohu tak jak by potřeboval, jinak jsme 
se k&nbsp;ohrožení branky moc nedostávali. Rezerva Habrů vyhrála zaslouženě, celý 
zápas nás přehrávala a klidně mohla zvítězit i větším gólovým rozdílem. Nám tak 
skončila naše šestizápasová série výher. Shrnutí jinak ale úspěšné podzimní 
části sezóny připravím později.<br />
<em>sestava: P.Veselý- I.Koutník, M.Vopršal, D.Vrána, M.Janáček- M.Ondráček, 
D.Říčan, P.Kafka, O.Starý- T.Zrzavý, S.Ondráček (M.Kučera)<br />
reportáž napsal: P.Kafka <br />
