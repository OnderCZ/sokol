Zrzavý Tomáš, 67. Vrána David <br />
Do Keřkova jsme cestovali s vědomím, že se nám zde&nbsp;na nepříliš kvalitním hřišti 
obvykle moc&nbsp;nedaří. První příležitosti jsme si ale vypracovali my. Nejdříve 
Zrzavý po centru z křídla s přispěním obránce trefil pouze tyčku. Poté dvakrát z 
dálky vyzkoušel brankáře domácích Říčan. Hostitelé se dostali do své nejvyšší 
šance na konci poločasu po našem nedůrazném odkopu, naštěstí nemířili mezi tyče.
<br />
Druhá půlka utkání pro nás nezačala vůbec dobře. Po špatné rozehrávce se dostal 
ve vápně k míči Kunc a ten se příliš v těchto situací nemýlí - 1:0. Za deset 
minut však bylo vyrovnáno. Valouškův vysoký nákop prodloužil Říčan, Zrzavý 
využil nedorozumění mezi obráncem a brankářem a pohodlně zasunul do prázdné 
branky. Za dvě minuty bylo ještě veseleji. Stejný hráč si naskočil na roh 
Jelínka a rozvlnil síť podruhé. Velmi podařenou část zápasu korunoval střídající 
Vrána, jeho tečovaná střela po pasu Ondráčka zapadla za záda brankáře - 3:1. V 
další šanci Ondráček branku netrefil a domácí trestali. Míč za obranu Štěrba 
pouze posunul nepřesně do strany hřiště, nabíhající útočné duo si vyměnilo balon 
a Zvolánek korigoval stav - 2:3. V nervozním závěru se spíše diskutovalo než 
hrálo a tak po více než 10 letech jsme brali v Keřkově všechny 3 body 
(5.10.2008, 9.kolo Okresního přeboru- Keřkov 2:3 Sobíňov (2:1) naše góly: 
D.Říčan PK, P.Bílek, M.Ondráček).<br />
