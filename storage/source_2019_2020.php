<p class="auto-style2"><strong>Jaro 2020</strong></p>
<p align="center" class="MsoNormal"><b style="mso-bidi-font-weight:
normal"><span style="mso-ansi-language:CS">Jak nám nezačala jarní část fotbalové 
sezóny<o:p></o:p></span></b></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Vzhledem k&nbsp;zdravotní 
situace v&nbsp;Česku a ve světě byl samozřejmě nejprve odložen a posléze i zrušen 
start jarní části soutěžního ročníku 2019/2020, která měla začínat 21.3. utkáním 
ve Věžnici. Fotbalisté Sobíňova v&nbsp;ní měli bojovat o minimálně udržení velmi 
pěkného třetího místa v&nbsp;tabulce, které nám na podzim 2019 zajistilo devět výher 
ze třinácti odehraných zápasů. Tým od začátku roku 2020 trénoval za vcelku 
slušné účasti venku a nově i v&nbsp;prostorech obecního kulturního domu, zdraví všech 
má však bezpochyby absolutní přednost před vším ostatním a tak musely být i 
společné tréninky týmu zhruba od půlky března zrušeny.<o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">
<o:p>Aktualizace 7.4.2020:<br />
Všechny amatérské fotbalové soutěže v Česku od třetí ligy níže byly kvůli 
pandemii nového typu koronaviru předčasně ukončeny. Rozhodl o tom výkonný výbor 
Fotbalové asociace ČR. Výkonný výbor se shodl, že pokračování amatérských 
soutěží, které řídí, by bylo i v nadcházejícím období příliš velkým rizikem a 
jejich dohrání by ani v létě nebylo možné.</o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">
<o:p>Konečné pořadí amatérských soutěží zůstane podle aktuálních tabulek k 8. 
dubnu, <strong>kluby nesestoupí ani nepostoupí</strong>. Výjimkou budou postupy 
do profesionálních soutěží - tedy z ČFL a MSFL do druhé ligy. <br />
<strong>TJ Sokol Sobíňov tedy v konečném pořadí nedohraného soutěžního ročníku 
2019/2020 obsadil třetí místo.</strong></o:p></span></p>
<p class="MsoNormal">
<o:p>Do doby než oficiálně začne nová sezóna (a všichni v tuto chvíli doufáme že 
to snad bude možné v původním termínu začátkem srpna 2020) je možné hrát 
nemistrovská a přátelská utkání, samozřejmě za předpokladu že to bude v souladu 
s předpisy nebo rozhodnutími orgánů státní správy vydanými zejména v souvislosti 
se šířením nemoci COVID-19.</o:p></p>
<p class="MsoNormal">
<o:p>Pokud bychom nějaká přátelská utkání plánovali a hráli, dáme určitě vědět 
na našem klubovém facebooku-
<a href="https://www.facebook.com/tjsokolsobinov/" target="_blank">ZDE</a></o:p></p>
<p class="MsoNormal">Přejeme všem hodně zdraví a v blízké době snad na trávníku 
i zde na stránkách s nějakými pozitivnějšími novinkami nashledanou...</p>
<p class="auto-style2">&nbsp;</p>
<p class="auto-style2"><strong>Podzim 2019</strong></p>
<p class="auto-style2">&nbsp;</p>
<p class="MsoNormal"><b style="mso-bidi-font-weight:normal">
<span style="mso-ansi-language:CS">Mužstvo dospělých<o:p></o:p></span></b></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">TJ Sokol Sobíňov začal 
v&nbsp;srpnu již osmou sezónu ve fotbalové třetí třídě havlíčkobrodského okresu. 
Vstupoval do ní trochu s&nbsp;obavami, neboť přes léto se rozhodl 
ukončit/pozastavit(?) své fotbalové působení Jára Ondráček ml., který byl přitom 
nejužitečnějším hráčem minulé sezóny 2018/2019 a další hráč základní sestavy Jan 
Hečko (pátý nejužitečnější hráč sezóny 2018/2019) si chtěl jít vyzkoušet 
působení v&nbsp;jiném okresním týmu a odešel tedy do Rozsochatce.<o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Před sezónou jsme se 
tedy snažili sehnat nějaké posily, bohužel R.Šedivý (4 starty) a F.Janáček (3x) 
odehráli jen pár zápasů než se zranili. A tak jsme během podzimu museli sáhnout 
do „rezerv“ a povolat do zbraně hráče, kteří v&nbsp;minulých sezónách tolik nehrávali 
a nebo dokonce již v&nbsp;podstatě hrát přestali. Na hřišti se tak desekrát objevil 
David Vrána a Marcel Kučera, osmkrát Jára Brabec a Milan Jelínek (předtím 
naposledy hrál soutěžní utkání v&nbsp;roce 2011), šestkrát Sláva Ondráček. Třikrát 
nám vypomohl i Lukáš Valoušek, ke konci sezóny ve dvou zápasech nastoupil i 
Ondra Starý. Všem těmto hráčům patří poděkování, nejenže bychom bez nich měli 
dost často problém postavit kompletní jedenáctku, ale navíc sbírali i důležité 
góly a asistence.<o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Vzhledem k&nbsp;výše uvedeným 
informacím považuji osobně skoro za zázrak, kolik bodů jsme na podzim dokázali 
uhrát a kde nakonec v&nbsp;tabulce přezimujeme. Zejména díky skvostné šestizápasové 
sérii výher z&nbsp;druhé poloviny podzimu jsme totiž získali krásných 27 bodů a 
nacházíme se na třetím místě třetitřídní tabulky při vysoce aktivním rozdílu 
skóre 40:23 (náš útok je druhý nejlepší). Pro srovnání- po podzimu 2018 jsme se 
nacházeli na pátém místě tabulky s&nbsp;23 body při skóre 33:15.<o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Začátek podzimu přitom 
nenaznačoval, že bychom tolik bodů měli udělat. V&nbsp;prvním zápase jsme sice 
porazili doma Věžnici „B“ 4:2, pak jsme ale dvakrát prohráli. Nejprve ve Vepřové 
2:3, což považujeme zpětně za asi nejhorší zápas sezóny a pak jsme doma neuhráli 
ani bod v&nbsp;zápase proti Jeřišnu- 1:2. Šťastná výhra v&nbsp;Havlíčkově Borové 3:2, kde 
jsme málem přišli o tříbrankový náskok, a důležitá domácí výhra nad Lipnicí 2:1 
nám naštěstí bodově polepšily a posunuly nás do klidných vod tabulky, takže nám 
ani tolik nevadila prohra ve Vísce 2:4, kde jsme hlavně fyzicky nestačili na 
mladé domácí mužstvo (věkový průměr domácí sestavy 23,6, věkový průměr Sobíňova 
36,3). Vítězstvím na hřišti posledního Kožlí „B“ 3:1 nastartovala skvělá 
šestizápasová série výher, která nás katapultovala až na třetí místo tabulky. 
Nejdříve jsme si doma jasným rozdílem poradili s&nbsp;Veselým Žďárem 5:0, poté jsme 
zvítězili v&nbsp;Rozsochatci nad místním béčkem 3:1, doma rozstříleli Lípu „B“ 6:1 a 
doslova vyválčili výhru v&nbsp;Keřkově 3:2. V&nbsp;posledním domácím zápase jsme 
přetlačili tým Malče 3:0 a až v&nbsp;posledním zápase podzimu jsme prohráli 
v&nbsp;Habrech, kde nás místní béčko přesvědčilo o tom, že se na špičce tabulky 
nachází oprávněně.<o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Poslední sezóny se dost 
často stává, že nějaký tým, který byl na podzim vysloveně špatný během jara 
vyletí nahoru. Ostatně i my sami jsme něco podobného zažili v&nbsp;sezóně 2017/2018 
kdy jsme po podzimu měli jen 10 bodů a na jaře jich získali 30. Uvidíme tedy, 
kdo se zapojí do bojů o postupové příčky, my dost pravděpodobně o postup hrát 
nebudeme </span><span lang="EN-US">;</span><span style="mso-ansi-language:
CS">). Naopak se nám snad podaří uhrát nějaké slušné výsledky hned na začátku 
jara, abychom si mohli v&nbsp;poklidu užít zbytek sezóny a potěšit tak naše věrné 
fanoučky nějakou tou další vítěznou děkovačkou. <o:p></o:p></span></p>
<p class="MsoNormal"><span style="mso-ansi-language:CS">Doufám též, že se podaří 
přes zimu rozšířit velmi úzký kádr, protože se mohou přihodit nějaká zranění a 
pak bychom mohli mít na jaře problémy.<o:p></o:p></span></p>
