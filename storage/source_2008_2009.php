<p align="left"><b>11.kolo Lučice 3:1 Sobíňov (1:0)<br>
náš gól: P.Bílek<br></b>
Zápas na půdě Lučice jsme si rozhodně představovali jinak. Nepovedlo se nám zachytit začátek zápasu a už jsme se do něj v podstatě nedokázali dostat.
Domácí šli velmi záhy do vedení po Michalově minele, kdy se při první střele ještě stačil vyznamenat Petr, na dorážku už však neměl nárok.
Nikdo z našeho týmu nedokázal vyburcovat mužstvo k lepšímu výkonu, domácí nás přehrávali agresivitou a důrazem, a jenom svou nepřesností v koncovce
se připravili o větší vedení ještě během první půle. Z naší strany nepřišla za celý první poločas v podstatě ani jedna povedená akce, takže ani není moc o čem psát.
Do druhého poločasu jsme po důrazné domluvě v kabině přišli s cílem výsledek zvrátit, bohužel jsme místo opět inkasovali po špatně rozehrané standardní situaci v blízkosti
velkého vápna domácích. Místo centru do vápna jsme ztratili míč, domácí přečíslili naši obranu a bylo to 2:0. Z inkasovaného direktu jsme se nedokázali vzpamatovat, 
uklidnění domácí v pohodě kontrolovali hru a náš gólman měl stále co dělat. Nebylo to však nic platné, neboť když dokázal fantasticky zneškodnit tutovku domácího útočníka,
který již mířil za něj do prázdné brány, tak jsme inkasovali z následného rohu po hlavičce nejlepšího domácího borce potřetí.V samotném závěru jsme už dokázali vstřelit alespoň jednu branku,
když se v závaru u domácí brány nejlépe orientoval Pája, ale to bylo víceméně vše. Po velmi nepovedeném výkonu a víceméně odchozeném zápase jsme tak po zásluze nechali všechny
body v Lučici, přičemž si nikdo si z nás za odvedený výkon nezaslouží pochvalu, snad kromě Petra, který zabránil ještě většímu přídělu v naší síti.</p>
