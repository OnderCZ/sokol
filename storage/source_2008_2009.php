<p align="left"><b>12.kolo Sobíňov 3:3 Leština (1:2)<br>
naše góly: Z.Němec, P.Bílek, M.Ondráček<br></b>
Utkání dvanáctého kola začalo naším náporem. Prvních patnáct minut jsme dokázali soupeře přehrávat a výsledkem byl i vedoucí gól Rena, který po sólu chladnokrevně překonal 
gólmana hostí. Tento gól přinesl do hry spoustu emocí, neboť hosté se při něm vehementně a možná i správně dožadovali odpískání ofsajdu. Rozvířených emocí jsme mohli rychle
využít k navýšení náskoku, před Bejkem se však míč ve stoprocentní šanci utopil v louži vody a Madri z blízkosti netrefil bránu. Přišel tedy trest, po rohovém kopu jsme 
inkasovali vyrovnávací gól, a o deset minut později po dalším rohu další gól. V posledních čtyřech zápasech jsme tak dokázali inkasovat po rozích 4 branky a to pro nás rozhodně není lichotivá vizitka.
Inkasované branky nás logicky rozhodily, a do poločasu jsme již nebyli schopni jakkoli zareagovat, první půle tedy skončila vedením Leštiny 2:1. <br>
Druhá půle byla z naší strany o dost lepší, začali jsme konečně předvádět fotbal, na který jsou naši příznivci zvyklí. Hostům začali jakoby docházet síly, stále více se uchylovali
pouze k nakopávání dlouhých míčů, které jsme dokázali v pohodě sklepávat a ihned je vracet před hostující bránu. První část druhého poločasu však přesto skončila gólem v naší síti,
David trošku podcenil souboj u postranní čáry a útočník hostí se posléze zpoza vápna nechytatelně trefil a zvýšil tak vedení hostů na dva góly. Naštěstí nás tento gól nesrazil a soupeře jsme naopak
ještě více přitiskli k jeho vápnu. Výsledkem naší snahy bylo několik slibných standardních situací a rohů, stále jsme však nemohli překonat gólmana hostí. Tou dobou už hosté znatelně nestíhali 
naše tempo a soustředili se na bránění výsledku. Naštěstí se jim to nevyplatilo. Nejprve si Pája ideálně naběhl za obranu, po Cafuově centru si zpracoval míč a chladnokrevně na vzdálenější tyč
zakončil-2:3. O chvíli později přistál po špatném výhozu hostujícího gólmana míč u Dana, ten ho posunul na Bejka, který dalším nádherným centrem našel přesně nohu Madriho, pro kterého již nebylo problémem
čtyři minuty před koncem zápasu vyrovnat. Hosté byli v té chvíli na ručník, a poslední hřebířek jim mohl zasadit Dan. Po rychlé kombinaci šli v podstatě tři naši hráči na jednoho beka, Reno(Bejk?) předložil Danovi,
který ovšem nedokázal tváří v tvář prostřelit gólmana hostí. Odražený míč pak chvilku poskakoval osamocen po malém vápně, ale nikdo z našich hráčů se k němu nedokázal dostat včas a tak zápas skončil remízou.
Po dobrém začátku zápasu jsme si tak vlastní laxností při bránění nebezpečných standardek soupeře málem prohráli zápas, naštěstí jsme ho ve druhé půlce stačili po zlepšeném výkonu alespoň zremizovat a moc
nechybělo k tomu, abychom ho dovedli i k vítězství. Z výsledné remízy na okresní poměry kvalitního utkání jsou tak asi nakonec mírně nespokojeni oba soupeři, neboť Leština promarnila dvoubrankové vedení a nám k tříbodovému zisku jeden gól chyběl.</p>
