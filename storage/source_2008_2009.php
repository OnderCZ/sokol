dovést k remízovému konci. Konečnou remízu 1:1 tak asi nakonec brali obě 
mužstva, my jsme byli spokojeni hlavně s prvním poločasem a s tím, že jsme 
dokázali v závěru ubránit alespoň onen bod, hosté myslím také neodjížděli 
smutní, bod z venku je dobrý začátek sezóny, a spokojeni byli snad i diváci, 
kteří si mohli užít vcelku zajímavého fotbalu bez nějakých záludností, oplácení 
a hrubých faulů, k čemuž zajisté přispěl i hlavní rozhodčí zápasu.</p>
