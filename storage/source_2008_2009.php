<p align="left"><b>10.kolo Sobíňov 3:1 Přibyslav "B" (1:0)<br>
naše góly: P.Kafka, M.Ondráček, D.Říčan PK<br></b>
Do zápasu s rezervou Přibyslavi jsme vstoupili velmi dobře a témeř celý první poločas jsme předváděli velmi dobrý fotbal,
kterým jsme dost často dostali obranu hostí do úzkých. Kombinovali jsme po zemi, zdobil nás rychlý přechod do útoku a pohyb s míčem i bez něho.
Celá dobře hrající obrana spolehlivě odebírala míče při sporadických útocích hostí, velmi dobře zahrál zejména David na jejím pravém okraji.
Bohužel se nám nedařilo proměňovat vypracované šance. První dvě měl na noze Pája, poprvé mu však tváří v tvář gólmanovi míč odskočil příliš daleko od nohy
a podruhé nedokázal dostat míč zblízka do sítě ani v okamžiku, kdy již gólman pouze bezmocně přihlížel z polohy vleže.
V samostatném úniku po rychlé rozehraném autu neuspěl Reno a chvíli poté hlavičkoval z vyložené pozice po výborném centru Madri nad. Naštěstí se nám přeci
jenom podařilo skórovat v samotném závěru první půle. Po Vikiho rozehrávce se k míči dostal Dan, krásnou přihrávkou našel za obranu nabíhajícího Cafua
a ten konečně překonal přibyslavského gólmana.<br>
Druhá půle začala lehce vlažněji. Hosté se rozhodli se zápasem něco udělat, zlepšili pohyb a naše obraná fáze najednou nebyla z nejpřesvědčivějších.
