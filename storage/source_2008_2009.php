lepším týmem, hrozili především ze standardních situací, které jsme nedokázali 
účinně odvracet. Vychýlená muška domácích střelců a spolehlivý výkon Petra 
Veselého v naší bráně však zapříčinily to, že se žádný míč nedostal až do naší 
sítě. První varování pro domácí přišlo z levé strany, kde se probil Pája, 
předložil míč Renovi, ale ten ve své první velké šanci těsně minul pravou tyč 
domácí svatyně. Ve dvacáté páté minutě tak uštědřil domácím první ránu Vlasta. K 
míči se po dlouhém autu dostal Dan, kličkou se zbavil obránce a z brankové čáry 
předložil před prázdnou bránu gólovou nabídku, kterou Vlasta nepohrdl. Vstřelená 
branka nás uklidnila, přestali jsme soutěžit s domácími o to, kdo nakopne míč do 
