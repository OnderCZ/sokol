<p class="MsoNormal"><b>25.kolo Leština 3:2 Sobíňov (3:1)<br>
naše góly: T.Štěrba, V.Němec<br>
</b>Po prvních deseti minutách zápasu předposledního kola jsme opět vypadali na 
ručník. Totálně zaspaný začátek, dva rychlé brejky domácích, které jsme nebyli 
schopni včas zastavit a prohrávali jsme 2:0. Nebylo to na jaře poprvé, co jsme 
se začali takto špatně, stále se nejsme schopni poučit z&nbsp;vlastních chyb. Do 
zápasu nás pak vrátil Tomáš, který po Jarinově přihrávce „povodil“ soupeřova 
obránce a krásnou ranou z&nbsp;nějakých pětadvaceti metrů vyhnal pavouky ze šibenice 
domácí brány. Hlavně v&nbsp;prvním poločase se hrál i za horkého počasí celkem svižný 
fotbal, k&nbsp;čemuž přispívali zejména domácí hráči, kteří nás díky svižnému pohybu 
často přečíslovali ve středu hřiště a vytvářeli si i nadále větší množství 
nebezpečých situací. Paradoxně největší šanci měl ovšem na kopačce opět Tomáš, 
který vypíchl míč chybujícímu bekovi, a pak zkoušel přehodit vyběhnuvšího 
gólmana, který mu již padal pod nohy, ten však stačil rukou střelu zblokovat i 
za cenu menšího zranění, které při zákroku utrpěl. Toto zranění poskytlo chvilku 
oddychu jak nám, tak soupeři, hlavním aktérem všeho dění se však na chvíli stal 
domácí laický pomezní, který neunesl kombinaci požitého většího množství 
alkoholu a ostrého Slunce a při ošetřování gólmana se málem také zranil při svém 
nekontrolovatelném pádu při pokusu přelézt zábradlí. Po ošetření gólmana a 
vystřídání pomezního rozhodčího se pokračovalo v&nbsp;prvním poločase v&nbsp;obdobném 
duchu, domácí se navíc po dalších zmatcích v&nbsp;naší obraně, kdy jsme jim dovolili 
střelu z&nbsp;nebezpečné pozice a posléze i dorážku, opět dostali do dvougólového 
vedení.<br>
V druhém poločase se již na obou mužstvech začala objevovat únava, u nás 
násobená tím, že jsme neměli nikoho na vystřídání a tak třebas Pepa dohrával 
posledních 15 minut s&nbsp;křečemi. Obě mužstva ztrácela množství míčů vlastními 
chybami, nepřesnými přihrávkami apod., domácí byli ale stále nebezpečnější a 
Petr se v&nbsp;naší bráně musel několikrát vytáhnout se skvělým zákrokem, aby nás 
udržel ve hře o body. My jsme si vytvořili několi slibných závarů, ale kýžený 
gól přišel z&nbsp;nenápadné akce- po levé straně se krásně individuálně uvolnil Pepa, 
který pak nacentroval míč před bránu, kde se nejlépe zorientoval Vlasta a 
hlavičkou(!) snížil na 2:3. Domácí znatelně znervóznili, a když Cafua sklepával 
Tomášův aut před zcela opuštěnou bránu, chyběly Jarinovi snad 2 kroky, aby 
pohodlně skóroval do prázdné brány. Největší naší šanci však spálil Cafua, který 
získal míč u našeho velkého vápna, předal ho Renovi, který ho zatáhl až před 
vápno domácích a tam ho vrátil do gólové pozice- gólman však stejně tak jako 
v&nbsp;prvním poločase dokázal rukou střelu zblokovat a odražený míč poslali obránci 
do bezpečí. Leština pak spálila množství příležitostí v&nbsp;době, kdy už jsme zcela 
otevřeli hru ve snaze alespoň vyrovnat, ale další branku už se nikomu vstřelit 
nepodařilo a tak jsme opět prohráli o jeden gól, tentokráte 2:3. Potkala nás tak 
další víceméně zbytečná bodová ztráta, způsobená zejména špatným vstupem do 
zápasu a nevyužitím šancí v&nbsp;poločase druhém.</p>
