<p align="left"><b>12.kolo Světlá n.S. "B" 1:2 Sobíňov (1:1)<br>
naše góly: P.Kafka, Z.Němec<br></b>
Naše poslední podzimní utkání se hrálo za nádherného slunečného počasí na lehce mokřejším ale jinak velmi dobře připraveném a velmi rozlehlém světělském trávníku.
Zpočátku se oba týmy spíše oťukávali, domácí i my se snažili dostávat dopředu hlavně kombinacemi po zemi. Ostatně k tomu pravděpodobně největší hřiště v naší soutěži přímo 
vybízí,neboť je na něm hodně prostoru. Hrál se tedy celkem zajímavý fotbal, a přihlížející diváci se rozhodně nenudili. Přicházeli i šance, a to na obou stranách, 
domácí hrozili především po standardkách, my se dostávali na dostřel domácí brány ze hry. Ve čtrnácté minutě jsme inkasovali jako první, Vaska se před tři hráče nedokázal dostat 
ke střílenému centru před naší bránu a míč tak skončil až za jeho zády. Naštěstí bylo už o minutu později vyrovnáno. V podstatě ihned po rozehrání byl faulován Pája, k míči se 
postavil Bejk a přesným centrem našel hlavu nabíhajícího Cafua, který se k míči dostal dřív než domácí gólman- 1:1. Ve zbytku prvního poločasu jsme si pak dokázali vytvořit 
několik dobrých střeleckých pozic na úrovni velkého vápna, ale většina takových pokusů bohužel míjela bránu. Nejblíže ke vstřelení vedoucího gólu byl Pája, který po narážečce s 
Bejkem jenom těsně minul pravou tyč brány a Dan, který po zahraném signálu z rohu z dobré pozice bránu přestřelil.<br>
Druhý poločas jsme trochu nepochopitelně začali hrát trošku zataženěji, než by bylo vhodné, a domácí se tak dostávali velmi často do našeho velkého vápna. Hodně situací naštěstí 
vyřešila naše obrana, pár slibných akcí zazdili sami domácí hráči a tak jsme toto hluché období přestáli bez pohromy v naší síti. Dopředu jsme se dostávali hlavně díky rychlému přechodu do útoku, ale většina akcí končila nepřesnou finální přihrávkou nebo střelou kamsi k rohovému praporku. Velkou šanci jsme si tak připravili až zhruba 20.minut před koncem- Cafua přebral na půlce míč, rychle se s ním dostal až k velkému vápnu domácích, tam si narazil s Madridem a ocitl se tak v té chvíli úplně sám před gólmanem domácích. 
Velmi dlouho však zpracovával míč, a vyběhnuvšího gólmana pak už nedokázal z blízkosti prostřelit. Domácí žádnou vyloženou šanci neměli, Vaska v poklidu kontroloval vysoké míče do vápna a tak už vše pomalu směřovalo k remízovému závěru. S tím jsme se však nechtěli smířit, stále jsme pokračovali ve snaze vstřelit rozhodující gól a to se nám nakonec také vyplatilo. Nejprve se po vystřídání Madriho na hřišti objevil David, který mohl skórovat v podstatě z prvního kontaktu s míčem, ale jeho šanci překazil správně zvednutý praporek pomezního rozhodčího. V devadesáté minutě už ovšem přišlo rozhodnutí- Bejk krásnou nahrávkou našel za obranu nabíhajícího Rena, který udělal kličku gólmanovi a z velkého úhlu pak dokázal trefit odkrytou bránu. Domácí se poté zmohli v závěrečném náporu na jednu nebezpečnou standardní situaci, při které jeden z útočníku jenom těsně minul naší bránu, ale vyrovnat už nedokázali. V posledním zápase první půlky sezóny 2008/2009 jsme tak ukořistili tři důležité body, které nám zajistili 
přezimování na výborném čtvrtém místě tabulky Okresního přeboru.</p>
