<p class="MsoNormal"><b>24.kolo Sobíňov : Lučice 0:1 (0:1)<br>
</b>Dvacáté čtvrté kolo letošního Okresního přeboru nás zastihlo na šestém místě 
tabulky a pokud jsme se na něm chtěli udržet, museli jsme porazit Lučici. Dalším 
motivem pro nás mělo být to, že jsme u nich na podzim prohráli 2:1 a tak jsme 
chtěli porážku vrátit.<br>
Zápas však začal úplně jinak, prvních dvacet minut patřilo pouze hostům, kteří 
dokazovali, proč patří v&nbsp;jarní části soutěže k&nbsp;nejlepším týmům. Byli jasně 
lepší, vytvářeli si standardní situace a po jedné z&nbsp;nich se dostali do vedení, 
když rozehráli rohový kop na sbíhajícího střelce, jehož rána prošla chumlem 
hráčů a po teči skončila v&nbsp;levé šibenici naší brány. My jsme se vůbec 
nedostávali do hry, a až s&nbsp;postupem času a snad i s úbytkem elánu hostí se nám 
to pomalu začalo dařit. Výsledkem byly dvě slibné příležitosti, při které 
nejprve zachránil hosty včasným vyběhnutím gólman, který tak překazil po 
nádherné Jarinově přihrávce gólovou šanci Cafuovi a posléze stejným způsobem, po 
další přihrávce ze středu hřiště, znemožnil zakončení i Renovi. Nutno říci, že i 
hosté měli další šance, výborně si určitě zachytal Vaska, který musel mnoho 
nebezpečných střel vyrážet z&nbsp;prostoru mezi tyčemi s&nbsp;vypětím všech sil a jednou 
či dvakrát nám pomohla i branková konstrukce.<br>
První poločas končil pod hustými kapkami deště a v&nbsp;začátku půle druhé přívaly 
vody ještě zesílily. Déšť však přinesl aktivitu spíše na naše kopačky, hosté se 
přeci jenom už tolik dopředu nehonili a spíše se soustředili na hlídání výsledku 
a na to, aby na zrádném terénu nevyrobili hrubku. Prvních dvacet minut bylo 
ještě oboustranně trochu vlažnějších, poté jsme si však začali pomaloučku 
vytvářet převahu, která sílila s&nbsp;blížícím se koncem zápasu. Domácí diváci se 
v&nbsp;jedné chvíli hodně zlobili na pomezního rozhodčího, který odmával hodně sporný 
offside Renovi, který v&nbsp;tu chvíli šel sám na gólmana a o chvíli později 
nevěřícně sledovali, jak se dá spálit tutová šance. Jarin si vyměnil míš s&nbsp;Cafuem, 
jeho centr sklepl Tomáš Vlastovi, který však úplně sám na malém vápně zamířil 
přesně do středu brány, kde stál připravený brankář hostí. Hosté v&nbsp;tu chvíli 
přestáli naši zřejmě největší šanci a vycítili, že je potřebas zkusit i 
zaútočit, jinak budou jejich body v&nbsp;ohrožení. Výsledkem jejich snahy byla šance, 
