<p align="center"><b><font size="5">Sezóna 2008/2009, Okresní přebor</font></b></p>
<p><b>Zhodnocení sezóny:<br>
</b>Podzimní začátek sezóny byl poznamenán mnoha změnami. Před sezónou došlo ke 
střídání na pozici trenérů, Milan Potůčka a Karla Bílka vystřídal Zdeněk 
Wasserbauer, který též přivedl novou akvizici do naší brány- Petra Veselého. 
Prvních šest kol jsme byli oslabeni o dva obvyklé základní stavební pilíře, tedy 
o Járu a Marka, navíc nás sužovala neobvyklá série zranění a nemocí, přesto jsme 
dokázali uhrát velmi slušný počet bodů. Díky patří hlavně hráčů, kteří již 
obvykle tolik nehrají a kteří pomohli, když nám bylo nejhůř: Petrovi Kodýmovi 
jakožto specialistovi na Ledeč, Luďkovi Hamerníkovi, Milanovi Kučerovi a v 
neposlední řadě samozřejmě našemu ex-trenérovi Milanovi Potůčkovi. Schválně jsem 
vynechal naší další velkou posilu- Davida Vránu, který se po několikaleté odmlce 
vrátil zpátky do aktivního fotbalového života a všichni určitě doufáme, že v 
této fázi ještě dlouho vydrží. Po vysoké porážce ve Ždírci následovaly důležité 
výhry nad Veselým Ž’dárem, otočený zápas v Keřkově, výhra nad Přibyslaví a v 
posledním zápase i výhra na půdě Světelské rezervy. Hlavně tyto výsledky nás 
posunuli na výborné čtvrté místo.</p>
<p>Na jaře už to s našimi výsledky tak 
oslnivé nebylo, oproti podzimním 24bodům jsme jich na jaře uhráli pouze 16. 
Velká škoda zranění klíčových ofenzivních hráčů, neboť v podstatě hned na 
začátku jara se zranili postupně Madri, Pája a Reno, a nějaké ty šrámy se 
nevyhnuly ani dalším hráčů. Z toho posléze vyplývaly nutné časté zásahy do 
sestava a mockrát se nám nestalo, že bychom mohli nastoupit dvakrát po sobě ve 
stejné sestavě (možná že se tak nestalo dokonce nikdy :) ). Kromě hostování Pepy 
Motla z Chotěboře se nám ztráty nepodařilo dalšími hostováními dorovnat a tak 
jsme se nakonec museli spolehnout na pomoc hráčů, kteří již byli pomalu členy &quot;old 
boys Sobiňov&quot;. Ještě že jsme vždy našli ochotné náhradníky, kteří neváhali a 
když bylo potřeba, přijeli nám se sestavou pomoci, díky jim všem ještě jednou.<br>
I tak jsme ale několik zápasů ztratili zcela zbytečně, ať už vlastními chybami, 
prachbídnými vstupy do utkání či třebas špatným přístupem k zápasům jako 
takovým. Bodů jsme rozhodně i přes utržené ztráty mohli a hlavně měli uhrát víc, 
hráčská a fotbalová kvalita na to v mužstvu určitě je. Až díky kanonádě v 
posledním zápase jsme se dostali do kladného rozdílu mezi vstřelenými a 
obdrženými brankami&nbsp; (v sezóně 07/08 jsme měli 71:47) a obraná činnost je 
asi hlavní oblastí, ve které nás takříkajíc &quot;tlačí bota&quot;.</p>
