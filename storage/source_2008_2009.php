tohoto &quot;snažení&quot; tak do konce zápasu byla červená karta pro jednoho z jejich 
hráčů, kterou dostal pravděpodobně za nadávky, ani při více jak pětiminutovém 
prodloužení si nedokázali vytvořit nějakou větší šanci kromě jedné hlavičky po 
jedné z mnoha standardních situací. My jsme zbytek zápasu odehrávali v úporném 
obraném sevření, snažili jsme se co nejvíce rozkouskovat hru&nbsp; dopředu jsme 
se již příliš netlačili. Přesto se do nadějné situace dostal po další Pájově 
rychlé akci Cafua, jeho možná trochu unáhlenou střelu však gólman domácích 
vyrazil na roh.<br>
V prvním jarním odehraném kole jsme tak v Havlíčkově Brodě díky bojovnému výkonu 
celého mužstva dokázali urvat tři velmi cenné body. Zejména za druhý poločas pak 
za pečlivě vystavenou a dodržovanou obranou taktiku zaslouží pochvalu nejen celá 
obraná čtyřka v čele s gólmanem&nbsp; ale i zbytek týmu, neboť pomoci směrem 
dozadu dokázali v mnoha situacích i oba hrotoví útočníci a to u nás dříve 
nebývalo zvykem.</p>
