<p align="left"><b>1.kolo Sobíňov 1:1 Ledeč nad Sázavou &quot;B&quot; (1:0)<br>
náš gól: P.Kodým</b><br>
Hned v prvním kole nového ročníku jsme narazili na nepříjemné béčko Ledče. V 
jeho řadách stále působí mnoho hráčů se zkušenostmi z vyšších soutěží, a tak se 
v zápasech s tímto soupeřem většinou hraje celkem zajímavý fotbal, neboť 
ledečská rezerva se snaží obvykle prosazovat rychlými přízemními kombinacemi. Ze 
zápasu jsme tak měli lehké obavy, neboť nám stále chybí Bejk s Madridem, jejichž 
anglické dobrodružství stále pokračuje a tak za nás museli do hry naskočit i 
hráči, kteří již kopačky obouvají spíše příležitostně. Zápas byl zároveň 
premiérou pro novou trenérskou dvojici, a tak jsme všichni čekali poměrně 
napjatě, jaký ten náš letošní první zápas bude. </p>
<p align="left">Po počátečním oboustranném oťukávání se začal hrát na první kolo okresního 
přeboru myslím poměrně atraktivní rychlý fotbal z obou stran, který se jistě 
musel líbit celkem početnému obecenstvu. Hosté drželi míč více na svých 
kopačkách, zkoušeli vytáhnout naši obranu rychlými kombinacemi a pak se pokusit 
rychlou přihrávkou dostat za záda našich beků. My se spoléhali spíše na pozorné 
a důsledné bránění, ze kterého jsme chtěli vyrážet do rychlých kontrů. Tato 
taktika se nám celkem dařila, v prvním poločase jsme nepouštěli hosty až na 
výjimky do vážnějších střeleckých pozic, a sami jsme si naopak vypracovali 
několik nadějných příležitostí. Svou pohyblivostí na hostující obranu platili 
zejména Reno a Pája, zatímco znovunavrátivší se Koďas spoléhal spíše na svůj 
výborný výběr místa. Výsledkem naší snahy bylo poměrně velké množství nadějných 
střeleckých příležitostí z přímých kopů, kterých jsme snad pět zahrávali v těsné 
blízkosti velkého vápna. Bohužel, neujala se z nich ani jedna střela, většinou 
jsme pouze zabušili do hostující zdi. Po jedné z našich útočných akcí, která 
skončila u hostujících obránců však přišla naše chvíle- hosté o míč velmi rychle 
opět přišli na půlce hřiště, Pavel Bílek potáhl míč dopředu, přihrávkou našel v 
křídelním prostoru zcela zapomenutého Cafua a ten z první levačkou posadil míč 
přesně na hlavu výborně naběhnuvšího si Kodýma, který poté s troškou štěstí 
protlačil míč až za záda hostujícího gólmana. Petr tak potvrdil svou pověst 
specialisty na Ledeč, neboť i loni nám proti tomuto soupeři vypomáhal a i tehdy 
se dokázal gólové prosadit. Do kabin jsme tak šli se slibným jednogólovým 
vedením. </p>
<p align="left">Po změně stran se ještě zhruba 15minut hrál vyrovnaný fotbal, hosté byli ale 
