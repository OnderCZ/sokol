jinak velmi dobře prezentovali a začali spíše nakopávat dlouhé míče za naší 
obranu, což byla voda na náš mlýn. Po krásně rozehrané akci se v pětadvacáté 
minutě po levém křídle probil Pája, nehledal zbytečně nikoho ze svých spoluhráčů 
a tvrdou přízemní střelou překonal hostujícího gólmana podruhé. Poté jsme se 
trošku stáhli do obrany, přičemž jsme ovšem špatně obsazovali hbité hostující 
záložníky, kteří nám zle zatápěli zejména z naší levé strany. Několik dobře 
umístěných ran skvěle pochytal v mistrovském zápase v Sobíňově debutující Petr 
Veselý, ale ve 40.minutě už nedosáhl na dobře umístěný prudký centr z pravé 
strany, který hosté dokázali z první uklidit do naší brány. V poločase jsme tak 
vedli 2:1, přičemž nás ještě mrzela neproměněná šance Kodýma, který běžel od 
půlky sám na gólmana.</p>
<p align="left">Druhá půlka začala velmi kuriózním momentem, který se určitě 
