slibné gólové příležitosti, Kodýmova střela po dalším rozehraném přímáku minula 
pravou tyč o půl metru, Pájovi propadl nešťastně mezi nohama míč téměř na 
brankové čáře míč po skrumáži ve velkém vápně hostů, ale to bylo z naší strany 
víceméně vše. Hosté nás přehrávali, v jedné z největších šancí dokázal jejich 
útočník překopnout naší v podstatě prázdnou bránu včetně ochranného pletiva z 
malého vápna. Po přímém kopu zvonila levá tyč Vaskovi branky, míč dokázal po 
skrumáži odkopnout do bezpečí Michal, ale dvacet minut před koncem jsme již 
inkasovali poté, co jsme dali hostujícímu hráči dostatek času na hranici našeho 
velkého vápna- ten se neukvapil, připravil si míč a vyslal prudkou umístěnou 
střelu přesně za levou tyč naší brány. A i když si Vasil na míč stačil ještě 
sáhnout, znamenala tato střela vyrovnání na 1:1. Hosté poté ještě přidali, 
