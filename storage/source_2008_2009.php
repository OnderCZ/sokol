<p class="MsoNormal"><b>26.kolo Sobíňov 7:1 Světlá n.S. &quot;B&quot; (4:0)<br>
naše góly: T.Štěrba 3x, Z.Němec 3x, P.Kafka<br>
</b>To co se během jara několikrát povedlo našim soupeřům se tentokráte zadařilo 
nám a zápas posledního kola jsme dokázali rozhodnout již v jeho začátku. Hned ve 
třetí minutě si na Renův pas z pravé strany hřiště naběhl na bližší tyč Tomáš a 
zaskakující gólman hostů šel pro míč do brány poprvé. Za deset minut si podobnou 
situaci zopakoval znovu, to když se po akci tentokráte z levé strany prosadil 
poprvé v zápase Reno. Zápas jsme zcela kontrolovali, na zmoklém trávníku se 
dobře kombinovalo a to nám vyhovovalo, jelikož soupeři se zcela očividně 
nechtělo moc běhat. Když už se soupeř dostal na dostřel, podržel nás dvěmi 
skvělými zákroky náš gólman. Třetí gól tak přidal po nedorozumění stopera s 
gólmanem po Jarinově přímém kopu pohodlně hlavou Cafua a ještě do poločasu 
přidal svou druhou branku Tomáš, ke kterému se dostala Jarinova střelu po 
zahraném signálu. <br>
Druhá půle začala trochu vlažněji, zápas byl rozhodnut, my se nikam nehnali a 
rezerva Světlé neměla sílu a snad ani chuť něco zkoušet. Pár střel z větší 
vzdálenosti Petr v pohodě kryl, a vypadalo to, že hosté odjedou s prázdnou nejen 
v kolonce bodů, ale i v kolonce vstřelených branek. Asi by se nám onu nulu 
ubránit v poklidu povedlo, nebýt naší chyby při rozehrávce u vlastního velkého 
vápna, kdy si dva beci dávali tak dlouho přednost, až mezi nimi s míčem proběhl 
hostující útočník, kterého se jakožto poslední instance musel snažit zastavit 
Hagi. Rozhodčí poté viděl v souboji na hraně pravidel faul našeho stopera a tak 
se hosté z penalty dočkali alespoň optické korekce výsledku. Inkasovaná branka 
nás konečně trochu probrala a soupeře jsme opět dostali pod tlak, výsledkem byly 
dva dokonalé hattricky, které si mezi sebe rozdělili naši dva útočníci a 
množství dalších šancí, jejichž neproměnění jsme ovšem tentokráte nemuseli 
příliš litovat... Po naší sedmé brance tak rozhodčí zápas raději ukončil, aby se 
zdeptaný soupeř už nadále netrápil...<br>
Díky svižnému a povedenému začátku jsme tak sezónu zakončili naší největší 
výhrou.</p>
