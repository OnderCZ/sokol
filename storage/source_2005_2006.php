<p align="left"><u><b>Shrnutí jara 2006:<br>
</b></u>Do jarních odvet zápasů jsme vstupovali s rozporuplnými pocity. Věděli 
jsme, že případný postup máme ve svých rukách a že je tak jen na nás, jestli si 
ho zasloužíme. Po výborných přátelských utkáních, které jsme odehráli v rámci 
zimní přípravy jsme odjížděli do Vepřové, neboli do místa našeho prvního jarního 
mistrovského zápasu,&nbsp; s vcelku pozitivními očekáváními. Tyto pozitivní 
pocity ještě zesílily poté, co jsme tam dokázali zvítězit. Hned ve druhém jarním 
kole ale přišla studená sprcha, když jsme i díky dvěma neproměněným penaltám 
nedokázali doma porazit Libici. Naštěstí to nijak neohrozilo náš náskok na čele 
tabulky, neboť nejbližší pronásledovatel z Herálce také zaváhal a rozdíl na čele 
tabulky tak zůstal nezměněn. Po tomto varování jsme však započali suverénní 
jízdu jarní částí sezóny, kdy jsme většinu soupeřů přehrávali a většinou jsme si 
v poklidu dokráčeli pro tři body. Naše nejlepší výkony pak přišly asi v zápasech 
v Nové Vsi a poté doma s Velkou Losenicí, kdy jsme pokaždé dokázali zvítězit o 
pět branek. Vzhledem k ostatním výsledkům měl přijít vrchol jara v podobě zápasu 
s Herálcem<span lang="en">&nbsp;</span>&quot;B&quot;, na který jsme se všichni těšili, neboť 
jsme jim chtěli doma vrátit naší porážku z podzimního zápasu. Bohužel, herálecké 
béčko k nám nedorazilo a tak jsme slavili postup díky kontumační výhře 3:0. Po 
již zmíněném zápase s Velkou Losenicí přišla již jen povinná výhra v Mírovce a 
poté v posledním kole trošku kyselá tečka v podobě remízy s Českou Bělou, která 
nám již však nemohla zkalit radost z našeho postupu do vyšší soutěže.<br>
<br>
Teď si dovolím malý podvůdek a v podstatě sem zkopíruji celý odstaveček, který 
jsem psal už na konci podzimního shrnutí, ale myslím, že i tady má své místo... Budu teď asi  psát za všechny hráče našeho týmu, když na tomto místě 
poděkuji všem našim skvělým fanouškům, kteří nás dokázali celou sezónu skvěle 
podporovat a to nejen na hřišti domácím, ale i na hřištích cizích, kam vyjížděli 
v opravdu hojném počtu- ještě jednou velké<br></p>

