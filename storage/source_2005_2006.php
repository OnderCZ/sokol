když postup už máme v kapse a nikdo nám ho nevezme. Zápas jsme začali slušně a 
hned ve čtvrté minutě jsme šli do vedení, když se obranou hostí probil Reno a 
Madrid následně nezaváhal. Po začátku, během něhož kterém působila obrana hostí 
dost chaotickým dojmem, se hra trochu vyrovnala a hosté se pomocí krátkých 
kombinací dokázali dostávat až k blízkosti naší brány. Velkou část jejich akcí 
však dokázala zastavit naše obrana a když se jim podařilo dostat se až do 
přímého zakončení, byl vždy na místě skvěle chytající Vaska. Takže jsme to byli 
my, kteří vstřelili druhý gól- Bejk doklepával z brankové čáry míč po Madridově 
akci a ještě do poločasu se nám podařilo přidat po jedné ze standardních situací 
i gól třetí-a tentokráte to byl&nbsp; Madrid, který z bezprostřední blízkosti 
překonal hostujícího gólmana potřetí.<br>
Ve druhé půli jsme již byli oproti poločasu prvnímu výrazněji lepším týmem, 
hosté se na naši polovině moc neobjevovali a když už tam nějaký míč přilétl, 
vcelku brzy se již pohyboval v blízkosti jejich pokutového území. A když jsme 
přidali další uklidnění na naše kopačky díky gólům Rena a Bejka, bylo o zápase 
rozhodnuto. Navíc jsme si ještě neodpustili náš obvyklý luxus v podobě dalších 
neproměněných brankových přííležitostech- po střele Cafua se míč otřel o levou 
tyč a odražený míč nedokázal do brány vrátit Madrid, a neúspěšný střelec z 
předchozí situace pak sám naprosto neuvěřitelným způsobem přestřelil z malého 
vápna úplně prázdnou bránu po skvělé akci Padíla. Díky výbornému výkonu celého 
mužstva jsme tedy porazili Losenici o pět branek, což je výsledek velmi 
potěšitelný už z toho hlediska, že Losenice předváděla z našich protivníků v 
jarní části soutěže nejlepší výkon a výsledek je pro ní asi až moc krutý. 
Výbornými výkony se vytáhli zejména Vaska, který s přehledem dokázal vyřešit 
několik velmi ošemetných situací, Reno, který dělal svým pohybem a napadáním 
soupeřovým obráncům velké potíže a samozřejmě také oba dvougóloví střelci- Madri 
s Bejkem. Trochu tmavší kaňkou na celém zápase je pak zranění Kopčema, který si 
při jednom ze soubojů něco udělal s kolenem(podle posledních zpráv natažené 
možná i přetrhané vazy v koleni, při prvním ošetření se to nedalo poznat) a je 
tak pravděpodobné, že jsme minimálně pro poslední dva jarní zápasy přišli o 
dalšího hráče.<br>
