<p><b>11.kolo 23.10. Herálec &quot;B&quot; 3:1 Sokol Sobíňov (2:0)<br>
náš gól:  J.Ondráček(PK)<br>
</b>Do utkání posledního kola podzimní části jsme nastupovali s jasným cílem- 
udržet před heráleckým béčkem a Vepřovou náš pětibodový náskok, nebo ho ještě 
vylepšit. Hned po příjezdu se ukázalo, že to nebude lehké, neboť domácí se velmi 
posílili hráči a-týmu, který hraje I.A. třídu. Z mužstva, které jsme viděli hrát 
o týden dřív v Rozsochatci tak na trávníku byli snad 3 hráči. Úvod utkání také 
nasvědčoval tomu, že si body z Herálce pravděpodobně neodvezeme, neboť jsme po 
20.minutách po hrubých chybách v obraně prohrávali 0:2. I přes podporu našich 
skvělých fanoušků, kterých za námi dorazilo hodně, jsme totiž celé utkání začali 
zbytečně nervózně a ustrašeně, čehož zkušenější domácí tým dokázal využít. 
Postupem doby se začal obraz hry trochu změnit, a byli jsme to my, kteří se více 
tlačili do útoku a dostávali se do situací, které zaváněli poměrně velkým 
ohrožením domácí branky. Zvláště série několika přímých kopů z pravé strany 
volala po alespoň jednom gólovém úspěchu. Domácí naopak nikam nespěchali, s 
vědomím dvoubrankového nástupu se nijak přehnaně netlačili dopředu a víceméně 
čekali, co se zápasem provedeme. Do konce poločasu se nám branku vstřelit 
nepodařilo a jelikož se při další velké šanci domácích blýskl skvělým zákrokem 
Vaska, šlo se do kabin za stavu 0:2 v náš neprospěch.<br>
Druhá půle začala v podobném duchu jako skončila ta první, s tím rozdílem, že 
jsme byli dle mého mínění většinu druhé pětačtyřicetiminutovky lepším a 
aktivnějším týmem. Po spálení několika dobrých šancí, ze kterých nás nejvíce 
mrzí zejména neproměněná šance Rena, který šel po dlouhém Vaskově 
výkopu(prodlouženého Marínovou hlavičkou) sám na domácího brankáře. Bohužel, 
jeho střela se nevešla mezi tyče domácí svatyně. Do utkání jsme se tak vrátili 
až po penaltovém zákroku na Waru, který trestal Bejk chladnokrevně proměněnou 
penaltou- 1:2. Domácí v té chvíli začali trochu zmatkovat, my jsme se je naopak 
snažili přitlačit do vápna a vstřelit tak vyrovnávací branku, která by nám 
zajistila alespoň kýžený bod. Bohužel, několik nadějných situací jsme &quot;zazdili&quot; 
sami, několik dalších zmařila vcelku pozorně hrající domácí obrana a tak se nám 
to nepodařilo. Naopak jsme sami v samotném závěru po brejku domácího mužstva 
inkasovali branku na konečných 1:3.<br>
