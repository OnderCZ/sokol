diskutabilních rozhodnutích hlavního rozhodčího dostali hosté šanci rozehrávat 
přímý kop z hranice šestnáctky a přesnou střelou k tyči nedali Vaskovi šanci- 
vyrovnáno, 1:1. Naštěstí se neodehrálo ani deset minut a na druhé straně byl v 
pokutovém území faulován Reno, a Bejk posléze penaltovou nabídku využil. Dostali 
jsme se tak do vedení. Přes několik dalších sporných momentů, kdy se na 
rozhodčího střídavě hněvali obě mužstva, se stav utkání už do konce utkání 
