	<strong>Zhodnocení sezóny 2016/2017</strong></p>
	<div class="auto-style23">
		Pátá sezóna ve třetí třídě byla pro Sobíňov rozporuplná. Stejně jako na 
		podzim se totiž nevyvedl konec jarní části sezóny a celkem 
		příjemné postavení v tabulce se tak na konci soutěže zhoršovalo. Po 
		podzimu patřila Sobíňovu osmá příčka v tabulce, a stejného umístění 
		dosáhl nakonec i po jarní části. K podzimní sedmnácti bodům jsme totiž 
		na jaře přidali patnáct a tak se nějaké velké posuny tabulkou nedaly 
		čekat. <br />
		<br />
		Hned na začátku jara nás povzbudila důležitá výhra na Malčí (3:0), 
		remízové zápasy doma s Novou Vsí u Světlé (3:3) a v Leštině (1:1) byly 
		pro nás spíše ztrátou. Asi nejdůležitější a také nejvíc utrápenou těsnou 
		výhru přinesl zápas v Jeřišně (1:0). Následovala domácí demolice rezervy 
		Věžnice (8:1) a hodně těsně ubráněná remíza ve Vísce (2:2). Uklidnění do 
		poslední kol přineslo vítězství nad Dolním Městem v poměru 2:1. Tou 
		dobou jsme se dokonce objevili na čtvrtém místě tabulky. Ale pak už to 
		byl jen zmar- nejdříve přišla těsná porážka v&nbsp;Havlíčkově Borové (2:3), 
		dvě následující prohry s Havlíčkovým Brodem &quot;C&quot; (0:3) a Hněvkovicemi 
		(0:2) se asi daly čekat, že ale nevydolujeme ani bod se zápasů s Českou 
		Bělou (0:2) a ve Šlapanově (0:1) už bylo pro nás zklamáním. Pět 
		posledních zápasů v&nbsp;řadě jsme tak prohráli a navíc jsme posledních 403 
		odehraných minut nevstřelili branku. <br />
		<br />
		Proti minulé sezóně jsme si tak nakonec pohoršili ve všech hlavních 
		ukazatelích- v tabulce jsme o tři místa níže, získali jsme o šest bodů 
		méně, vstřelili jsme o čtyři branky méně a dostali jsme o čtyři branky 
		navíc.<br />
		<br />
		<img alt="3 třída přehled" height="149" src="../obrazky/3trida_prehled.png" width="324" /><br />
		<br />
		Při zpětném pohledu bych řekl, že to umístění cca odpovídá současnému 
		rozpoložení týmu. K posunu do vyšších pater tabulky nám chybí to, 
		abychom dokázali pravidelně nastupovat v co možná nejsilnější sestavě a 
		zároveň to, abychom dokázali hrát fotbalově větší části zápasu. Většinou 
		totiž docházelo k tomu, že s tím jak nám docházely síly, horšila se i 
		předváděná hra. Díky většímu počtu náhradníků se sice nestávala tak jako 
		loni, že by se na zápasy jezdilo v jedenácti lidech, ale stále více a 
		více je znát nedostatek mladých a především běhavých hráčů :). <br />
		<br />
		<span class="auto-style1">Postupy a sestupy</span><br />
		Letos se i na administrativní úrovni událo mnoho změn, a tak je seznam 
		postupů a sestupů poměrně obsáhlý- v příštím ročníku se tedy ve 
		III.&nbsp;třídě potkáme hned se šesti novými celky oproti současné sezóně.<br />
		<br />
		Z okresního přeboru k nám sestupuje Veselý Žďár. Administrativně se do 
		naší soutěže přehlásil i tým Chotěboř &quot;C&quot;. Naopak do okresního přeboru 
		postupuje jako vítěz třetí třídy Havlíčkův Brod &quot;C&quot; a doplní ho 
		mimořádně mimo pořadí také Hněvkovice, Víska a Dolní Město. <br />
		<br />
		Do čtvrté třídy sestupují týmy Malče a Jeřišna. Ze čtvrté třídy 
		postupuje Rozsochatec &quot;B&quot;, Ledeč nad Sázavou &quot;B&quot; a mimo pořadí též týmy 
		Habry &quot;B&quot; a Kamenná Lhota. Na ty se dostalo díky tomu že postup odmítly 
		Kouty a Štoky &quot;B&quot;. <br />
