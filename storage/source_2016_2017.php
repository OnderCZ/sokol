	<strong class="auto-style23">Podzimní část sezóny 2016/2017</strong></p>
	<p class="auto-style23">Před 
	rokem jsem touto dobou psal o tom, jak fotbalový Sobíňov špatně začal 
	podzimní část sezóny a jak se podařilo větší počet bodů nasbírat až u jejího 
	konce. Letos to bylo přesně naopak- nejlepší začátek podzimu za poslední 
	roky, ucházejí střední pasáž a utrápená koncovka se čtyřmi prohrami v řadě.</p>
	<p class="auto-style23">Ale 
	vezmeme to pěkně popořadě. První tři kola podzimu přinesla Sokolu devět bodů 
	a úctyhodné skóre 13:0. Skvělou střeleckou efektivitu odnesli postupně 
	vysokými prohrami Šlapanov (5:0), Maleč (4:0) a Lípa &quot;B&quot; (4:0). Poté sice 
	přišla ve velmi oslabené sestavě vysoká prohra v Nové Vsi u Světlé n. 
	Sázavou (1:6), ale na dobrý začátek sezóny fotbalisté hned dokázali navázat 
	domácí výhrou nad Leštinou &quot;B&quot;, kde jsme sice herně lehce zaostávali, ale na 
	góly vyhráli 2:0. Domácí bezbranková remíza s tou dobou neporaženým Jeřišnem 
	ještě neznamenala žádnou velkou komplikaci, prohra na hřišti Věžnice &quot;B&quot; už 
	ale moc vhod nepřišla. Vísku jsme pak doma jednoznačně přejeli poměrem 5:1, 
	v Dolním Městě uhráli remízu 2:2 a se sedmnácti body jsme tou dobu okupovali 
	třetí místo tabulky. Největším podzimním &quot;průšvihem&quot; se pak ale stal domácí 
	zápas s rezervou Havlíčkovy&nbsp;Borové. Zápas jsme herně ovládali, během utkání 
	jsme šli snad pětkrát sami na gólmana a měli i další šance, ale poměrně 
	kuriózním gólem z předposlední minuty jsme nakonec prohráli 1:2. Deka z této 
	porážky na nás pak vydržela až do konce sezóny, kdy jsme nejdříve dvakrát 
	jasně podlehli lídrům tabulky s postupovými ambicemi- tj. &quot;C&quot; týmu 
	Havlíčkova Brodu a Hněvkovicím. V posledním kole jsme pak i přes zlepšený 
	výkon nestačili na Českou Bělou.</p>
