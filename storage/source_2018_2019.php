<p class="auto-style7"><strong>14. kolo Sobíňov 6:0 Šlapanov (2:0)<br />
</strong>střelci: 10. Zrzavý Tomáš, 45. Kafka Pavel, 51. Ondráček Marek, 58. 
Štěrba Tomáš, 83. Kučera Marcel, 85. Ondráček Jaroslav <br />
V posledním zápase sezóny jsme přivítali druhý tým tabulky ze Šlapanova. Hosté 
přijeli oslabeni o některé hráče a pouze v jedenácti lidech, takže od začátku 
tahali za kratší konec. Hned v desáté minutě jsme se dostali do vedení, když se 
po rohovém kopu sražená střela M.Ondráčka dostala k volnému Zrzavému a ten ji 
uklidil do sítě hostí- 1:0. Sobíňov byl více na míči, ale i hosté se dostali k 
dvěma nebezpečným situacím, kdy jsme lehkovážně ztratili míč u své šestnáctky a 
těžkými zákroky se musel blýsknout gólman Veselý. Nám se většinu prvního 
poločasu nedařilo dotahovat akce do nebezpečného konce a tak uklidnění do 
poločasové kabiny přinesla až další standardní situace, když po dalším rohovém 
kopu J.Ondráčka hlavičkoval přesně Kafka- 2:0.<br />
Když se nám navíc chvíli po začátku druhého poločasu podařilo náskok navýšit, 
bylo o osudu zápasu rozhodnuto. Hosté pak už rezignovali, směrem dopředu nebyli 
vůbec nebezpeční a jen se bránili. O třetí gól se hezkou akcí postaral Hečko, 
který přešel přes dva bránící hráče, a svou střelu pak namířil do tyče hostující 
brány- s dorážkou poté už neměl problém M.Ondráček- 3:0. Na čtyři nula zvyšoval 
po pěkné kombinaci na pravé straně hřiště a přihrávce M.Ondráčka sváteční 
střelec Štěrba, který vstřelil první branku od 1.11.2014, kdy skóroval proti 
Tisu "B" při výhře 5:1. Na pět nula zvyšoval v situaci sám proti gólmanovi po 
další hezké příhře od M.Ondráčka Kučera, který tak vstřelil svůj druhý gól v 
mistrovských zápasech- první vstřelil 5.5.2018 proti Kamenné Lhotě. Finální 
skóre 6:0 ustanovil J.Ondráček, který po dlouhém pasu od D.Říčana udělal kličku 
i gólmanovi a poté pohodlně uklidil míč do sítě.<br />
Vysoké vítězství nad oslabeným soupeřem pro nás znamená celkově výborné třetí 
místo v tabulce, jelikož Keřkov vysoko 2:7 prohrál v Jeřišně. <br />
