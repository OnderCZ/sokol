<p class="auto-style7"><strong>Statistický přehled podzimu 2018</strong></p>
<p class="auto-style7">Netrvalo příliš dlouho a po loňské změně na špici 
historické tabulky v počtu startů za Sobíňov se letos změnila i nejvyšší pozice 
