<p class="auto-style7"><strong>26. kolo Libice nad Doubravou 0:4 Sobíňov (0:3)</strong><br />
střelci: 27. Vopršal Michal, 38. Zrzavý Tomáš, 41. Kafka Pavel, 62. Zrzavý Tomáš&nbsp; <br />
Libice byla už před tímto zápasem sestupujícím týmem a jelikož se hrálo za 
úporného horka, nedal se čekat zápas s nějakým velkým nábojem. Odpovídala tomu i 
většina utkání, které bylo poznamenané velkým množstvím nepřesností na obou 
