<p class="auto-style2"><strong>Hodnocení podzimní části sezóny 2018/2019</strong></p>
<p class="auto-style7">Sobíňovští fotbalisté během podzimní části nové sezóny 
celkem zdařile navázali na povedené jaro a v rámci celého kalendářního roku 2018 
se chlubí jednou parádní statistikou- na domácím trávníku nepoznali hořkost 
porážky. Na jaře 2018 jsme doma remizovali v prvním kole s Novou Vsí u Světlé 
0:0 a stejným výsledkem skončil i první zápas podzimu 2018 s rezervou 
Rozsochatce. Všechny ostatní jarní i podzimní zápasy na domácím trávníku dokázal 
Sobíňov vyhrát. </p>
<p class="auto-style7">Během podzimu jsme na domácím trávníku získali 16 bodů (nejlepším 
týmem v domácím prostředí je Rozsochatec "B", který získal 18 bodů). Sedm zápasů 
jsme odehráli na venkovních hřištích a tam už to taková paráda nebyla . Dvakrát jsme zvítězili (6:2 v Hněvkovicích, 3:0 
v Lípě "B"), jednou remizovali (2:2 v České Bělé) a čtyřikrát prohráli. Venku 
jsme tak získali 7 bodů. Vedoucí tým tabulky Šlapanov přitom venku získal 13 
bodů, druhá Česká Bělá bodů 12. Nejvyšší výhrou podzimu je domácí výhra 6:0 v 
zápase proti Libici nad Doubravou, o dva góly jsme prohráli v Habrech (2:4) a v 
Havlíčkově Borové "B" (0:2).</p>
<p class="auto-style7">Po podzimní části sezóny se Sobíňov může pochlubit 
nejlepší obranou soutěže, když inkasoval 15 branek a je tak o jednu obdrženou 
branku lepší než týmy Šlapanova a České Bělé. V žebříčku vstřelených branek 
patří Sobíňovu 6. místo- nejvíc branek vstřelila Maleč (44), pak následuje 
Mírovka "B" (38), Keřkov (36), Šlapanov a Česká Bělá (oba týmy 34 vstřelených 
branek).</p>
<p class="auto-style7">Všechna tato čísla po podzimní části sezóny znamenají to, 
že Sobíňov získal celkem 23 bodů a při aktivním skóre 33:15 se ve velmi 
vyrovnané tabulce nachází na pátém místě. Po sestupu z okresního přeboru hrajeme 
třetí třídu sedmou sezónou. A 23 bodů znamená vyrovnání druhého nejlepšího 
bodového zisku za tuto část soutěže. (2017- 10b., 2016- 17b., 2015- 16b., 2014- 
15b., 2013- 23b., 2012- 25b.) Na první Šlapanov ztrácíme jen 4 body, na druhou 
stranu 4 body máme též náskok na devátý tým tabulky, kterým je Jeřišno. 
Zajímavostí je, že první i druhý tým tabulky mají úplně stejné skóre, i když 
Šlapanov získal o bod víc. </p>
<p class="auto-style7">Tak či tak nás po dlouhé zimní přestávce opět čeká  
zajímavé jaro. Na rozdíl od posledních dvou let do něj nebudeme vstupovat v 
pozici týmu, který je v přímém ohrožení sestupu. Bude ale zapotřebí uhrát na 
začátku jara pár dobrých výsledků, abychom si zbytečně nepřidělali starosti do 
posledních zápasů.</p>
