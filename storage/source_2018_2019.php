<p class="auto-style2"><strong>Jaro 2019</strong></p>
<p class="auto-style7">V&nbsp;polovině června skončila další fotbalová sezóna. 
Sobíňovští fotbalisté se v&nbsp;třetí třídě havlíčkobrodského okresu umístili na 
velmi hezkém třetím místě. Z&nbsp;dvaceti šesti odehraných zápasů jsme jich čtrnáct 
dokázali vyhrát, čtyřikrát jsme remizovali a osmkrát prohráli. Po podzimní části 
soutěže jsme byli na pátém místě se ziskem 23 bodů, na jaře jsme získali stejný 
počet bodů a v&nbsp;celkem vyrovnané tabulce to stačilo na posun o dvě místa vzhůru. </p>
<p class="auto-style7">&nbsp;Celkových 46 bodů znamená rekordní bodový zisk po 
sestupu z&nbsp;okresního přeboru, dosavadním maximem bylo 45 bodů z&nbsp;první 
„posestupové“ sezóny 2012/2013. Absolutním rekordem samozřejmě i nadále zůstává 
62 bodů, které jsme získali v&nbsp;sezóně, kdy jsme naopak postupovali ze třetí třídy 
do okresu- 2006/2007. </p>
<p class="auto-style7">&nbsp;Sobíňov se pyšní nejlepším útok soutěže, síť za 
soupeřovými gólmany jsme dokázali rozvlnit celkem 74 góly. Ani obranná hra týmu 
moc nezaostávala, nejlepší obranou soutěže se prezentoval první tým tabulky 
z&nbsp;České Bělé (31 obdržených branek), na druhém místě této statistiky se umístil 
Sobíňov s&nbsp;34&nbsp;obdrženými brankami.</p>
<p class="auto-style7">&nbsp;Do okresního přeboru tedy postupuje již zmíněná 
Česká Bělá, která vyhrála soutěž s&nbsp;náskokem sedmi bodů přes Šlapanovem. Do IV. 
tříd sestupují týmy Libice nad Doubravou, Hněvkovic a Veselého Žďáru.</p>
<p class="auto-style7">&nbsp;Obecně platí už několik let, že když se sejdeme 
v&nbsp;kompletní sestavě, jsme schopni porazit víceméně každého- viz poslední dva 
domácí zápasy soutěže, když jsme porazili první Českou Bělou 5:1 a druhý 
Šlapanov 6:0. Občas jsme však rádi, když dáme sestavu vůbec dohromady kvůli 
pracovním nebo rodinným povinnostem a podle toho pak samozřejmě vypadají i 
výsledky- třebas na hřišti sestupujícího Veselého Žďáru jsme vedli 2:0, a 
nakonec prohráli 3:4. Ztratili jsme i zápas v&nbsp;Keřkově, zbytečně jsme přišli o 
body i v&nbsp;domácím zápase s&nbsp;též sestupujícími Hněvkovicemi, kdy jsme prohráli 0:1. 
I&nbsp;když tam to byla spíš otázka nemohoucnosti v&nbsp;koncovce než oslabené sestavy. 
Zápasem s&nbsp;Hněvkovicemi skončila i jedna unikátní série domácí neporazitelnosti, 
kterou jsme drželi více než rok- předtím jsme na domácím hřišti naposledy 
prohráli 23.9.2017 s&nbsp;týmem Habrů „B“. &nbsp;</p>
