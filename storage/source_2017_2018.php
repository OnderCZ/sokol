<p class="auto-style7"><strong>10. kolo Sobíňov 4:4 Ledeč n.S. &quot;B&quot; (3:2)<br />
</strong>střelci branek: 26. Ondráček Jaroslav, 35. Kafka Pavel, 39. Němec 
Zdeněk, 77. Říčan Daniel (PK)&nbsp;-&nbsp;19. Machala Ondřej, 36. Šenk Vladimír, 53. Toula 
Martin, 84. Šenk Vladimír<br />
V zápase s rezervou Ledče nás nečekalo nic lehkého. Soupeř se nachází na druhém 
místě tabulky, pyšní se druhou nejlepší obranou soutěže (v prvních devíti 
zápasech dostal jen sedm branek) a disponuje zřejmě nejmladším kádrem ve třetí 
třídě- hned devět hráčů základní sestavy a další čtyři na lavičce byli ročník 
narození 1990 a mladší, my jsme měli pouze jednoho podobně mladého na střídačce- 
M. Dočekala. Podařilo se nám ale tentokráte dát dohromady celkem hodně slušnou 
sestavu, což se na podzim dosud stávalo zřídkakdy a zejména v prvním poločase 
jsme s favoritem hráli vyrovnaný fotbal, když jsme dokázali slušně kombinovat a 
podržet míč. Do vedení se v zápase dostala Ledeč- v 19. minutě se z přímého kopu 
trefil před zeď Machala- 0:1. O sedm minut později ale dostal Sobíňov též šanci 
zahrávat přímý kop z podobné vzdálenosti a J.Ondráček mířil také přesně- 1:1. V 
pětatřicáté minutě šel Sobíňov dokonce do vedení- Pfeffer vyslal krásnou kolmicí 
do úniku Kafku, a ten podél vybíhajícího gólmana mířil přesně- 2:1. Bohužel nám 
vedení nevydrželo příliš dlouho- po levé straně hřiště se protáhl hbitý záložník 
hostí a Šenk od něj dostal přesnou přihrávku mezi beky- se zakončením do prázdné 
poloviny brány už poté neměl problém- 2:2. Přesto jsme ještě do poločasu 
dokázali opět strhnout vedení na svou stranu- divokou pětiminutovku uzavřel po 
