<p class="auto-style7"><strong>11. kolo Havlíčkova Borová "B" 2:0 Sobíňov (0:0)<br />
</strong>střelci branek: 46. Votava Michal, 51. Rakušan Petr <br />
V Havlíčkově Borové se první poločas hrál vyrovnaný fotbal. Michal Vopršal 
trefil po závaru z rohového kopu tyč, po ideálním centru od Říčana pak ve velké 
šanci nedokázal zakončit Kafka. Domácí též nedokázali proměnit dvě šance které 
si vypracovali po standardních situacích a tak se do kabin šlo za bezbrankového 
stavu. O osudu zápasu rozhodly první tři minuty druhého poločasu. V něm Sobíňov 
rozehrál na půlce, o míč rychle přišel a domácí Votava s míčem postupoval téměř 
od poloviny hřiště až k vápnu, kde zamířil přesně- 1:0 pro Borovou. Jen o chvíli 
později ve 49. minutě domácí rychle rozehráli autové vhazování na pravé straně 
naší obrany a centr na vzdálenější tyč pak důrazně propálil do sítě Rakušan- 
2:0. To byl pro Sobíňov šok, ze kterého už jsme se do konce zápasu nedokázali 
dostat a kromě střely Koutníka, která se po odraženém míči otřela o vnější tyč 
brány domácích už jsme neměli žádnou jinou nebezpečnou situaci. Naše hra byla 
strašně těžkopádná, pomalá a na soupeřově polovině nepřesná, bez šance na 
úspěch. A jelikož domácí nedotáhli do gólového konce některou ze situací kdy 
chodili do naší otevřené obrany, skončil zápas dvougólovým rozdílem. <br />
Je vidět, že na Sobíňovu leží ohromná "deka". Dokud je stav utkání vyrovnaný a 
jsme stále ve hře o body, tak to ještě ujde. Jakmile ale dostaneme první gól a 
zápas se začne vyvíjet špatně, je zle. V útočné fázi se přestaneme nabízet, 
nepomůžeme si, nedokážeme dát kolmici skrz soupeřovu obranu. Kombinace jsou 
těžkopádné, hrajeme strašně moc složitě, co je velmi obtížné když nám míče 
odskakují při zpracování od nohy. Nedokážeme se dostávat do zakončení, nemáme 
odražené míče. Je to všechno samozřejmě velmi spojené s tím, že tým je i na 
poměry třetí třídy poměrně "starý", většině týmu chybí dostatečná fyzická kondice, nikdo nedokáže zahrát lépe 
než průměrně alespoň tři zápasy v řadě. Když se zápas vyvíjí špatně, přestaneme 
se povzbuzovat, chybí nějaký hráč který by pak dokázal tým probudit z jakési 
letargie, do které v takovém případě upadneme. Když k tomu přičteme fakt, že v podstatě 
nikdy nedokážeme dva zápasy po sobě postavit stejnou sestavu, je výsledkem to, 
že z posledních šestnácti odehraných zápasů máme na kontě jednu výhru proti 
Veselému Žďáru, který dohrával v devíti lidech a jednu remízu proti rezervě 
Ledče, kterou jsme minulý týden ukopali s hodně velkým štěstím...<br />
