Zápas posledního kola jsme začali vcelku dobře, na těžkém terénu jsme vzadu 
hráli důrazně a jednoduše, vepředu jsme si pak dokázali vytvářet šance. 
Největším rozdílem proti minulým zápasům bylo to, že jsme počáteční nápor 
dokázali zúročit i gólově. Hned v desáté minutě využil Z.Němec menších zmatků v 
domácí obraně a po přihrávce od Janáčka mířil přesně k tyči- 1:0 v náš prospěch. 
O deset minut později jsme předvedli snad nejhezčí kombinační akci podzimu, kdy 
akci založil odzadu Pffefer, míč se pak přes dvě přihrávky dostal k Z.Němcovi, 
který ho zprvní přihrál přesně k noze Říčana a ten ho nechytatelně poslal k tyči 
podruhé- 2:0. Rychlé vedení nás bohužel trochu ukolébalo, domácí se dostali do 
hry a zhruba dvacet minut jsme se spíš bránili. K vysloveně gólové šanci se ale 
domácí nedostali a když už mířila nějaká střela na bránu, pochytal to spolehlivě 
gólman Veselý. <br />
Ve druhém poločase domácí zkusili hrát více kombinačně, ale na již hodně 
rozbahněném terénu to moc nešlo a tak se jejich počáteční náznak tlaku 
rozplynul. Přesto si vypracovali vyloženou šanci, když se po pěkné kolmici za 
naše beky dostal samotný před našeho gólmana útočník Věžnice, který ale místo 
zakončení naštěstí pro nás zvolil zbytečnou přihrávku do ofsajdové pozice na 
svého kolegu a celou šanci tím zhatil. Uklidnění tak Sobíňovu dodal druhou 
brankou v zápase Říčan, který proměnil pokutový kop nařízený za ruku domácího 
obránce- 3:0. To byl definitivní hřebíček do nadějí domácích na bodový zisk. 
Uklidněný Sobíňov pak mohl dát ještě i další branky, po přihrávce Říčana 
proměnil samostatný únik střelou podél gólmana Z.Němec a stanovil tak stav 
utkání na 4:0. Těsně před koncem málem Z.Němec zkompletovat i hattrick, šanci mu 
ale dobrým zákrokem překazil gólman domácích, a tak už více branek nepadlo. 
Sobíňov tak slaví zaslouženě první podzimní bodový zisk z venkovního utkání a 
odsoudil k přezimování na poslední příčce tabulky právě Věžnici "B".<br />
