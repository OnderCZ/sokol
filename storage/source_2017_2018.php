<p class="auto-style7"><strong>25. kolo Rozsochatec "B" 3:5 Sobíňov (2:1)<br />
</strong>střelci branek: 8. Bílek Jakub, 10. Bílek Jakub, 71. Bílek Zdeněk&nbsp;-&nbsp;4. 
Ondráček Marek, 52. Ondráček Marek, 56. Ondráček Marek, 69. Němec Zdeněk, 76. 
Němec Zdeněk <strong><br />
</strong>V Rozsochatci na výborně připraveném trávníku jsme začali opět velmi 
dobře když se hned ve čtvrté minutě prosadil přesnou střelou Marek Ondráček po 
přihrávce Zdendy Němce. Domácí ale hráli velmi dobře, v obraně sice nepůsobili 
nejpevnějším dojmem, ale v ofenzívě se jejich mladí hráči velmi dobře 
pohybovali, vyhověli si a neustálým napadáním naší rozehrávky nás dostávali pod 
tlak. I díky našim chybám se jim během dvou minut podařilo zápas otočit na svou 
stranu, když se dvakrát prosadil J.Bílek a Rozsochatec "B" tak vedl 2:1. Domácí 
pak měli i další šance, několikrát nás podržel opět výborný gólman Wasserbauer, 
párkrát nás zachránila nepřesně seřízená mířidla domácích útočníků. Ani my jsme 
nedokázali proměnit své dvě velké šance, kdy nejprve na mokrém trávníku 
podklouzl téměř do prázdné brány zakončující Zrzavý a pak neproměnil svůj 
samostatný únik Z.Němec a tak se do kabin šlo za stavu 2:1 pro domácí.<br />
Ve druhém poločase se hra vyrovnala, naše defenziva se zpevnila a domácí se už 
tak často nedostávali do zakončení. Navíc nám pomohlo i trochu štěstí, když 
střelu Marka Ondráčka ztečoval domácí hráč tak nešťastně, že ta vysokým obloukem 
zapadla za záda v této chvíli bezmocného gólmana- vyrovnáno 2:2.O tři minuty 
později už jsme vedli- zřejmě zaskakující gólman domácích přišel o míč za velkým 
vápnem, a Marek Ondráček dovršil svůj hattrick trefou do prázdné branky domácího 
celku téměř z nulového úhlu od rohového praporku- 3:2 pro Sobíňov. Do 
dvoubrankového vedení nás dostal hlavičkou Zdeněk Němec, na kterého po centru 
M.Ondráčka úplně zapomomněla celá domácí obrana - 4:2. Rozsochatec se po tomto 
šoku rychle otřepal a snažil se dostat zpátky do zápasu. Po rohovém kopu trefil 
ale odražený míč jen do tyče naší brány domácí útočník Kiss, a snížení tak 
přišlo až po standardní situaci, kdy jsme neuhlídali hlavičkujícího hráče na 
přední tyči- 4:3. V další velké šanci pak reflexivně opět skvělé zasáhl 
Wasserbauer a naopak na druhé straně využil další chyby domácího gólmana 
Z.Němec, který tak pohodlně skóroval na 5:3 a dostal nás tak opět do 
uklidňujícího dvougólového vedení. Domácí pak už trochu rezignovali, poslední 
čtvrthodina se už odehrála celkem v klidu. Šestý gól mohl do sítě domácích 
přidat ještě střídající Vrána, který byl po krásné přihrávce od Hochmana úplně 
sám na penaltě, bohužel místo zpracování a zakončení volil střelu z voleje která 
se mu nepovedla a tak víc branek už nepadlo. <br />
V prvním poločase nás pohybliví domácí přehrávali a měli více šancí, naštěstí 
jsme neinkasovali víc jak dvakrát. Ve druhém poločase nám pak svými chybami 
hodně pomohla defenziva Rozsochatce a díky zlepšené obranné hře celého mužstva 
jsme dokázali zápas otočit a zvítězit tak počtvrté v řadě. Příští týden by nás v 
sobotu měl čekat poslední zápas sezóny s Věžnicí "B", po kterém by měla 
následovat rozlučka, na kterou zveme i příznivce a fanoušky- přijďte se s námi 
dát pivko. Nám už o nic nejde, i díky ostatním výsledkům neskončíme hůř než na 
sedmém místě tabulky, tak nám snad do toho nezasáhne Okresní fotbalový svaz 
změnout termínu zápasu- Věžnice "B" je totiž ještě namočená v sestupových vodách 
a svaz by teoreticky mohl změnit data všech zápasů posledního kola tak, aby se 
vše hrálo ve stejný čas.<br />
