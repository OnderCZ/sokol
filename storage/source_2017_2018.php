<p class="auto-style7"><strong>23. kolo Ledeč nad Sázavou "B" 1:2 Sobíňov (0:1)<br />
</strong>střelci branek: 52. Martinek Ondřej&nbsp;-&nbsp;15. Říčan Daniel, 67. Vopršal 
Michal&nbsp; <strong><br />
</strong>Rezerva Ledčce nad Sázavou byla už před zápasem jasným vítězem 
letošního ročníku III.třídy a měla tak zajištěný postup do okresního přeboru. Na 
velkém a krásně upraveném trávníku nás tedy rozhodně nečekal lehký zápas, čemuž 
odpovídala i naše přeci jen defenzivnější sestava a taktika. Domácí se snažili 
překonávat naši obranu kolmicemi, na širokém hřišti k tomu měli poměrně dost 
možností, většinu těchto pokusů ale stíhali odvracet krajní beci nebo stoper 
Štěrba. Snad z prvnější vážnější akce jsme se naopak do vedení dostali my- po 
kombinaci ze středu hřiště se míč dostal&nbsp; k Zrzavému (?), ten ho předložil Říčanovi 
a vedli jsme 1:0. Domácí to trochu zaskočilo a jejich aktivita přeci jen lehce 
upadla, poločas jsme tak vyhráli 1:0.<br />
Druhá půle začala velkým náporem Ledče. Její hráči nás prvních deset minut 
nepustili za půlku a výsledkem bylo vyrovnání na 1:1 kdy jinak výborně 
chytajícímu Wasserbauerovi nedal šanci Martinek. Domácí pak měli další minimálně 
čtyři ložené gólové šance, většinu z nich ale zlikvidoval Wasserbauer ve 
spolupráci s obranou, a když už domácí hráč udělal kličku i jemu, zamotal se mu 
míč pod nohy a následně trefil břevno naší brány. Z ničeho nic tak udeřilo na 
druhé straně- Michal Janáček posunul míč na levé straně hřiště na Michala 
Vopršala- jeho první střelu ještě sice stihl zblokovat domácí bek, ale míč se 
odrazil zpátky k Michalovi a ten pravačkou střelou na vzdálenější šibenici nedal 
šanci gólmanu domácích- 2:1 pro Sobíňov. V posledních dvaceti minutách hráči 
rezervy Ledče ještě zkusili s výsledkem něco udělat, ale další míč se jim do 
naší brány už dostat nepodařilo. A jelikož se ani nám nepodařilo dotáhnout do 
konce alespoň jednu ze zhruba tří brejkových akcí, zvítězili jsme nakonec v 
Ledči hodně šťastně po těžce odbojovaném utkání 2:1.<br />
