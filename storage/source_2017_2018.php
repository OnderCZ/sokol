chvíli později běžel sám na gólmana- jeho střela ale tentokráte mířila do tyče, 
když ho stihl hodně na hranici faulu rozhodit domácí brankář. Další dvě či tři 
příležitosti jsme si sami zhatili špatnou finální přihrávkou a domácí se dostali 
poměrně jednoduše zpátky do hry- v 33. minutě se po nákopu za naší obranu z 
hranice vápna opřel do míče Doležal a mířil přesně na vzdálenější tyč- 1:2. 
Chotěboř pak přidala, chtěla do poločasu skóre vyrovnat a to se jí i podařilo- v 
poslední minutě poločasu dokázal útočník míč dostat skrz tři beky až ke 
