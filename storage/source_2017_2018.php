<p class="auto-style7"><strong>26. kolo Sobíňov 4:2 Věžnice "B" (3:1)<br />
</strong>střelci branek: 12. Němec Zdeněk, 22. Kafka Pavel, 25. Kafka Pavel, 52. 
Němec Zdeněk&nbsp;-&nbsp;9. Krupička Michal, 80. Toman Václav&nbsp; <strong><br />
</strong>Poslední zápas sezóny 2017/2018 jsme začali za celkem příjemného 
fotbalového počasí s vědomím dobré formy z minulých zápasů. Do vedení se ale 
dostali hosté, když hned v osmé minutě prodloužil jeden z nich hlavičkou dlouhý 
aut za sebe a Krupička neměl problém se skórováním do prázdné brány- 0:1. 
Naštěstí se nám ale rychle podařilo vyrovnat, když dlouhý nákop Říčana 
promáchnul hostující bek, a do samostatného úniku se tak dostal Z. Němec, který 
poté pohodlně skóroval na bližší tyč- 1:1. Do dvoubrankového vedení 3:1 dostal 
Sobíňov Kafka- ten si nejprve ze vzduchu stáhnul přihrávku od Z.Němce a poté 
skóroval podél vybíhajícího gólmana na přední tyč, a o pár minutek později 
dostal krásný míč za obranu od Koutníka, přičemž pak míč poslal opět do sítě. 
Hosté nehráli špatně, důrazná hra urostlých hráčů dělala sobíňovské obraně 
problémy a tak musel několikrát zasahovat gólman Wasserbauer. I Sobíňov měl 
nějakolik dalších dobrých příležitostí k navýšení náskoku, do poločasu už ale 
žádný další gól nepadl.<br />
Do druhé půle jsme šli s předsevzetím, že zkusíme rychle přidat nějaký další 
gól, abychom mohli prostřídat i všechny hráče z lavičky. O nic důležitého nám 
již tabulkově nešlo, ale poslední zápas sezóny jsme doma chtěli vyhrát. První 
dvě šance měli hráči Věžnice, při střelách ze střední vzdálenosti se ale opět 
vyznamenal Wasserbauer, a tak se nakonec kýžený další gól podařilo vstřelil 
Sobíňovu- po hezké kombinaci po ose M.Ondráček, Kafka, Z.Němec zakončoval 
poslední jmenovaný přesně a zvýšil tak na 4:1. To byl signál pro to, abychom 
postupně využili všech pět dostupných střídání, což se posléze v malých 
intervalech odehrálo. Hra se samozřejmě vyměněním půlky hráčů trochu rozpadla, a 
hosté to využili i ke snížení, když se krásnou ránou, na kterou tentokráte 
Wasserbauer neměl šanci dosáhnout, prezentoval Toman- 4:2. Více gólů už ale hosté 
nedali a jelikož pumelice Koutníka mířila pouze do břevna branky, skončil zápas 
dvoubrankovým vítězstvím Sobíňova, který tak dosáhl na jubilejní třicátý jarní 
bod.<br />
<em>sestava: Z.Wasserbauer - zprava I.Koutník (M.Kučera), O.Vopršal, T.Štěrba, M.Vopršal - 
M.Ondráček, D.Říčan, P.Kafka (L.Pfeffer), M.Janáček (O.Starý) - T.Zrzavý (J.Hečko), 
Z.Němec (P.Kodým), na lavičce připraven ještě P.Sláma<br />
reportáž napsal: P.Kafka<br />
