Pokud bych měl za podzim vysloveně někoho pochválit, byl by to z pohledu výkonů 
na hřišti gólman Petr Veselý, který se sice nevyvaroval několika chybek, ale ve 
většině zápasů nás hodně podržel. Zdeněk Němec nám v&nbsp;útoku ohromně pomohl vždy 
když nastoupil, ve středu pole pak důrazem a rozehrávkou řídil hru kapitán Dan 
Říčan. Osobně bych zároveň chtěl moc poděkovat Slávovi Ondráčkovi, že se rozhodl 
vzít trenérské otěže ještě jednou do ruky a i přes obtíže s tím spojené utvářel 
sestavu a pomohl s alespoň částečnou konsolidací týmu na konci podzimní části 
sezóny. <br />
