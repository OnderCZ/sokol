Důvody proč nám to na podzim moc nešlo jsou pořád stejné- často se měnící 
sestava z důvodů častých absencí (což se podepsalo zejména na venkovních 
zápasech), postupné stárnutí týmu a časová zaneprázdněnost mnoha hráčů, která je 
posléze spojena s nízkou tréninkovou účastí. Přesto jsme i tak mohli a asi 
i měli uhrát během podzimu více bodů- v zápase s Chotěboří jsme rychle vedli 2:0 
přičemž vedení mohlo být ještě větší, nakonec jsme ale prohráli vysoko 3:5. S 
Lípou "B" jsme dokonce v poločase vedli 4:2, přesto jsme prohráli 4:5, když jsme 
dostali tři góly během pěti minut. Stejně tak se nějaké body daly vydolovat i třebas ze zápasů se Šlapanovem a Kamennou Lhotou.<br />
