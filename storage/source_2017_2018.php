sklepl před prázdnou bránu odkud Novák pohodlně skóroval- 2:2.<br />
Začátek druhého poločasu Sobíňov bohužel vůbec nezachytil a hned po jeho první 
minutě domácí vedli 3:2, když se hlavou trefil Doležal. Sobíňov poté upadl do 
herního zmaru, byl všude pozdě a bylo otázkou času, kdy inkasuje další branku. 
