<p class="auto-style7"><strong>12. kolo Sobíňov 4:2 Rozsochatec "B" (1:1)<br />
</strong>střelci branek: 35. Ondráček Jaroslav, 49. Ondráček Jaroslav, 73. Němec 
Zdeněk, 76. Koutník Ivo -&nbsp;43. Dundáček Dan, 61. Kiss Tibor <br />
V posledním domácím zápase podzimní části sezóny jsme chtěli navázat na bod 
získaný s rezervou Ledče. Na soupeře jsme doslova vlétli, během první 
čtvrthodiny jsme měli snad tři gólové šance, které ale bohužel zůstaly 
neproměněné. Tu největší z nich nám mizerným výhozem dopřál gólman rezervy 
Rozsochatce, ani situaci dva sami na gólmana jsme ale nedokázali brankově 
vyřešit. Hra se pak vyrovnala, hosté spoléhali na zkušenou obranu a rychlé hráče 
do ofenzivy. Do vedení jsme se ale dostali my, když faul na Kafku potrestal 
precizně provedeným přímým kopem J.Ondráček- 1:0. Hosté pak poměrně jednoduše 
vyrovnali, když se Dundáček mrštně protáhl obranou a zavěsil- 1:1. Další šance 
na obou stranách hřiště zůstaly v první půli nepoměněné.<br />
Už během první půle se objevovaly známky podrážděnosti z obou stran, bylo tam 
nějaké simulování, došlo i na slovní rozmíšky, a poločas druhý v tom pokračoval 
hned od samého začátku. Hosty hodně rozčílila situace ze 49. minuty, kdy bylo na 
hranici vápna podle nich nesprávně odpískáno přistrčení Z. Němce a i další přímý 
kop v provedení J.Ondráčka skončil gólem- 2:1. Od té doby naštěstí pro nás 
začali diskutovat s rozhodčím po každém jeho výroku a přestali se tolik 
soustředit na hru.V šedesáté minutě se přesto dočkali vyrovnání a opět to byl 
velmi laciný gól v naší síti- dlouhatánský nákop ze soupeřovi poloviny propadl 
až mezi naše beky a gólmana, rozsochatecký Kiss byl u míče první a vyrovnat na 
2:2. Neuběhlo ale ještě ani dalších deset minut a hosté se sami oslabili o 
jednoho hráče- Dobrovolný neudržel nervy na uzdě a potleskem ocenil to, že mu 
rozhodčí udělil žlutou kartu za faul. Obdržel tedy ihned druhou žlutou a šel do 
sprch. Sobíňov dokázal přesilovku bleskurychle využít, když se po přihrávce od 
Říčana dostal před gólmana Z.Němec a střelou na zadní tyč ho překonal- 3:2. O 
chvíli později později ve vápně hostí přiťukl J.Ondráček míč střídajícímu 
Koutníkovi a ten nechytatelnou dělovkou pod břevno zvýšil na dvoubrankový 
rozdíl- 4:2. To už bylo na rozsochateckou rezervu příliš, v té chvíli už neměla 
síly na zvrat. Korunu pak neustálým protestům a stížnostem na rozhodčího nasadil 
Pleskač, který proti němu "Použil pohoršujících, urážlivých nebo ponižujících 
výroků nebo gest" (tak stojí v zápise) a dostal z fleku červenou kartu. Šanci na 
dovršení hatricku pak ještě dostal J.Ondráček, v pozici sám proti gólmanovi ale 
přeloboval i bránu soupeře a tak zápas skončil 4:2.<br />
První polovinu sezóny zakončíme příští týden ve Věžnici, jejíž rezerva má po 
dvanácti kolech na kontě stejný počet bodů jako my a tak se bude hrát přímý 
souboj o to, kdo přezimuje na úplném konci třetitřídní tabulky.<br />
