až k zakončení, jeho střelu ale zastavilo břevno domácí brány. Slušnou šanci měl 
na kopačce i po velmi dlouhé době hrající Sláma a krok chyběl k zakončení do 
prázdné brány střídajícímu Kodýmovi. Domácí měli také ještě zhruba 2-3 šance, i 
oni trefili tyč, poslední gól ale nakonec vstřelili opět hosté, když se po 
přihrávce Říčana pohodlně trefil Kafka a ustanovil tak konečné skóre na 5:3.<br />
