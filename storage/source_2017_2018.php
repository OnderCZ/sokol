<p class="auto-style7"><strong>24. kolo Sobíňov 5:0 Havlíčkova Borová "B" (3:0)<br />
</strong>střelci branek: 2. Kafka Pavel, 6. Němec Zdeněk, 40. Ondráček Jaroslav, 
70. Zrzavý Tomáš, 81. Ondráček Jaroslav <strong><br />
</strong>V předposledním domácím zápase jsme chtěli navázat na dobrou jarní 
formu a zápas jsme nakonec ovládli jasným vítězstvím o pět branek. Hodně k tomu 
pomohl již samotný začátek zápasu, neboť v jeho druhé minutě posadil J.Ondráček 
míč z rohového kopu přesně na hlavu Kafky a vedli jsme 1:0. Neuběhlo ani dalších 
pět minut a bylo to o dvě branky, když hosté špatně rozehráli ve středu hřiště, 
míč se od Kafky dostal k Z.Němcovi a ten překonal gólmana Borové podruhé- 2:0. 
Poté následovala herně trochu horší fáze, kterou utnula další branka v hostující 
síti- Z.Němec vybojoval míč na levém kraji velkého vápna a následně ho parádně 
předložil J.Ondráčkovi v podstatě před poloprázdnou bránu, ten už tedy neměl 
problém se zakončením - 3:0.<br />
Ve druhém poločase se nehrál v teplém počasí nějaký zázračný fotbal- Sobíňov 
pohodlně kontroloval hru, Borová "B" se nebyla schopna prosadit a naopak sama 
ještě dvakrát inkasovala. Nejprve se po pravé straně protáhl M.Ondráček, nahrál 
do vápna Zrzavému a ten zvýšil náskok na 4:0. Deset minut před koncem pak dal 
definitivní podobu výsledku J.Ondráček, který si okolo gólmana dokázal prohodit 
míč po přihrávce M.Vopršala a rozsvítil tak na tabuli konečné skóre 5:0. Za 
poslední tři domácí zápasy máme skóre 21:0 (8:0, 8:0, 5:0), na jaře jsme zatím 
pouze jednou prohráli a tak doufejme, že si tuto velmi lichotivou bilanci 
nepokazíme ani v posledních dvou zápasech jara.<br />
