takový jsme začali velmi dobře, a během úvodní čtvrthodiny jsme si vytvořili několik dobrých
brankových příležitostí. Využili jsme však pouze jednu z nich, kdy Padílo dorazil za gólmanova
záda bejkovu odraženou střelu. Ke konci prvního poločasu se pak hra lehce vyrovnala, i když
větší šance jsme si stále vypracovávali my. Nic důležitého se již však nestalo, a tak poločas
skončil naším jednobrankovým vedením. Začátek druhé půle nám opět vyšel velmi dobře, a během
šesti minut na rozmezí padesáté minuty zápasu jsme zápas rozhodli dvěma góly vstřelenými
po rohových kopech. Poté se však veškerý fotbal ze hřiště vytratil, a byli to spíše hosté,
kteří se snažili něco vymyslet a zápas tak případně poněkud zdramatizovat. Nám se po vynuceném
střídání Ludi Hamerníka poněkud rozpadla hlavní osa mužstva a tak jsme se chvílemi omezili
na pouhé odkopávání míčů co nejdál od naší brány. Bohužel, Erikovi jsme čisté konto neuchránili,
a hosté se tak necelých deset minut před koncem dočkali aspoň čestného úspěchu. A jelikož se nám
během druhé půle nepodařilo proměnit ani některou z našich nadějně rozehraných brejkových situací,
skončil celý zápas výsledkem 3:1.
Sestava: Urban- zleva Suchý, O.Vopršal, Hamerník(Kopecký), M.Vopršal- V.Němec, Kafka, Ondráček,
Jelínek(Mužila)- Marek, T.Štěrba(Bílek)</pre>
