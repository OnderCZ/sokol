<pre><b>10.kolo 16.10. Sokol Sobíňov - Keřkov B 3:1(1:0)
naše branky: Štěrba T. 2x, Marek</b>
Zápas předposledního podzimního kola se hrál za stálého jemného deště a na poměrně záludném
