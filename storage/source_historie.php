<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
<strong>Volně převzatá historie klubu z knihy Fotbal Havlíčkobrodska (Veselka 
Petr, Buňat Pavel, Vácha Luboš, vydáno 2013), doplněno a upraveno</strong></p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Dělnická tělovýchovná jednota a tělocvičná jednotka Sokol v roce 1938 požádaly o 
pozemek k vybudování hřiště na "Kačinách" ležící mezi obcí Sobíňov a 
evangelickým hřbitovem. Během roku 1943 vznikl fotbalový oddíl a začaly se zde 
hrát fotbalové zápasy. Hřiště bylo využíváno také německými vojáky, kteří 
sloužili u nedalekého vojenského skladiště na Bílku.</p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Po válce hrálo mužstvo přátelská a mistrovská utkání na Hlinecku, kde se 
bojovalo ve II. třídě, a to s celky Hrochova Týnce, Vitanova, Přestavlk, 
Chrudimi, Moravan, Miřetic a dalších. Doprava na venkovní duely byla většinou 
vlakem, někdy však i pěšky. V pozdější době se jezdilo na kolech a motocyklech. 
Velikou osobností byl tehdy Stanislav Vojíř, který po válce působil v Kutné 
Hoře. Tým Sobíňova byl tehdy sestaven hráči z Rozsochatce, Bílku, Křížové a 
dalších okolních vesnic, v nichž v té době ještě nebyl založen oficiální klub. 
Konec padesátých let znamenal pro mužstvo zápasy na Chotěbořsku, kde se hrála 
okresní soutěž. Mezi nejobětavější pracovníky patřil Stanislav Kafka.</p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Během šedesátých a sedmdesátých let byl okresní přebor rozdělen na několik tříd 
a Sobíňov obvykle bojuje ve třetí nebo čtvrté třídě. Roku 1972 se hřiště dočkalo 
zázemí, byla vystavěna zděná kabina. Travnatá plocha patřila v té době k 
nejlepším na okrese. O dva roky později se založilo družstvo žáků, a posléze i 
dorostu. Období mezi lety 1978 a 1979 přineslo nepříjemnou krizi, došlo totiž k 
rozpadu fotbalového výboru, mužstvo pak sestoupilo do IV. třídy. Přece jenom se 
ale našli obětaví pracovníci bratři Jelínkové, Miroslav Chmelík a Viktor Starý, 
kteří oddíl opět pozvedli.</p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Vzestup sobíňovského fotbalu se datuje k roku 1981, kdy začal hrát okresní 
přebor. V roce 1988 měli Sobíňovští možnost sledovat na vlastní oči přátelské 
utkání, které zde proti místních borcům sehrála slavná Amfora, tým složený ze 
známých osobností. Velký generační problém zasáhl družstvo Sobíňova v první 
polovině devadesátých let, kdy se sestoupilo do třetí třídy a posléze i do třídy 
čtvrté. Pro nedostatek hráčů bylo zrušeno i mužstvo dorostu a později i žáků.</p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Na lepší zítřky se začalo blýskat až po přelomu tisíciletí, kdy se postoupilo v 
sezóně <a href="http://fotbalsobinov.unas.cz/sezony/2005_2006.htm">2005/2006</a> 
zpět do třetí třídy a hned nato v sezóně
<a href="http://fotbalsobinov.unas.cz/sezony/2006_2007.htm" style="font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: 400; letter-spacing: normal; orphans: 2; text-align: -webkit-center; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;" target="_self">
2006/2007</a> i do Okresního přeboru který se hrál pět sezón.&nbsp; Velkou 
zásluhu na postupu měli trenéři Milan Potůček, hrající trenér Zdeněk Wasserbauer 
a také vedoucí mužstva Jiří Jirásek. V sezóně
<a href="http://fotbalsobinov.unas.cz/sezony/2011_2012.htm" style="font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: 400; letter-spacing: normal; orphans: 2; text-align: -webkit-center; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;" target="_self">
2011/2012</a> Sobíňov opět sestoupil do třetí třídy, kterou od té doby stále 
hraje.</p>
<p style="color: rgb(0, 0, 0); font-family: Arial; font-size: medium; font-style: normal; font-variant-ligatures: normal; font-variant-caps: normal; font-weight: normal; letter-spacing: normal; orphans: 2; text-align: start; text-indent: 0px; text-transform: none; white-space: normal; widows: 2; word-spacing: 0px; -webkit-text-stroke-width: 0px;">
Největší osobností sobíňovské kopané je bezesporu Bedřich Hamsa (<a href="http://www.csfotbal.cz/prvni-liga/hrac/bedrich-hamsa/2001?&amp;pj=2&amp;od=63&amp;do=67" target="_blank">CS 
Fotbal</a>,
<a href="https://cs.wikipedia.org/wiki/Bedřich_Hamsa" target="_blank">Wikipedie</a>), 
jenž nejprve jako dorostenec působil v Pardubicích. Mezi dospělými pak kopal za 
Bohemians, Slavii a Drnovice.<br />
V&nbsp;československé&nbsp;a&nbsp;české lize&nbsp;nastoupil v 82 utkáních a dal 12 gólů. Ve druhé 
lize zaznamenal více než 60 branek, stal se nejlepším střelcem&nbsp;<a href="https://cs.wikipedia.org/wiki/2._česká_fotbalová_liga_1994/95" target="_blank">2. 
české fotbalové ligy 1994/95</a>&nbsp;s 22 góly.<br />
</p>
