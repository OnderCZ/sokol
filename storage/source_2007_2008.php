rozhodnutého stavu. </p>
<p>Uspokojení z dostatečného náskok, zraněními stíhaný tým a možná i únava z 
předchozího večera. To vše zřejmě zapříčinilo totální herní výpadek v poslední 
půlhodině. Přitom prvních deset minut druhého dějství ale nic takového 
nenaznačovaly. Borová dobře držela míč na dostřel sobiňovské branky a jako první 
také vyslala pokusy na Wasserbauerovu svatyni, jako Němcovu hlavičku po pěkném 
Klementově centru. Jenže v 55. minutě se domácí dostali do první gólovky, 
Kopecký jejich hlavičku ale vytáhl na roh. Pak se do brejku dostal Z.Němec, ale 
hostující gólman vyběhl včas, stejně jako měl hlavičku M.Vopršala. Další domácí 
šanci si připsal Ondráček, ale jeho pokus z dalšího úniku mířil mimo borovskou 
branku. Poté si na přetažený centr naběhl opět Z.Němec, ale fantastický Kopecký 
se stihl přesunout ke vzdálenější tyči a jeho hlavičku vyrazit. V těchto 
chvílích se borovská defenziva dostala snad podruhé v sezoně pod takový tlak, 
ale nemohoucnost domácí „střelců“ korunoval čtvrt hodiny před koncem Ondráček, 
který po další Němcově přihrávce dorážel míč na branku ze dvou metrů, ale 
nepochopitelně trefil pouze tyčku. Neujala se ani další hlavička Bílka, která 
letěla nad borovskou branku, Němcova střela z úhlu podél Kopeckého letěla mimo a 
zpětnou přihrávku J.Ondráčka srazil Kučera na roh. Poté se ještě jednou vytáhl 
znovu Kopecký, který lapil další pokus zevnitř pokutového území. Hosté se 
připoměli Němcem, který šel neohrožen do souboje s domácím gólmanem a brejkem 
bratří Klementů. Patička mladšího Radka ale na Martina, který by šel sám na 
Wasserbauera, neprošla. Nakonec ale hosté udělili domácím ukázku z lekce 
produktivity. Blažek si pohrál s míčem, přiťukl R. Klementovi, který se nemýlil 
a zvýšil na 4:0 z pohledu hostí. Domácí pak měli ještě další dvě šance, ale 
jednou opět po rohu mířili mimo a podruhé jim sudí neuznal branku pro domnělý 
ofsajd. Havlíčkova Borová si tak veze se Sobíňova všechny body, ale může děkovat 
i totální impotenci domácích hráčů z druhé půle a vynikajícímu Kopeckému. <br>
