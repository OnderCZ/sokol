<p align="center"><b><font size="5">Sezóna 2007/2008, Okresní přebor</font></b></p>
<p align="left"><b><font color="#993333">Celkové zhodnocení sezóny 2007/2008:
<br>
</font></b>Do podzimu jsme vstupovali jakožto nováčkové Okresního přeboru. 
Rozhodně jsme si věřili na to, že nebudeme v přeboru pouze na okrasu a že 
dokážeme sehrát dobrá utkání. To se nakonec určitě podařilo, obzvláště v závěru 
jara jsme dokonce dokázali zasáhnout do boje o postup, když jsme sehráli s 
předními týmy naprosto vyrovnaná utkání (Ransko i Ždírec shodně 1:1 venku). Na 
druhou stranu jsme v této sezóně zaplatili i nováčkovskou daň v podobě několika 
zbytečných ztrát, z nichž nejvíc asi mrzí jarní zápas v Keřkově (0:1).<br>
&nbsp;</p>
<p align="left">Doma i venku jsme dokázali v několika zápasech určitě potěšit 
naše výborné diváky bohatou&nbsp; gólovou úrodou, výhry 7:1(Keřkov podzim doma), 
7:2 (Světlá &quot;B&quot; jaro doma), poslední dvě domácí výhry v poměru 6:1(Lipnice, 
Lučice), a debakl, který jsme uštědřili Mírovce dokonce na jejím hřišti (9:1) 
mluví myslím za vše. V soutěži jsme vstřelili na nováčka velmi slušných 71 
branek, což by nás umístilo v pomyslné tabulce nejlépe střílejících týmů na 
perfektní čtvrté místo. Určité mezery tak lze najít hlavně v naší hře směrem 
dozadu, kdy jsme dostávali poměrně hodně laciných branek.<br>
<br>
Lze tak snad oprávněně doufat, že na povedené výkony dokážeme navázat i v sezóně 
další, říká se ostatně, že druhá sezóna v nové soutěži bývá obtížnější než ta 
první...</p>
