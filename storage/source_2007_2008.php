<p align="left"><b>26.kolo Ždírec n.D. &quot;B&quot; 1:1 Sobíňov (1:1)<br>
náš gól: T.Štěrba<br>
</b>V zápase posledního kola letošní sezony nám už o nic nešlo, a tak jsme si 
chtěli pouze zahrát fotbal na krásném ždíreckém trávníku. Chyběli nám navíc dva 
hráči obvyklé základní jedenáctky, kteří dočasně &quot;emigrovali&quot; do zahraničí a tak 
jsme byli nuceni v sestavě lehce improvizovat. To domácí byli v jiné 
situaci, k postupu do I.B třídy museli v posledním kole získat víc bodů než 
Havlíčkova Borová, která hrála svůj zápas ve stejnou chvíli v Ledči a podle toho 
to též na hřišti vypadalo. Hned ve druhé minutě se nepříjemně s Vaskou srazil 
při bránění nebezpečného centru Cafua, o chvíli později jedna ze střel domácích 
skončila těsně vedle naší tyče a v šesté minutě jsme již prohrávali 1:0, když 
Tomáš do Vaskova protipohybu nešťastně tečoval střelu J.Matějky, kterému míč 
krásně předložil Kysilko. Inkasovaná 
rychlá branka s námi trochu otřásla, a domácí z toho těžili- kombinacemi se 
dostávali do blízkosti našeho vápna, kde jsme jejich akce dost často 
zachraňovali pouze za cenu faulů, z čehož se rekrutovaly standardní situace. 
Naštěstí jsme měli v bráně skvělého Vasila, obrana též pracovala velmi dobře a 
tak jsme domácí nepouštěli do vyslovených šancí. Postupem doby jsme se navíc též 
trochu osmělili a začali jsme hrozit na druhé straně rychlými protiútoky, které 
taktéž nezřídkakdy skončily faulem domácích. Po jednom takovém se urodila  
standardní situace v náš prospěch, a Vikyho tvrdá střela musela Semelku v domácí 
bráně v rukavicích trochu zabrnět. O chvíli později však přišla další standartka, Vikyho přetažený míč si našel Tomáš a z 
volejte trefil míč tak, že ten zapadl za záda lehce překvapeného gólmana. To naopak trochu 
zaskočilo domácí hráče, do poločasu se tak urodily zajímavé situace spíše ve 
středu hřiště, kde se začalo při některých soubojích trochu jiskřit.<br>
Druhý poločas přinesl očekávaný obrázek hry- ždírecká rezerva se tlačila dopředu, zkoušela 
využít rychlost svých útočníků při kombinacích, nebo naopak při dlouhých 
nákopech za naši obranu. My jsme se soustředili spíše na hlídání remízového 
výsledku, s tím, že jsme zkoušeli využít každou příležitost k rychlému 
protiútoku. Postupem času si panující vedro začalo vybírat svou daň a všem 
hráčům docházely síly. Ždírec naštěstí rezignoval na hru po zemi, a většinu míčů 
se do našeho vápna snažil procpat vzduchem a doufal tak snad ve využití 
