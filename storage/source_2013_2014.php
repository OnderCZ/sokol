<p align="center"><b><font size="5">Sezóna 2013/2014, III.třída</font></b></p>
<div align="center">
	<p class="MsoNormal" align="left"><br>
	<br>
	<font face="Verdana"><b>Zhodnocení sezóny 2013/2014</b><br>
	Fotbalové družstvo Sobíňova hrálo letos druhým rokem III.třídu 
	Havlíčkobrodska. V konečné tabulce skončilo na šestém místě, když zejména v 
	jarní části poznamenané mnoha zraněními a dalšími absencemi ztratilo víc 
	bodů, než by bývalo odpovídalo kvalitě týmu. Během podzimní části soutěže 
	totiž fotbalisté získali 23 bodů, zatímco v části jarní bodů pouze 16, to 
	vše při aktivním skóre 61:51 (pro porovnání čísla z loňské sezóny- 45b. 
	(25+20), skóre 65:43).</font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">V letošní velmi 
	vyrovnané tabulce III.třídy, kdy je konečný bodový odstup druhého týmu v 
	tabulce od předposledního pouhých třináct bodů, rozhodla o konečném umístění 
	při stejném počtu bodů s Českou Bělou a Mírovkou &quot;B&quot; minitabulka vzájemných 
	zápasů- v ní Sobíňov získal stejně tak jako Česká Bělá sedm bodů (Mírovka 
	&quot;B&quot; body tři), ale Česká Bělá má skóre 8:6, zatímco Sobíňov 6:5. </font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Podobná minitabulka 
	rozhodla i o sestupujících týmech. Letos totiž sestupují kvůli vývoji ve 
	vyšších soutěžích hned tři týmy a kromě posledního Herálce &quot;B&quot; a 
	předposlední Nové Vsi u Světlé zůstal černý petr také v rukách Štoků &quot;B&quot;, 
	které sice získaly stejně bodů jako Hněvkovice a Věžnice &quot;B&quot;, ale jeden 
	jediný rozdílový gól je v rámci minitabulky poslal o soutěž níž. Na rozdíl o 
	sestupu bylo o<span lang="en">&nbsp;</span>postupu Golčova Jeníkova rozhodnuto už 
	dávno, tým ze západního okraje okresu postoupil zpět po roce do Okresního 
	přeboru zcela zaslouženě. Z Okresního přeboru sestupují do III.třídy týmy 
	Dolního Města a Lípy &quot;B&quot;, ze čtvrtých tříd postupují týmy Chotěboře &quot;C&quot; a 
	Šmolov.</font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Nejoblíbenějším 
	soupeřem Sobíňova byl ve skončené sezóně celek Tisu &quot;B&quot;, který na podzim 
	doma utrpěl debakl 0:8 a na jaře prohrál na hřišti v Sobíňově 0:6. Naopak 
	dvě porážky pro Sobíňov přinesly zápasy s Golčovým Jeníkovem (1:5 a 1:3), s 
	Pohledem &quot;B&quot; (0:3 a 1:2) nebo třebas s Keřkovem (2:4 a 0:3).</font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Na hřišti se během 
	celé sezóny včetně gólmanů objevilo 21 hráčů. Všech 26 zápasů odehrála 
	trojice D.Říčan, T.Štěrba a M.Vopršal. Jednou absentovali J.Petruželka a 
	O.Vopršal.&nbsp; V bráně se dvaadvacetkrát objevil P.Veselý a ve čtyřech 
	zápasech (shodou okolností vždy vítězných) za něj zaskočil trenér 
	Z.Wasserbauer.</font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Produktivita týmu má 
	v letošní sezóně jednoho jasného vládce- je jím J.Ondráček, který vstřelil 
	celkem 25 gólů a na dalších 17 nahrál, do kanadského bodování si tak připsal 
	parádních 42 bodů. S velkým odstupem se pak se ziskem 14<span lang="en">&nbsp;</span>kanadských 
	bodů o druhé až třetí místo dělí T.Štěrba (7+7) a M.Ondráček (6+8). </font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Do mužstva před 
	začátkem jarní sezóny přišlo několik nových hráčů, ale především ze 
	zdravotních důvodů odehráli většinou jen pár utkání. A tak zatímco na 
	začátku jara to chvílemi vypadalo tak, že se pomalu nevejdeme do kabiny, na 
	konci jarní části sezóny jsme v pár zápasech sotva postavili jedenáctku 
	zdravých hráčů do pole. </font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Doufejme tedy, že se 
	přes krátkou letní pauzu dají všichni zdravotně do pořádku, abychom na 
	podzim mohli do zápasů dalšího ročníku nastupovat v plné síle.</font></p>
	<p class="MsoNormal" align="left"><font face="Verdana">Děkujeme za podporu 
	všem fanouškům, divákům a samozřejmě i sponzorům, těšíme se na další 
	společnou sezónu...</font></p>
