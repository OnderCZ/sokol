	pozici pouze nastřelil gólmana. <br>
	Ve druhém poločase se domácí snažili tlačit dopředu, ale sami se brzdili 
	poměrně hodně nepřesnostmi a nebo jejich pokusy odvracela naše vcelku dobře 
	hrající obrana a tak se nekonal žádný velký festival gólových šancí. A když 
	už se Borová dostala až do blízkosti brány, zasáhl opět bezchybně a velmi 
	jistě působící gólman Veselý. Z našich pár náznaků brejků se též neurodilo 
	nic extra zajímavého a tak zápas doplynul až do závěrečného hvizdu 
	rozhodčího, který nám přinesl letošní první tři body.<br>
