	gólů. S podobnou formou všichni doufáme, že nejen na podzim odehraje zápasů 
	víc. Stejně tak odehrál povedený zápas i Ondra Koubek, kterého jsme si 
	doslova na poslední chvíli vypůjčili z hasičského tábora.<br>
	Z naší strany měl pak samotný zápas dva hlavní hrdiny- střelce obou branek, 
	novopečeného otce J.Ondráčka, který oslavil narození dcery dvěma paradními 
	góly z přímých kopů a gólmana Veselého, který zejména v začátku zápasu 
	chytil snad tři vyložené šance domácích. Ti totiž začali utkání mnohem lépe 
	než my- byli pohyblivější, rychlejší a fotbalovější, naštěstí pro nás však 
	neměli dostatečně přesnou a účinnou koncovku. Zhruba od dvacáté minuty se 
	pak hra vyrovnala, domácí obrana pod tlakem začala zmatkovat a nabízela tak 
	hostům šance k ohrožení branky. První gól jsme vstřelili po standardní 
	situaci, kdy šel Říčan důrazně do odraženého míče a na hranici šestnáctky 
