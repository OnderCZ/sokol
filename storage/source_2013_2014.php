	<span style="font-family:&quot;Verdana&quot;,&quot;sans-serif&quot;"><b>
	1.kolo Havlíčkova Borová &quot;B&quot; 0:2 Sobíňov (0:2)<br>
	naše góly: 2x J.Ondráček<br>
	</b>Letošní sezóna třetí třídy Havlíčkobrodska začala s několika změnami. Ze 
	čtvrté třídy kvůli nezájmu několika týmu o postup nakonec postoupily rezervy 
	Štoků a Mírovky, tj. třetí a pátý tým loňské čtvrté třídy. Z Okresního 
	přeboru sestoupil tým Golčova Jeníkova, a naopak do něj postoupili hned 
	první tři týmy loňské tabulky třetí třídy- Veselý Žďár, Okrouhlice a Dolní 
	Město. Vedení ČMFS odhlasovalo změnu pravidel, kdy se v nižších soutěžích 
	zvýšil počet maximálně možných střídání až na pět hráčů, z čehož by 
	teoreticky mohly nejvíce profitovat týmy, které mají &quot;A&quot; i &quot;B&quot; mužstvo. <br>
	Tato změna pravidel však asi nebude mít příliš velký vliv na naše mužstvo, 
	neboť hned na první zápas jsme jen těžko dávali dohromady jedenáct hráčů. 
	Naštěstí se nám nakonec povedlo ke startu umluvil Davida Vránu, který přitom 
	chtěl loni ukončit kariéru a dobře jsme udělali- na hrotu útoku odehrál 
