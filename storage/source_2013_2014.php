	šťastně. Střídající Vrána byl na hřišti zhruba dvě minuty, když prodloužil 
	do vápna míč po rohovém kopu Sobíňova. Ten poté spadnul přesně na nohu 
	hostujícího beka od kterého se odrazil za záda tentokrát už zcela bezmocného 
