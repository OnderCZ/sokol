	<span style="font-family: Verdana,sans-serif"><b>14.kolo Sobíňov 4:2 
	Havlíčkova Borová &quot;B&quot;<br>
	naše góly: J.Ondráček 3x, Kafka<br>
	</b>V posledním zápase sezóny už ani jednomu ze soupeřů o nic nešlo. Přesto 
	se hrál celkem zajímavý fotbal, zřejmě i díky tomu, že se nám do sestavy 
	vrátilo pár absentérů z minulých kol. Hosté byli prvních dvacet minut utkání 
	aktivnější, zdobil je především velmi rychlý přechod do útoku a přesně po 
	jedné takové akci se dostali i do vedení, kdy se přesnou střelou na zadní 
