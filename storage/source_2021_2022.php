<p class="MsoNormal"><strong>Hodnocení sezóny 2021/2022</strong><br />
<br />
postup do OP: Jeřišno, Keřkov<br />
sestup z OP: Habry "B" (nucený sestup, jejich "A" tým spadl z I.B třídy), Okrouhlice 
(nepřihlásili nakonec žádnou soutěž), Dolní Město<br />
<br />
sestup do IV. tříd: Vepřová, Veselý Žďár, Víska<br />
postup z IV. tříd: Chotěboř "C", Tis "B", Hněvkovice<br />
<br />
Sezóna 2021/2022 byla první kompletně dohranou sezónou po dvou letech 
nedohraných soutěží. Sobíňov v ní získal celkem 41 bodů za 12 výher, 5 remíz a 9 
proher, čímž jsme si vlastně jen o jednu příčku (a o pět získaných bodů) 
pohoršili oproti poslední kompletně dohrané sezóně 2018/2019. V té jsme tehdy 
skončili třetí za postupující Českou Bělou a Šlapanovem se ziskem 46 bodů. 
Celkový zisk 41 bodů je naším třetím nejlepším bodovým ziskem ze všech deseti 
sezón ve III.třídě po sestupu z okresního přeboru- mimo již zmíněné sezóny 
2018/2019 jsme více bodů získali už jen v první posestupové sezóně 2012/2013, 
kdy jsme brali čtvrté místo za 45 bodů.<br />
<br />
Na podzim 2021 jsme získali 21 bodů ze čtrnácti zápasů (utkání s Lípou "B" jsme 
předehrávali), na jaře 2022 pak 20 bodů ze dvanácti zápasů. V domácím prostředí 
jsme získali 25 bodů (včetně jednoho zápasu na UT v Chotěboři), z venkovních 
utkání jsme si přivezli slušných 16 bodů. </p>
<p class="auto-style33">
<img alt="tabulka" height="366" src="../obrazky/2022.06-tabulka_2021_2022.jpg" width="362" /></p>
<p class="MsoNormal">Jarní část sezóny byla orámována několika historickými 
rekordy.<br />
Nejprve hned v první jarním kole 27.března 2022 odehrál Michal Vopršal svůj 
pětistý mistrovský zápas mezi dospělými.<br />
A pak v posledním jarním kole 11.června 2022 vstřelil Zdeněk Němec svůj dvoustý 
gól v mistrovských zápasech mezi dospělými.<br />
Oběma hráčům patří velká gratulace, smekáme pomyslný klobouk a přejeme, ať co 
nejdéle vydrží zdraví i střelecká forma :).<br />
<br />
O velmi dobré postavení v tabulce se tentokráte postarala především velmi 
kvalitní hra obrany. V šestadvaceti odehraných utkáních jsme dostali 49 branek, 
což nás staví na pomyslné třetí místo nejlepších obran soutěže. Vstřelili jsme 
60 branek, což znamená šestý nejlepší útok soutěže.<br />
<br />
Během sezóny jsme se museli potýkat jako už asi tradičně s velkou marodkou, na 
kratší či delší časové úseky vypadli ze sestavy Hochman, Jelínek, Kafka, 
M.Ondráček, Vrána… Na jaře jsme také nejspíš „zlomili“ náš věkový rekord, neboť 
v zápase proti rezervě Havl. Borové měla naše základní sestava průměrně 38,6 
let, poté co jsme vystřídali a na hřiště přišli i Sláva Ondráček a Petr Kodým 
nám průměr vyrostl dokonce na 41,5 let. A to nám na hrot v tomto zápase musel 
jít nestandardně pomoci Ondřej Vopršal, který nám věkový průměr snižoval.<br />
<br />
Naštěstí jsme nepočítali jen absence, ale povedlo se získat i nějaké posily. 
Adam Jablonský nás posílil už během podzimní části sezóny a do naší sbírky 
vstřelených branek přispěl celkem deseti přesnými zásahy. Vojtěch Kyzlík k nám 
před začátkem jara přestoupil z Miřetic a našel si své pevné místo v základní 
sestavě buď na kraji zálohy nebo na kraji obrany, v zápase proti Šlapanovu pak 
vstřelil i první gól za Sobíňov. Jako staronovou posilu pak samozřejmě musím 
zmínit i Járu Ondráčka, který se na své místo uprostřed zálohy vrátil do týmu v 
zápase proti Malči (předtím poslední start 15.6.2019 v zápase proti Šlapanovu) a 
v pěti zápasech do kterých nastoupil „nashromáždil“ šest gólových asistencí a 
jeden gól. <br />
<br />
Oporou jako obvykle byli i naši gólmani. Petr Veselý odchytal 22 zápasů, Zdeněk 
Wasserbauer tři kompletní a půlku čtvrtého, jeden a půl zápasu odchytal 
"univerzál" David Vrána. <br />
<br />
Hráči s největším počtem startů:<br />
1. Ve všech 26 zápasech nastoupil pouze Michal Vopršal. <br />
2. Jednou absentovali: Ivo Koutník a Tomáš Štěrba.<br />
3. Třikrát chyběl Daniel Říčan.<br />
<br />
Nejlepší střelci sezóny:<br />
