<p class="auto-style7"><strong>
<span class="auto-style25" style="line-height: 107%; mso-ascii-theme-font: minor-latin; mso-hansi-theme-font: minor-latin; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-bidi-theme-font: minor-bidi; color: black; mso-ansi-language: CS">
26. kolo Sobíňov 3:0 Věžnice "B" (3:0)<br />
</span>
<span class="auto-style25">střelci: 12. Němec Zdeněk, 26. Jablonský Adam, 43. 
Němec Zdeněk&nbsp; <br />
</span></strong><span class="auto-style25">Hosté přivezli na poslední zápas 
sezóny tým smíchaný ze starých mazáků ale i z několika mladých hráčů. Věkový 
průměr jejich základní sestavy byl tak nakonec cca o 2 roky nižší než věk 
základní sestavy Sobíňova, ať to vizuálně možná tak nevypadalo. Sobíňovu 
absentoval kvůli svatebním radovánkám obvyklý stoper Štěrba a na jeho místo se 
tak postavil David Vrána, který odehrál stejně jako zbytek obrany velmi dobrý 
zápas. Utkání začalo v netradičním čase trochu později než mělo, neboť se čekalo 
na příjezd gólmana Veselého, na hru obranné řady to ale naštěstí nemělo vliv a 
zápas jsme uhráli vzadu na nulu bez obdržené branky. Směrem dopředu se o 
ofenzívu starala obvyklá a silná sestava hráčů, proti někdy až staticky hrajícím 
hostům jsme si začali hned vytvářet šance. Ve dvanácté minutě jsme se tak 
dočkali do vedení, když po akci vedené z našeho z pravého křídla našel Říčan 
přesnou přihrávkou Němce, který stál přesně tam kde být měl a uklízel míč do 
prázdné brány- 1:0. Dvě velké šance měl pak chvíli po sobě Jablonský- nejprve po 
zpětné přihrávce Vopršala střílel nad, o chvíli později se mu míč ve vyložené 
šanci nějak podivně zamotal mezi nohama. Třetí šanci v šestadvacáté minutě už 
ale po přihrávce M.Ondráčka proměnil bez problémů a poslal tak Sobíňov do 
dvoubrankového vedení. Dvě minuty před koncem poločasu dostal přesný míč od 
J.Ondráčka opět Němec, vstřelil svou druhou branku v utkání a do sobíňovských 
historických tabulek zapsal už svůj dvoustý vstřelený gól v mistrovských 
zápasech. Neuvěřitelná statistika kterou těžko kdy někdo překoná!!!<br />
Do kabin se tak šlo za pohodového vedení 3:0. Druhý poločas začali hosté lépe 
