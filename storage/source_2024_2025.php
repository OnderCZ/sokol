<p class="auto-style2"><strong>TJ Sokol Sobíňov – sezóna 2024/2025</strong></p>
<p class="auto-style7">Sobíňovští fotbalisté se v sezóně 2024/2025 po dvanácti 
letech vrátili do Okresního přeboru, respektive do 8. ligy OFS Havlíčkův Brod, 
jak se tato soutěž nyní oficiálně nazývá. Sezóna proběhla se střídavými úspěchy 
– zejména závěr podzimu a celá jarní část byly poznamenány nedostatečnou šířkou 
kádru. Často jsme tak nastupovali pouze ve dvanácti či třinácti hráčích, což byl 
výrazný rozdíl oproti minulé, postupové sezóně. V celkové tabulce jsme nakonec 
obsadili devátou příčku, což zhruba odpovídá našemu předsezónnímu očekávání – 
tedy umístění někde uprostřed. Získali jsme celkem 31 bodů, přičemž zajímavostí 
je, že z toho jen 15 bodů pochází z domácího hřiště. V tomto ohledu jsme se 
zařadili na předposlední místo celé soutěže. Sezónu nám tak „zachránily“ body 
získané venku – konkrétně 16 bodů za pět výher a jednu remízu. </p>
<p class="auto-style7">Ani statistiky vstřelených a obdržených branek pro nás 
tentokrát nevyznívají příliš příznivě. Méně branek než my vstřelily pouze 
sestupující Věžnice a předposlední Šmolovy. A hned dvakrát jsme v sezóně utrpěli 
pořádný debakl – na podzim jsme podlehli Dlouhé Vsi 1:7 a v posledním zápase 
sezóny na jaře jsme prohráli s Novou Vsí u Světlé dokonce 2:11.</p>
<p class="auto-style7">&nbsp;Dle informací, které máme dostupné k&nbsp;dnešnímu datu 
kdy článek vzniká (20. června), by od nás do krajských soutěží měli nakonec 
postupovat dva týmy – Golčův Jeníkov a Nová Ves u Světlé. Z&nbsp;I.B třídy k&nbsp;nám 
sestoupily Štoky. Od nás do třetí třídy sestoupila Věžnice. K&nbsp;nám by naopak měla 
postoupit Mírovka „B“ a také Chotěboř „C“. </p>
<p class="auto-style7"><strong>Starty:</strong><br />
