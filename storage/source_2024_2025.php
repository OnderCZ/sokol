– Petr Veselý. Dvakrát za něj při jeho absenci zaskočil veterán Zdeněk 
Wasserbauer. Ve všech 26 zápasech sezóny se na trávníku objevila dvojice Tomáš 
Štěrba a Michal Vopršal. Jen jednou chyběl Matěj Hochman, dvakrát Marek 
Ondráček.</p>
