Nová Ves nastoupila v Sobíňově již s jistotou, že skončí po výhře Golčova 
Jeníkova v Jeřišně na druhé příčce v tabulce. A zápas v Sobíňově si hráči hostů 
velmi užili, nastříleli oslabeným domácím jedenáct branek, přičemž nejlepší 
střelec soutěže Jaromír Pešek dokonce branek pět. Hattrick zaznamenal i 
hostující Josef Novák. U domácích hrozilo, že k zápasu kvůli malému počtu hráčů 
nenastoupí, nakonec sestavu dali dohromady a poslední domácí zápas odehráli.
<br />
Nová Ves jako favorit&nbsp; zápasu si vypracovala náskok již v prvním poločase. 
Domácí v něm ještě trochu zlobili, v jejich dresu museli kvůli absencím a 
zraněním nastoupit i dva veterání, Zdeněk Wasserbauer v brance a Petr Kodým v 
poli. Střelecký den měl opět útočník hostů Jaromír Pešek, jež se v prvním 
poločase trefil dvakrát, ve 21. a ve 29. minutě. Ještě před jeho góly poprvé 
skóroval hostující Lukáš Holcman. Když dal ve 38. minutě&nbsp; krásným lobem čtvrtou 
branku hostů středopolař Josef Novák, bylo již o třech bodech jasno. Domácí však 
snížili do poločasu ještě na tříbrankový rozdíl, když úspěšným střelcem byl 
Matěj Hochman po přihrávce od Petra Kodýma ve 43. minutě. Sám Petr Kodým mohl 
být chvilku předtím slavný sám, když krásnou střelou z velké vzdálenosti trefil 
spojnici hostující brány.<br />
Ve druhém poločase již domácím došly síly a hosté rozjeli svůj brankostroj. 
Jejich branky padaly povětšinou po pěkných střelách zpoza vápna. V 51. minutě se 
trefil střídající Roman Závorka, jež nastoupil po delší pauze, po něm mířil 
přesně znovu Josef Novák. V 56. minutě korigoval stav Jaroslav Ondráček, když 
využil chyby hostující obrany a po obejití brankáře skóroval do prázdné 
branky.&nbsp;V rozmezí 59. až 70. minuty se třikrát prosadil Jaromír Pešek. V 
závěrečné desetiminutovce ještě mířili do černého Josef Novák a jako poslední 
kapitán hostů Daniel Suchý. Nová Ves tak po loňském bronzu, letos končí těsně 
druhá a za své výkony by si hráči této vísky rozhodně zasloužili hrát s Golčovým 
Jeníkovem o soutěž výše.<br />
