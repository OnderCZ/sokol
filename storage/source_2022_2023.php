<p class="auto-style2"><strong>Hodnocení sezóny 2022/2023</strong></p>
<p><span class="auto-style25">Sobíňov skončil v soutěžním ročníku 2022/2023 na 
pátém místě třetitřídní tabulky. Získali jsme celkem 43 bodů při skóre 71:55 (v 
minulém soutěžním ročníku 2021/2022 jsme skončili na čtvrtém místě se ziskem 41 
bodů při skóre 60:49). Na jaře 2023 jsme odehráli 12 zápasů, neboť zápas s 
Hněvkovicemi se předehrával již na podzim 2022 a v těchto dvanácti zápasech jsme 
získali 18 bodů za pět výher (Dolní Město, Tis "B", Maleč, Lípa "B" a Věžnice 
"B") a tři remízy (Habry "B", Havlíčkova Borová "B", Rozsochatec "B"), čtyřikrát 
jsme prohráli (Golčův Jeníkov, Ždírec n.D. "C", Chotěboř, Šlapanov).</span></p>
<p><span class="auto-style25">Z těchto zápasů mrzí zejména ztráta bodů v utkání 
s nakonec sestupujícími rezervami Habrů i Rozsochatce, na druhou stranu jsme 
měli kolikrát i kliku, když jsme třebas proti Borové ubránili v oslabení remízu 
1:1 jen s velkým štěstím nebo když Veselý v naší bráně chytil v Rozsochatci 
pokutový kop atd. Těšit nás mohou kvalitně odehrané zápasy s postupujícím 
Golčovým Jeníkovem, který většině svých soupeřů naděloval velké gólové příděly a 
nás porazil dvakrát relativně těsně 2:0, nebo třebas výhra 2:0 nad druhým Tisem 
"B".
</span></p>
<p><span class="auto-style25">Celkový zisk 43 bodů je naším třetím nejlepším 
bodovým ziskem ze všech jedenácti sezón ve III.třídě po sestupu z okresního 
přeboru. Více jsme získali jen v sezónách 2018/2019- třetí místo za 46 bodů a v 
první posestupové sezóně 2012/2013- čtvrté místo za 45 bodů. Na jaře jsme 
vstřelili jen 23 branek, tj. přesně polovinu toho co na podzim (46). Dvě branky 
si naši soupeři dali sami a tak se naše ofenzíva s celkovým počtem 71 
vstřelených branek řadí v této statistice na pomyslné čtvté místo (nejvícekrát 
skóroval Tis "B"- 132x). Za celou sezónu jsme dostali 55 gólů, což naši 
defenzivu v rámci třetí třídy řadí na páté místo (nejvíckrát lovila míč se sítě 
Věžnice "B"- 111x).
</span></p>
<p><span class="auto-style25">Jako vždy v posledních sezónách platí, že když se 
sejdeme v plné sestavě, jsme schopni zahrát kvalitní zápas s každým v naší 
soutěži. Když nám ale kvůli absencím vypadnout 2-3 hráči základní sestavy tak 
máme problém, ve hře to pak hodně skřípe a těžko se nám hraje i proti týmum ze 
spodku tabulky. Tím jak tým stárne navíc samozřejmě každé zranění trvá déle a 
tak nutně musíme kádr trochu rozšířit. Chtěli bychom tedy získat ideálně 2-3 
hráče, kteří by nám kádr doplnili.
</span></p>
<p class="auto-style25">Do okresního přeboru by měl letos dle postupových 
tabulek povyskočit jen Golčův Jeníkov, sestoupit k nám by pak z vyšší soutěže 
měla dvojice týmů- Lipnice nad Sázavou a Přibyslav "B". Do IV. tříd by měla 
sestoupit trojice Habry "B", Věžnice "B" a Rozsochatec "B", k nám by měli 
postoupit vítězové čtvrtých tříd, tj. Štoky "B" a Lučice "B". Zasáhnout do toho 
ale samozřejmě mohou jako každý rok různé mimotabulkové posuny, odhlášky soutěží 
atd., uvidíme tedy jak moc se naše soutěž do soutěžního ročníku 2023/2024 reálně 
obmění. Letní pauza bude jako vždy krátká, nový soutěžní ročník se začne 
pravděpodobně hrát stejně jako obvykle první srpnový víkend, tj. 5-6/8. </p>
