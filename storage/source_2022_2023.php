</span>
<span class="auto-style25">střelci: 28. Kopečný Jan, 45. Kopečný Jan, 51. Špaček 
Jiří - 16. Němec Zdeněk, 19. Ondráček Marek, 49. Říčan Daniel, 73. Říčan Daniel <br />
</span>
</strong><span class="auto-style25">Na krásně připraveném hřišti ve Věžnici jsme 
odehráli poslední zápas sezóny 2022/2023 a pro cca 70 přítomných diváků to byla 
celkem zajímavá podívaná. Po trošku neurovnaném začátku utkání jsme se během 
pěti minut dostali do dvoubrankového vedení. V šestnácté minutě vyslal pěknou 
kolmici skrz soupeřovu obranu Vopršal a Němec z úhlu možná trochu překvapil 
domácího gólmana střelou na přední tyč- 1:0. O tři minuty později po pěkné 
kombinaci po pravé straně Němec centrem našel na vzdálenější tyči M.Ondráčka, 
který rozvlnil síť podruhé- 2:0. V pětadvacáté minutě poslat rozhodčí oba týmy 
vzhledem k panujícímu počasí na občerstvovací pauzu a ta nám rozhodně nepomohla. 
Hned po rozehrávce jsme totiž spáchali první velkou chybu v rozehrávce a Kopečný 
v samostatném nájezdu nezaváhal- 2:1. Domácí zahrozili i několika pěknými 
