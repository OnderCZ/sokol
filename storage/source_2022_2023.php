<p class="MsoNormal"><strong>Podzim 2022</strong></p>
<p class="MsoNormal">Do naší v pořadí už jedenácté sezóny ve třetí třídě 
havlíčkobrodského okresu jsme vstupovali bez jakýchkoliv změn v hráčském kádru. 
Nikdo nepřibyl, naštěstí oproti jaru nikdo ani neubyl. Během podzimu se nám 
navíc vyhnuly i nějaké dlouhodobější zdravotní problémy, a tak jsme byli schopni 
téměř vždy postavit kvalitní základní jedenáctku. Soutěž se hodně obměnila, 
přibyla nám hned pětice (staro)nových soupeřů – Habry „B“, Dolní Město, Chotěboř 
„C“, Tis „B“ a Hněvkovice.&nbsp; </p>
<p class="MsoNormal">Podzimní část sezóny jsme začali velmi dobře, v prvních 
třech zápasech jsme zvítězili a brali tak plný počet devíti bodů. Pak jsme ale 
dostali šest gólů v Tisu, který se svou posílenou rezervou předváděl celý podzim 
hodně kvalitní výkony. V prostřední části sezóny jsme střídavě prohrávali a 
vyhrávali, nejhorší porážku jsme museli strávit na začátku října, když jsme 
dostali sedm gólů v Chotěboři. Nejvíce se nám střelecky zadařilo naopak koncem 
října proti rezervě Věžnice, která domů odjížděla s přítěží osmi gólů.&nbsp;&nbsp; </p>
<p class="MsoNormal">Na špičce tabulky se po kompletním podzimním programu a 
předehrávce prvního jarního kola nachází Golčův Jeníkov, který oproti minulým 
letům omladil i zkvalitnil kádr a během čtrnácti zápasů pouze jednou prohrál 
v Tisu. A právě Tis „B“ je na druhém místě tabulky, ten prohrál dvakrát – 
v Chotěboři a ke konci podzimu překvapivě i v Hněvkovicích. &nbsp; &nbsp;</p>
<p class="MsoNormal">Sobíňov přezimuje na rozmezí pátého a šestého místa 
tabulky. Pátí jsme dle rozdílu ve skóre, šestí, když zohledníme náš vzájemný 
zápas s Lípou „B“ - 1:4. A nutno říct, že tabulka tentokráte vcelku přesně 
ukazuje naši výkonost – se všemi týmy co jsou v tabulce nad námi jsme prohráli 
(včetně Lípy), všechny týmy, které jsou v tabulce pod námi jsme naopak 
porazili.&nbsp; O postup se zdá se bude prát dvojice Golčův Jeníkov a Tis „B“, 
Chotěboři „C“ trochu uškodil horší závěr podzimu, o překvapení se bude na jaře 
pokoušet i oproti minulým letům zkvalitněná rezerva Havl. Borové. V sestupových 
vodách jsou naopak hodně namočeny rezervy Rozsochatce (jejich „A“ tým přitom 
hraje oblastní „A“ třídu, i když je tam pravda na sestup) a trochu překvapivě i 
Habrů, která k nás nuceně sestoupila v létě z okresu.&nbsp; </p>
<p class="MsoNormal">Loni jsme touto dobou po stejném počtu odehraných zápasů 
byli na šestém místě tabulky se ziskem 21 bodů při skóre 34:24, v současné 
sezóně jsme tedy získali o čtyři body více, vstřelili jsme o třináct branek víc, 
a obdrželi jsme o jedenáct branek víc. V soutěži se oproti dřívějšku prohloubily 
rozdíly mezi jednotlivými týmy, které vedou k divokým výhrám o 5, 6, 7 i víc 
branek – rekordní výhru si připsala Chotěboř „C“ která ve čtvrtém kole doma 
porazila Šlapanov 11:2. Prvnímu Golčovu Jeníkovi vychází průměr k šesti 
vstřeleným brankám na zápas, a to je věc dříve nevídaná.&nbsp;&nbsp;</p>
<p class="MsoNormal">Na jaře se určitě budeme muset obejít bez Vojty Kyzlíka, 
který přestupuje do Keřkova a bude nám v základní sestavě chybět. Uvidíme tedy, 
jestli se nám podaří zlanařit nějakou posilu. Sice jsme se během podzimu utkali 
se staršími týmy než jsme aktuálně my (Šlapanov, Věžnice „B“), ale hráčů okolo 
čtyřiceti let či víc máme v kádru opravdu dost, chtě nechtě tedy budeme muset 
začít věkovou obměnu.&nbsp; Jarní část sezóny začne pravděpodobně o víkendu 1-2. 
dubna 2023, máme tedy před sebou jako obvykle dlouhou několikaměsíční zimní 
pauzu. </p>
