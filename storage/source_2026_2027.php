<span class="auto-style25">
<strong>
střelci:&nbsp;9. Bělovský Michal, 39. Hudec Jan, 52. Veselý Vojtěch, 82. Císař Jan&nbsp; <br />
</strong>Po vysoké domácí výhře nad oslabenou rezervou Ledče jsme tentokrát 
zajížděli na hřiště vedoucí Chotěboře „C“, kde nás čekala podstatně těžší 
prověrka. Do utkání jsme nastoupili v ne úplně tradičním rozestavení 3-5-2, na 
které zkušení domácí od začátku zareagovali. Na velkém a širokém hřišti 
využívali při přechodu do útoku především krajní prostory a vzhledem k tomu, že 
jsme jim nechávali až příliš mnoho volného místa a nevyhrávali ani osobní 
souboje, měli od začátku utkání převahu. Do vedení šla Chotěboř v 9. minutě. Po 
autovém vhazování jsme nedokázali včas zareagovat na následný centrovaný míč a 
Michal Bělovský otevřel skóre – 1:0. My jsme se během první půle dostávali k 
ohrožení domácí brány jen velmi sporadicky a vyloženou šanci jsme po odraženém 
míči měli snad jednu či dvě. Ve 39. minutě jsme navíc přišli o míč ve středu 
hřiště, domácí rychle přešli do protiútoku a Jan Hudec zvýšil na 2:0. <br />
Ani začátek druhého poločasu nám příliš nevyšel. V 52. minutě si Vojtěch Veselý 
po dalším nedůrazu pohrál s naší obranou a zvýšil už na 3:0. Chotěboř měla 
utkání pod kontrolou a víceméně se hrálo jen o to, kolik branek nám ještě 
vstřelí. My jsme se směrem dopředu prosazovali jen velmi obtížně a ve druhé půli 
jsme domácí branku výrazněji ohrozili prakticky jen dvěma střelami z hranice 
pokutového území. Definitivní podobu výsledku dal v 82. minutě Jan Císař, který 
vstřelil čtvrtou branku domácích – 4:0. O chvíli později se po hezké akci 
radoval ze snížení na 4:1 Filip Štolfa po přihrávce Jáchyma Kampa, radost nám 
ale překazil zvednutý praporek asistenta rozhodčího, a stav se tak už nezměnil. 
Z Chotěboře jsme tedy odjeli s poměrně jasnou a zaslouženou porážkou. Kvalitnímu 
soupeři jsme nechávali až příliš mnoho prostoru, čehož domácí dokázali využívat. 
Směrem dopředu jsme si navíc vytvořili jen minimum příležitostí, takže jsme 
tentokrát neměli příliš možností zápas výsledkově zdramatizovat. <br />
<em>sestava: Š. Kamp - zprava T. Štěrba, T. Hocke, A. Jablonský - M. Ondráček 
(P. Kafka), J. Ondráček (A. Janata), D. Říčan, D. Polánský, M. Hochman (J. Kamp) 
- Z. Němec (I. Koláček), V. Vepřovský (F. Štolfa) </em><br />
</span></p>
<p class="auto-style7">
<span class="auto-style25" style="line-height: 107%; mso-ascii-theme-font: minor-latin; mso-hansi-theme-font: minor-latin; mso-bidi-font-family: &quot;Times New Roman&quot;; mso-bidi-theme-font: minor-bidi; color: black; mso-ansi-language: CS">
<strong>09. kolo Sobíňov 6:0 Ledeč nad Sázavou "B" (2:0)<br />
</strong>
</span>
<span class="auto-style25">
<strong>
střelci:&nbsp;19. Říčan Daniel, 33. Ondráček Marek, 53. a 84. Němec Zdeněk, 58. 
Polánský David, 85. Ondráček Jaroslav <br />
</strong>Po čtyřech porážkách a následné remíze v Tisu jsme se konečně dočkali 
vítězství – a tentokrát pořádného. Rezervu Ledče nad Sázavou jsme doma porazili 
6:0 a po delší době si užili zápas, ve kterém s přibývajícími minutami nebylo 
otázkou, zda body zůstanou v Sobíňově, ale spíš kolik branek hostům přibalíme na 
cestu domů. Ledeč přijela ve značně oslabené a velmi mladé sestavě. Už ve středu 
před zápasem nás soupeř kontaktoval s prosbou o přesunutí utkání na 28. října, 
na náhradním termínu jsme se ale nakonec nedomluvili. Hosté tak museli využít 
řadu dorostenců, z nichž někteří měli navíc v nohách už dopolední zápas. Od 
začátku jsme byli aktivnějším a nebezpečnějším týmem. Hosté si v prvním poločase 
vytvořili jen dvě příležitosti, se kterými si jistý Štěpán Kamp poradil. Skóre 
jsme otevřeli v 19. minutě. Jára Ondráček připravil míč Danielu Říčanovi a náš 
kapitán utaženou střelou zpoza vápna k tyči nedal brankáři Pavlu Malimánkovi 
šanci – 1:0. Ve 33. minutě přišel druhý zásah. David Polánský poslal kolmici za 
obranu na Marka Ondráčka, který zakončil přesnou střelou kolem gólmana – 2:0. 
Ještě před přestávkou jsme mohli přidat třetí branku, hostující gólman ale 
střelu směřující do odkryté brány výborným zákrokem pokryl.<br />
Po změně stran se obrana Ledče začala zejména ve středu hřiště hodně otevírat a 
vznikajícího prostoru jsme dokázali využívat. V 53. minutě vyslal Marek Ondráček 
kolmicí za obranu Zdeňka Němce a ten zvýšil na 3:0. O pět minut později přišla 
velmi podobná situace. Tentokrát poslal za obranu Davidu Polánskému přesnou 
přihrávku Jára Ondráček. První zakončení ještě hostující brankář zlikvidoval, 
dorážku už ale David dostal do sítě – 4:0. Další góly přišly v závěru. V 84. 
minutě vyslal Matěj Hochman krásným dlouhým pasem z vlastní poloviny do úniku 
Zdeňka Němce, který nadvakrát vstřelili svou druhou branku v utkání. A prakticky 
hned po rozehrání jsme skórovali znovu. Situaci čtyři na dva rozehrál David 
Polánský do křídla na Pavla Kafku, ten vrátil míč pod sebe a Daniel Říčan ho 
chytře pustil mezi nohama na nabíhajícího Járu Ondráčka. Ten celou pohlednou 
akci zakončil šestou brankou – 6:0. Výsledek mohl být ještě výraznější. Několik 
dalších příležitostí jsme neproměnili a jen Jáchym Kamp měl během zápasu snad 
tři možnosti na gól. Tentokrát nás to ale mrzet nemuselo.<br />
Po pěti utkáních bez vítězství jsme tak zabrali tím nejlepším možným způsobem. 
Hosté sice přijeli výrazně oslabeni a jejich mladé sestavě postupně docházely 
