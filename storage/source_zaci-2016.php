<p>
	<strong>Zhodnocení sezóny žáků 2016/2017</strong></p>
<p class="auto-style2" style="mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: CS">
S letošní fotbalovou sezónou mladších žáků se Sobíňov rozloučil domácím utkáním 
se Šlapanovem, které skončilo výsledkem 6:5 (2:4). V tomto utkání nastoupil i 
teprve čtyřletý Kryštof Němec, který při dovednostní soutěži po utkání proměnil 
svoji penaltu. Chtěl bych touto cestou poděkovat všem, kteří nás nejen v&nbsp;tomto 
zápase podporovali. Právě v utkání se Šlapanovem se ukázala velmi důležitá 
podpora rodičů a fanoušků, kteří na začátku druhého poločasu za stavu 2:5 začali 
hnát své „miláčky“ kupředu a jak bylo vidět, dětem to velmi pomohlo a semknutým 
výkonem dokázali zápas otočit. Myslím, že toto je cesta v případě dalšího 
pokračování žáků v&nbsp;soutěžích- podpora rodičů a fanoušků, čím intenzivnější, tím 
lepší. <o:p></o:p></p>
<p class="auto-style2" style="mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: CS">
Celkově tým žáků v sezóně 2016/2017 odehrál 16 zápasů s konečným umístěním na 
sedmé příčce tabulky při zisku dvanácti bodů, což považuji pro náš velmi mladý a 
nezkušený tým za úspěšnou sezónu. <o:p></o:p></p>
<p class="auto-style2" style="mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: CS">
Po této sezóně nás opouští Petr Horvát, Erika Horvátová a Michaela Valentová, 
všem třem moc děkuji za vše, co pro náš fotbal dělali a přeji hodně úspěchů i 
nadále. <o:p></o:p></p>
<p class="auto-style2" style="mso-fareast-font-family: &quot;Times New Roman&quot;; mso-fareast-language: CS">
Na závěr bych všechny rád pozval na turnaj do Šlapanova, který se koná v&nbsp;sobotu 
15.7.2017 od devíti hodin. Tým žáků tam odehraje pět zápasů s týmy Šlapanova, 
Úsobí, Kněžic, Jamné „A“ a Jamné „B“. <o:p></o:p></p>
<p class="auto-style3">Michal Moldavčuk</p>

