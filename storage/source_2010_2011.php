<p class="MsoNormal"><b><span style="font-family: Verdana,sans-serif">26. kolo 
Leština 3:2 Sobíňov (1:0)<br>
naše góly: P.Kafka, T.Zrzavý<br>
</span></b>Zápas jsme začali za vytrvalého deště aktivně, první tři šance se 
urodili na našem kontě. Kafka však po rohu a standardní situaci nedokázal ani 
jednou hlavou trefit bránu domácích a podobně se vedlo i Zrzavému, který se 
hezky obtočil kolem obránce, ale jeho střela minula vzdálenější tyč brány snad o 
půl metru. Do vedení tak šla těsně před poločasem Leština, kdy se po naší chybě 
ve středu hřiště dostali do brejku dva hráči domácích a šanci dokázali dokonale 
zužitkovat-0:1.<br>
Po poločase jsme se snažili pokračovat v aktivní hře a dočkali jsme se i 
vyrovnání, i když se to stalo dost šťastným způsobem- V.Starý zahrával 
standardní situaci poblíž velkého vápna Leštiny, jeho střela trefila uhýbajícího 
Kafku do hlavy a od ní míč zamířil přesně k tyči domácí brány- 1:1. Domácí poté 
přidali, a začali nás i díky naší zbytečné pasivitě, kdy jsme snad chtěli bránit 
remízu, přehrávat. Výsledkem byl druhý gól v naší síti, který padl velmi 
podobným způsobem jako ten náš vyrovnávací- útočník domácích tečoval přímý kop 
hlavou tak, že míč obloukem zapadl těsně pod břevno naší brány- 1:2. O chvíli 
později navíc Leština odskočila do ještě většího rozdílu, kdy se v situaci na 
hranici offsidu prosadili domácí potřetí-1:3. Parádní střelu M.Vopršala poté 
vytáhl výborně chytající domácí gólman na roh a do konce zápasu zbývalo cca deset 
minut... Hlasatel oznámil stav souběžně hraného zápasu v Ledči, kde Rozsochatec 
vedl 1:0 a nám v té chvíli nebylo zrovna moc veselo. Přesto jsme ještě zkusili 
zabojovat, a výsledkem byl gól Zrzavého, který si perfektně naskočil na centr V.Starého 
z rohového kopu- 2:3. Vyrovnat se nám však již nepodařilo a tak jsme šli do 
kabin s vědomím toho, že se pravděpodobně vyplnil černý scénář a Rozsochatec se 
před nás v tabulce dostane. Naštěstí se o chvíli později ukázalo, že to není 
pravda, neboť ledečská rezerva dokázala zhruba deset minut před koncem vyrovnat 
na 1:1 a zachránila nám tak naše dvanácté místo v tabulce. V posledním zápase 
výsledkově nepříliš povedené sezóny jsme herně navázali na celkem slušně 
odehrané poslední zápasy (remíza s Ranskem, Rozsochatcem a Přibyslaví, výhra nad 
Šlapanovem), na body to však tentokráte nestačilo.&nbsp; <br>
