T.Zrzavý, Z.Němec – T.Štěrba, M.Ondráček(J.Ondráček)</span></p>
<p class="MsoNormal"><br>
<u>Situace v&nbsp;tabulce:</u><br>
Šlapanovu jsme díky výhře odskočili na čtyřbodový rozdíl a v&nbsp;tabulce se tak už 
před nás nemůže dostat. Rozsochatec dokázal nakonec zremizovat divoké domácí 
utkání s&nbsp;rezervou Světlé, během kterého prohrával už 2:5 na konečných 5:5 a 
aktuálně na nás tedy ztrácí dva body. Pokud uhrajeme v&nbsp;Leštině minimálně bod, 
nebo Rozsochatec nezvítězí na hřišti ledečské rezervy, neskončíme v&nbsp;tabulce 
horší než třetí od konce. <br>
<br>
Stále není jasné, kolik týmů bude z&nbsp;Okresního přeboru padat níže. V&nbsp;„B“ třídě 
prohrála ždírecká rezerva záchranářský duel v&nbsp;Pacově vysoko 0:6 a je tak prvním 
jasným sestupujícím. O další sestupové místo či místa však bude ještě boj, neboť 
hned tři týmy mají shodně 28 bodů- Lukavec, Chotěboř „B“, Pacov „B“, a&nbsp;další dva 
týmy mají pouze o dva body více- Budíkov a Lípa. Chotěboř „B“ jede v&nbsp;posledním 
kole právě do Budíkova a pokud tam vyhraje, neměla by z&nbsp;bé třídy spadnout. Lípa 
hostí v&nbsp;posledním kole doma Pacov „B“ a určitě nebude chtít prohrát, neboť by 
tak mohla zkomplikovat postup své rezervy z&nbsp;III.třídy do Okresu (áčko a béčko 
nemohou hrát stejnou soutěž, pokud by tak tedy nějakou shodou okolností Lípa z 
bé třídy spadla, nemohlo by její béčko postoupit ze III.třídy).<br>
