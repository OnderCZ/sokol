<p class="MsoNormal">Vítězem ročníku se stala Lučice, která tak v&nbsp;příští sezóně ochutná krajské trávníky v&nbsp;I. 
B třídě, ze které sestoupila do Okresního přeboru rezerva Ždírce nad Doubravou. 
Šlapanov se po roce vrací zpět do III.třídy, odkud ho nahradí „bé“ mužstvo Lípy.<br>
<br>
V&nbsp;brance Sobíňova se v&nbsp;tomto ročníku objevoval hlavně P.Veselý, kterého pouze na 
jeden zápas vystřídal Z.Wasserbauer.&nbsp; V&nbsp;poli se vystřídalo rekordních 24 hráčů, 
přičemž ani v&nbsp;jediném ze šestadvaceti utkání nechyběl M.Vopršal. Pětadvacet 
zápasů pak mimo již zmíněného P.Veselého odehrál ještě D.Říčan a T.Štěrba, 
dvakrát chyběl P.Kafka a V.Starý.&nbsp; Tři absence si připsal Z.Němec, M.Ondráček a 
O.Starý, hranici dvaceti startů překonal ještě J.Petruželka. <br>
<br>
Nejlepšími střelci týmu se s&nbsp;devíti brankami stali P.Kafka a Z.Němec, šest 
branek vstřelil M.Ondráček. <br>
Nejvíce asistencí si zapsal Z.Němec (10x), druhé místo v&nbsp;této statistice obsadil 
M.Ondráček (7x), třetí byl P.Kafka(5x).</p>
