<p class="MsoNormal">&nbsp;Po podzimu jsme vstupovali do druhé části sezóny 
s&nbsp;vědomím, že bodů na kontě moc nemáme a bylo by tedy záhodno s&nbsp;jejich sběrem co 
nejdříve. To se nám bohužel i přes velmi nadějné výsledky ze zimní přípravy 
nedařilo a hned v&nbsp;prvním kole jsme doma nedokázali porazit Světlou, která zcela 
určitě byla hratelná. Na Ledeč a Lipnici jsme neměli, Jeřišno jsme poté porazili 
s&nbsp;notnou dávkou štěstí a následující dva domácí zápasy s&nbsp;Veselým Žďárem a 
Golčovým Jeníkovem definitivně rozhodly o tom, že se opět budeme zachraňovat do 
poslední ho kola.&nbsp; Lučice byla přes slibný začátek zápasu nad naše síly a tak 
nás paradoxně k&nbsp;lepším výkonům popohnal až zasloužený debakl v&nbsp;Mírovce. Bohužel 
remíza je v&nbsp;tříbodovém systému málo a to se ukázalo v&nbsp;následujících kolech, kdy 
jsme ji uhráli třikrát po sobě (navíc s&nbsp;totožným výsledkem 1:1). Z&nbsp;toho jsme se 
dvakrát měřili se soupeři ze spodních příček tabulek, a dvakrát jsme hráli doma, 
moc plusových bodů nám to tedy do tabulky nepřineslo- nakonec měl ale každý 
jeden bod cenu zlata. Jasná výhra nad Šlapanovem přišla více než vhod, ale kvůli 
prohranému zápasu posledního kola v&nbsp;Leštině jsme stejně byli odkázáni na 
výsledky ostatních mužstev nejen v&nbsp;Okresním přeboru ale i&nbsp;v&nbsp;I.třídě.&nbsp; Nakonec 
jsme se podruhé za sebou dokázali velmi těsně zachránit, tentokráte 
s&nbsp;pouhopouhými devatenácti body za pět výher a čtyři remízy (v předchozí sezóně 
2009/2010 spadlo z&nbsp;OP Dolní Město s&nbsp;29ti body což by letos stačilo na osmé 
místo)…</p>
