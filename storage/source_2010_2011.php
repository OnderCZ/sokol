<p class="MsoNormal"><b><span style="font-family: Verdana,sans-serif">25. kolo 
Sobíňov 5:0 Šlapanov (4:0)<br>
naše góly: Z.Němec 2x, P.Kafka 2x, J.Ondráček<br>
</span></b>Předposlední kolo letošní sezóny přineslo přímý záchranářský duel 
s&nbsp;posledním Šlapanovem, který na nás ztrácel jenom bod a na podzim nás dokázal 
porazit 4:1. V&nbsp;domácím zápase jsme ale ovšem naštěstí byli od začátku lepším 
týmem a hned ve čtvrté minutě jsme se dostali do vedení, když celé obraně hostí 
po hezké přihrávce Zrzavého utekl Němec. Udělal kličku i gólmanovi a zakončil do 
prázdné brány- 1:0. Chvíli se poté hrálo spíše ve středu hřiště bez výraznějších 
šancí, a pak došlo k&nbsp;možná rozhodujícím situacím celého zápasu. Hosté se dostali 
k&nbsp;rohovému kopu, hlavičkující hráč ovšem těsně minul pravou tyč naší brány. 
V&nbsp;podstatě z&nbsp;protiútoku pak Němec zatáhl míč po levé straně, na hraně vápna 
našel Kafku, který míč zpracoval a poté ho poslat podél vybíhajícího brankáře 
hostí do brány podruhé- 2:0. Hosté se i nadále snažili držet krok, s&nbsp;vědomím 
dvougólové ztráty však poměrně lehce ztráceli balóny a nám se navíc nebývale 
dařila kombinace. Výsledkem byl třetí gól v&nbsp;síti hostů, kdy se po další 
přihrávce Zrzavého opět nemýlil Němec- 3:0. Čtvrtý zápis do střelecké listiny 
jsme si nechali až na samotný konec poločasu, kdy Zrzavý po standardní situaci a 
nákopu do vápna důrazně vybojoval míč pro Kafku, který uzavřel poločasové skóre 
na 4:0. Zajímavostí poločasu je i to, že všechny čtyři góly padly po střele 
levačkou, tedy nohou, kterou obvykle oba úspěšní střelci mívají pouze na 
opírání… <br>
Ve druhém poločase už jsme se nikam nehnali, s&nbsp;vědomím toho, že hlavně nechceme 
udělat chybu, jsme se soustředili spíše na držení míče než na přímé ohrožování 
hostující brány. Dobrá úroveň utkání, které sledovalo na Okresní přebor úžasných 
150 diváků tak trochu opadla, nebylo se však příliš čemu divit, neboť Šlapanov 
za celou druhou půli nevymyslel vůbec nic. Šance tak přibývaly jenom na naší 
straně, M.Ondráček však po přihrávce Štěrby ve vyložené pozici nastřelil 
hostujícího gólmana, Kafka hlavičkoval nad a střela Slámy z&nbsp;dobré pozice po 
hezké individuální akci se mezi tyče též nevešla. Na hřiště se na naší straně 
dostali i dva navrátilci ze studijních pobytů v&nbsp;zahraničí a J.Ondráček oslavil 
svůj návrat na sobíňovský trávník stylově gólem ze standardní situace, kdy 
v&nbsp;samotném závěru utkání přesně trefil skulinku vedle postavené zdi hostů- 5:0.<br>
Povzbuzeni rychlým gólem jsme tak sehráli velmi povedené utkání, jehož zejména 
první poločas se musel všem přítomným (pokud tedy nepatřili mezi početné 
fanoušky hostů) líbit. Celý tým sehrál velmi dobré utkání, nejlepšími hráči byli 
Z.Němec, T.Zrzavý a T.Štěrba.<br>
