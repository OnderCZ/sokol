<p class="MsoNormal"><u>Situace v tabulce:<br>
</u>Po posledním kole jsme skončili na dvanáctém místě tabulky Okresního 
přeboru(OP) s jednobodovým náskokem na dvojici Rozsochatec, Šlapanov. 
Rozsochatec má se Šlapanovem lepší vzájemné zápasy (dvě nejtěsnější vítězství 
