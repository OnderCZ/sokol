	<p class="MsoNormal" align="left"><strong>Zhodnocení sezóny 2015/2016</strong></p>
	<p class="MsoNormal" align="left">Fotbalový tým Sokola Sobíňov hrál čtvrtým 
	rokem v řadě III. třídu okresu HB a byl po podzimní části sezóny se 
	šestnácti body (skóre 21:23) na devátém místě tabulky, přičemž měl stejný 
	bodový zisk jako týmy na osmém a sedmém místě. V jarní části však přišlo jak 
	tabulkové, tak hlavně herní zlepšení, které nakonec přineslo Sobíňovu velmi 
	slušné páté místo. Během jarní části soutěže totiž &quot;Sokoli&quot; nasbírali na 
	hřištích 22 bodů při aktivním skóre 33:20. <br><br>Hodně tomu samozřejmě 
	pomohl zimní návrat Járy Ondráčka z hostování v Chotěboři, který ve 
	vyrovnaných zápasech pomohl svou kombinační zdatností a klidem v rozehrávce. 
	Celý tým ale několikrát dokázal uhrát body i ve velmi poslepované sestavě a 
	tak byl po zásluze oceněn posunem tabulkou směrem vzhůru. Pokud už bych měl 
	někoho vyzvednout (na základě zápasů které jsem viděl/hrál na vlastní oči), 
	tak se do výborné formy rozehrál mimo dalších hlavně Dan Říčan, který ke své 
	neúnavnosti a důrazu ve středu hřiště přidal i střílení důležitých gólů a 
	stal se tak pilířem hry celého družstva.<br><br>Oproti loňským sezónám 
	přivezli sobíňovští fotbalisté hodně bodů ze hřišť soupeřů, o čemž svědčí i 
	páté místo při 15ti získaných bodech v tabulce venkovních zápasů, v zápasech 
	domácích získal Sokol 23 bodů a skončil na sedmém místě této dílčí tabulky. </p>
	<p class="MsoNormal" align="left">Z Okresního přeboru sestoupilo do III. 
	třídy Jeřišno.&nbsp;Do Okresního přeboru postupuje Chotěboř &quot;C&quot; a také z druhého 
	místa Keřkov. <br>Do IV. třídy sestupuje Pohled &quot;B&quot;. Ze IV. tříd měli 
	postupovat Víska a Kouty, ale Kouty se to rozhodli přenechat Havlíčkovu 
	Brodu &quot;C&quot;, který v &quot;B&quot; skupině IV.&nbsp;třídy skončil na druhém místě s velmi 
	zajímavým vysoce aktivním skóre 157:28- čeká nás tedy v utkání s ním zřejmě 
	velmi slušná ofenzivní síla.<br></p>
	<p align="left"><strong>Statistický přehled sezóny</strong></p>
	<p align="left">Na hřišti se během sezóny objevilo celkem 25 hráčů. Dva z 
	toho byli gólmani- Petr Veselý odchytal spolehlivě 23 utkání a v mnoha z 
	nich nás podržel. Ještě lepší statistiky má ale Zdeněk Wasserbauer, který 
	šel do brány na poslední dva zápasy sezóny a oba dva vyhrál :).</p>
	<p align="left">&nbsp;Všech 26 zápasů odehrála trojice hráčů: J. Hečko, T. 
	Štěrba a M. Vopršal. Již zmíněný P. Veselý odehrál 24 zápasů.</p>
