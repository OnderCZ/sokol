</span>
</strong><span class="auto-style25">Vedoucí tým tabulky Tis "B" už měl všechny 
své zápasy odehrané, takže jsme už před utkáním věděli, že v tabulce nemůžeme 
skončit lépe než druzí. Třetí Chotěboř "C" na nás ztrácela tři body a měla lepší 
vzájemné zápasy, pro udržení druhého místa jsme tedy museli minimálně remizovat. 
Hosté ale přijeli ve znatelně oslabené sestavě a moc jim nepomohl ani Průša, 
který se nechal hned v páté minutě utkání naprosto nesmyslně vyloučit za 
oplácení. Celý zápas se pak hrálo víceméně na jednu branku, Sobíňov měl moře 
šancí a otázkou zůstávalo jen to, jestli nakonec padne desítka stejně jako na 
