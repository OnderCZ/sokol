<p class="auto-style7">Sobíňovští fotbalisté za sebou mají velmi úspěšný 
soutěžní ročník 2023/2024. Po dvanácti sezónách strávených v&nbsp;třetí třídě 
havlíčkobrodského okresu se nám dokonce s&nbsp;trochou nezbytného štěstí podařilo 
postoupit do Okresního přeboru, který jsme naposledy hráli pět sezón v&nbsp;řadě mezi 
lety 2007 až 2012.&nbsp;</p>
	<p class="auto-style7">
	<b id="docs-internal-guid-234c2bad-7fff-b797-8085-f18e79e69e2d0" style="font-weight:normal;">
	<a href="../obrazky/2024_06_tym_foto_postup.jpg" target="_blank">foto 
	postupového týmu</a></b></p>
	<p class="auto-style7">&nbsp;Ze čtyřiadvaceti odehraných zápasů jsme jich 
	osmnáct vyhráli, třikrát jsme remizovali a pouze třikrát prohráli. V&nbsp;tabulce 
	domácích zápasů nám patří první příčka soutěže, neboť jsme doma zvítězili 
	v&nbsp;jedenácti ze dvanácti odehraných utkáních a pouze jednou ztratili body při 
	jarní remíze 2:2 s&nbsp;Chotěboří&nbsp;„C“. Venku už to bylo trochu slabší, z&nbsp;dvanácti 
	odehraných zápasů jsme jich na hřištích soupeřů sedm vyhráli, dva remizovali 
	a tři prohry přišly v&nbsp;podzimních zápasech v&nbsp;Chotěboři, ve Vísce a ve druhém 
	jarním kole i ve Štokách.&nbsp;</p>
	<p class="auto-style7">&nbsp;Suma sumárum nám to v&nbsp;konečné tabulce stačí na 
	krásné druhé místo, první Tis „B“ před námi nakonec uhájil náskok tří bodů. 
	Nutno poznamenat, že Tis „B“ za celou sezónu prohrál jen dvakrát, a to vždy 
	s&nbsp;námi – na&nbsp;podzim jsme je doma porazili 5:1, na jaře pak i na jejich hřišti 
	4:0.&nbsp;</p>
	<p class="auto-style7">&nbsp;Vzhledem k&nbsp;vývoji ve vyšších soutěžích to 
	původně nevypadalo, že by „nahoru“ do Okresního přeboru mohly postupovat dva 
	týmy. Naštěstí ale nakonec došlo k&nbsp;posunům, z&nbsp;Okresního přeboru postoupila 
	do krajské I.B třídy dvojice Herálec a Havlíčkova Borová, a tudíž se v&nbsp;OP 
	uvolnilo jedno místo pro nás a mohli jsme s&nbsp;krátkým dvoudenním zpožděním 
	postup slavit též. </p>
	<p class="auto-style2">
	<img alt="Tabulka 2023/2024" height="494" src="../obrazky/2024.06-tabulka2023_2024.png" width="443" /></p>
	<p class="auto-style7">Jak je vidno z&nbsp;tabulky, naše ofenzivní síla byla 
	tentokráte opravdu rekordní. 112 vstřelených branek je maximem jak třetí 
	třídy, tak naší historie. Od doby, kdy vedeme podrobné statistiky bylo naším 
	nejlepším výkonem v&nbsp;této statistice 86 vstřelených branek v&nbsp;sezóně 2006/2007 
	(též postup do OP). Dva naši elitní střelci ostatně obsadili druhou (Vojta 
	Vepřovský- 30 gólů) a třetí příčku (Zdeněk Němec- 25 gólů) pořadí v&nbsp;rámci 
	celé soutěže, na vítěze Jana Miříckého z&nbsp;Tisu „B“ (36 gólů) jim pravda pár 
	gólů ještě chybělo. Pozadu se ale nedržela ani defenzíva, 33 obdržených 
	branek je druhý nejlepší výsledek soutěže hned za Chotěboří „C“, která 
	dostala ještě o jednu branku méně.</p>
	<p class="auto-style7">Pokud bych měl mluvil o faktorech, které 
	napomohly tomuto nečekanému úspěchu, musím zmínit především tři věci. První 
	z&nbsp;nich je posílení týmu před sezónou, kdy k&nbsp;nám postupně přišla pětice velmi 
	kvalitních, a hlavně mladých hráčů. Lukáš Mrkvička bohužel na jaře kvůli 
	zdravotním trablům hrát nemohl, na podzim si ale připsal deset startů. 
	Čtveřice dalších hráčů se pak stala pevnou součástí základní sestavy našeho 
	týmu – Michal Moldavčuk, Kuba Rejholec, Jirka Šťastný a samozřejmě i již 
	zmiňovaný kanonýr Vojta Vepřovský.</p>
	<p class="auto-style7">Druhým faktorem je rozšíření trenérského týmu o 
	Davida Vránu, který se připojil k&nbsp;Petrovi Kodýmovi a do naší hry postupně 
	„vpašoval“ nové myšlenky i taktiky.</p>
	<p class="auto-style7">No a třetím faktorem je ochota všech hráčů 
	podřídit se tomu co a jak chceme na hřišti hrát, přijmout svou roli třebas i 
	střídajícího hráče, a hlavně pracovitost kdy většina hráčů chodila v&nbsp;dlouhé 
	zimní pauze sama běhat abychom na jaro byli připraveni co možná nejlépe. 
	Přičtete-li k&nbsp;tomu skvělé zázemí našeho hřiště o které se s&nbsp;pomocí obce 
	stará Danek Říčan a hlasitou podporu všech našich fanoušků a příznivců 
	kterých s&nbsp;námi je občas i venku více než domácích fanoušků, dostaneme tak 
	nakonec takovouto skvělou odměnu pro všechny.</p>
	<p class="auto-style7">Ve statistikách sezóny 2023/2024 máme interně 
	započítaný i jeden odehraný a vítězný zápas proti Přibyslavi „B“ která 
	nakonec ze soutěže odstoupila, a tudíž se do oficiálních statistik nepočítá. 
	Nejvíc startů si připsal Adam Jablonský, který za celou sezonu chyběl jen 
	jednou – v&nbsp;Dolním Městě. Dvě absence si zapsali gólman Petr Veselý, Marek 
	Ondráček, Matěj Hochman a Tomáš Štěrba. Třikrát chyběli Michal Vopršal a 
	Daniel Říčan. </p>
	<p class="auto-style7"><strong>Nejlepší střelci (+ kanadské bodování) sezóny:<br />
	</strong>1. Vojtěch Vepřovský- 30 gólů + 16 asistencí = 46 bodů<br />
	2. Zdeněk Němec- 25 gólů + 11 asistencí = 36 bodů<br />
	3. Marek Ondráček- 15 gólů + 19 asistencí = 34 bodů<br />
	4. Jára Ondráček- 12 gólů + 16 asistencí = 28 bodů<br />
	5. Matěj Hochman- 8 gólů + 8 asistencí = 16 bodů </p>
