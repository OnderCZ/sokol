<p class="auto-style2"><strong>Hodnocení podzimní části sezóny 2023/2024</strong></p>
<p class="auto-style47">&nbsp; Sobíňovští fotbalisté za sebou mají jednu z 
nejúspěšnějších půl sezon za poslední roky. Z dvanácti odehraných utkání jsme 
dokázali osmkrát zvítězit, dvakrát remizovat a jen dvě utkání jsme prohráli. 
S&nbsp;celkovým ziskem 26 bodů nám v&nbsp;průběžné tabulce soutěže patří třetí příčka, 
přičemž na první Chotěboř „C“ ztrácíme tři body a na druhý Tis „B“ jeden bod. 
Dvě prohry přišly hned po sobě v šestém a sedmém kole kdy jsme dvakrát prohráli&nbsp; 
0:1. Paradoxně se tak stalo na hřišti prvního a poté v podstatě posledního týmu 
podzimní tabulky, tj. v Chotěboři a ve Vísce. Doma jsme odehráli během podzimu 
pět zápasů, všechny jsme vyhráli s krásným skóre 35:8 a to nám ještě do této 
statistiky není započítán zápas s Přibyslaví "B". I v něm jsme původně zvítězili 
2:0. Přibyslav pak ale soutěž odhlásila a tak byly všechny její odehrané zápasy 
anulovány. Naše ofenzíva se pyšní 51 vstřelenými brankami (průměr 4,25 
vstřelených gólů na zápas), což nás v naší soutěži řadí v této statistice na 
druhé místo, defenzíva je pak s pouhými šestnácti obdrženými brankami (průměr 
1,3 obdržené branky na zápas) ve třetí třídě zatím nejlepší.</p>
<p class="auto-style47">Soutěž jsme začali v Lípě a v průběhu utkání jsme vedli 
3:1, nakonec jsme ale byli ještě rádi za remízu 3:3. Jasně jsme poté zvítězili v 
prvním derby ve Ždírci, v divokém domácím zápase jsme přestříleli Štoky "B"- tam 
jsme v poločase vedli 5:1, nakonec jsme ale dohrávali v deseti a byli rádi za 
výhru 6:4. Po dvou v úvodu již zmíněných prohrách v Chotěboři a ve Vísce jsme 
dokázali otočit zápas v Havlíčkově Borové, kterým tak začala naše šňůra pěti 
výher v řadě. Z ní vyčnívá zejména demolice oslabených Hněvkovic v poměru 13:0 a 
zejména rekordní zápis Vojty Vepřovského. Ten v tomto utkání vstřelil svůj první 
gól za Sobíňov a pak jich hostům na dlouhou cestu domů přidal dalších šest, stal 
se tak rekordmanem klubu. Herně možná nejpovedenější zápas jsme odehráli proti 
rezervě Tisu, kterou jsme hlavně díky skvělému druhému poločasu porazili 5:1. V 
absencemi poznamenané sestavě jsme se pak utkali v Malči s místním týmem o 
průběžné třetí místo tabulky, a ačkoliv jsme prohrávali 0:2, dokázali jsme 
nakonec z utkání vybojovat cennou remízu 2:2. V posledním utkání podzimu jsme 
pak po velmi nepovedeném první poločase zcela otočili výsledek proti rezervě 
Lučice a zvítězili jsme nakonec 5:2. </p>
<p class="auto-style47">Po velmi dlouhé době se tentokráte v našem článku 
nedočtete o tom, že nás je málo, že jsme staří a že musíme omladit. A chtělo by 
se říci- konečně :). Již před sezónou nás posílila čtveřice hráčů- Jakub 
Rejholec, Vojta Vepřovský, Lukáš Mrkvička a Jirka Šťastný, po prvních odehraných 
zápasech se k nám přidal i Michal Moldavčuk, a tak se počet posil zastavil 
nakonec na číslu pět. Většina hráčů může hrát na více postech, a i díky tomu že 
máme obvykle "v zásobě" na lavičce minimálně dva či tři naprosto rovnocenné 
hráče na střídání, můžeme občas sestavu trochu občerstvit, hráče prostřídat, 
nebo postavení na hřišti v případně nepříznivého vývoje trochu přeskládat. Navíc 
nás samozřejmě až tak nebolí, když někdo ze základní sestavy na nějaké utkání 
nemůže. A to je rozhodně luxus, který jsme v minulých sezónách neměli. Projevuje 
se to možná i tím, že jsme zejména ke konci podzimu měli druhé poločasy výrazně 
lepší než ty první a jsme v nich schopni naše protivníky spíše přehrát než 
zkraje utkání, kdy mají ještě všichni na hřišti dost sil.</p>
