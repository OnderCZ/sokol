<p class="MsoNormal"><b>2. kolo 
Sobíňov 2:3 Lípa „B“ (0:2)<br>
naše góly: V.Starý, P.Kafka<br>
</b>Začátek zápasu se nesl ve znamení naší převahy, bohužel ani 
nejvyloženější šance jsme nedokázali využít. V&nbsp;největší z&nbsp;nich Štěrba překopl 
z&nbsp;malého vápna téměř úplně prázdnou bránu hostů a ani v&nbsp;další Němec netrefil 
v&nbsp;dobré pozici bránu. Poté přišla naše chyba- po trošku sporné situaci, kdy jsme 
se dožadovali odpískání penalty po souboji ve vápně, hosté dlouhým nákopem 
poslali míč na naši půlku, který jsme nezachytili, a útočník Lípy postupoval sám 
na Veselého, kterému nedal šanci- 0:1. Už v&nbsp;nastaveném čase prvního poločasu pak 
hosté nakrátko rozehráli roh a střelou z&nbsp;úhlu se snažili překvapit našeho 
gólmana. Míč se ovšem bohužel otřel o záda stopera a po této teči neměl Veselý 
šanci- 0:2. Začátek druhé půle se nesl ve znamení spousta nepřesností na obou 
stranách, ani jedno mužstvo si nebylo schopno nahrát třikrát po sobě a hra podle 
toho vypadala. Hosté se cca dvacet minut před koncem dostali do třígólového 
vedení, když další střelu z&nbsp;úhlu opět nešťastně tečovat Říčan a náš gólman lovil 
míč ze sítě potřetí- 0:3. Hned po rozehrání se nám konečně povedla rychlá a 
účelná kombinace, Pešek, který po ní vyplul za obranou Lípy, však bohužel trefil 
jenom tyč. Snížení jsme se tak dočkali až po přímém kopu, který hezky k&nbsp;tyči 
umístil V.Starý- 1:3. Minutu před koncem před koncem obral důrazný Ondráček o 
míč hostujícího beka, který dlouho váhal s&nbsp;rozehrávkou a předložil ho před 
bránu, kde ho dostal podruhé do brány Kafka. Alespoň vyrovnat jsme už ale 
nestihli, fotbal jsme totiž hráli jenom prvních a posledních dvacet minut zápasu 
a to je na Okresní přebor málo. Nic na tom nemění ani to, že první gól jsme 
dostali velmi lacině a dva další jsme si hodně nešťastně vstřelili v&nbsp;podstatě 
sami.<br>
