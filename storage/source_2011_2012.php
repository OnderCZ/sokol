v&nbsp;posledních zápasech určitě zasloužil gólman P.Veselý, který patřil k&nbsp;hlavním 
oporám týmu. Na hřišti se během podzimu objevilo celkem dvacet hráčů, všech 
třináct zápasů odehrála trojice T.Štěrba, V.Starý, M.Vopršal.&nbsp; Dobrým znamením 
je též postupné zapracovávání nově příchozích mladých hráčů do sestavy- A.Pešek, 
D.Jágr, M.Janáček- ti všichni jsou příslibem nadějné budoucnosti.<br>
