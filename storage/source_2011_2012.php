vysoká domácí prohra s&nbsp;Veselým Žďárem&nbsp;(0:3). Herně nejvíce nepovedené zápasy 
jsme odehráli na Starém Ransku (1:4) a v&nbsp;Přibyslavi (0:0). Dobrá utkání jsme 
