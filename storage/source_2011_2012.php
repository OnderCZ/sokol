<p class="MsoNormal"><u><b>Podzim 2011 – Shrnutí<br>
</b></u>V polovině soutěže se nacházíme se stejným bodovým ziskem jako loni na 
předposledním místě tabulky Okresního přeboru Havlíčkobrodska. Odstupy ve druhé 
polovině tabulky však nejsou nikterak hrozivé a mezi sedmou rezervou Lípy a námi 
na místě třináctém je bodový odstup pouhých šesti bodů, ve kterých je namačkáno 
hned sedm týmu. Poslední rezerva Přibyslavi navíc ztrácí pouhé dva body, což 
v&nbsp;tříbodovém systému za vítězství není v&nbsp;podstatě nic. Zaznamenání hodným faktem 
je tak snad pouze to, že zatímco loni jsme po podzimu měli skóre 24:32, máme 
letos na kontě o pět vstřelených branek méně a naopak jsme inkasovali o čtyři 
branky více. Zásadním ukazatel úspěšnosti je pak to, že jsme nejhorším týmem 
v&nbsp;tabulce domácích zápasů, když jsme ze šesti odehraných zápasů vydolovali pouze 
dvě vítězství nad Mírovkou a rezervou Ždírce a máme tak z&nbsp;nich na kontě šest 
bodů. Celkem čtyři body jsme přivezli z&nbsp;Rozsochatce a z&nbsp;Přibyslavi a v&nbsp;tabulce 
zápasů na venkovních hřištích nám tak patří desátá příčka. <br>
