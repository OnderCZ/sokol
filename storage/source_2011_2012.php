<p class="MsoNormal" align="center" style="text-align: left; line-height: normal">
Po pěti letech působení v Okresním přeboru Havlíčkobrodska sestupujeme do třetí 
třídy. Po podzimu jsme se s pouhými deseti body krčili na předposledním místě 
tabulky a kvůli tomu, že jsme na jaře nedokázali bodů nasbírat o moc víc, jsme 
tam zůstali až do konce soutěže. Vzhledem k tomu, že chotěbořská rezerva se 
tentokrát nedokázala udržet v krajské I.B třídě a spolu s ní padá do OP 
Havlíčkobrodska i Dlouhá Ves, musí Okresní přebor opustit též dva týmy. Spolu s 
námi tento úděl postihl i poslední Veselý Žďár. V našich silách určitě bylo 
soutěž zachránit, pokud se sejdeme v plném složení jsme schopni zahrát velmi 
kvalitní fotbal, bohužel si úzký kádr a omezené tréninkové možnosti vybraly svou 
daň. Ze zpětného pohledu z jarních ztrát zamrzí především domácí prohra s Rozsochatcem či remíza s Přibyslaví, se ždíreckou rezervou se též při větší 
troše štěstí mohlo uhrát bodů více.<br>
<br>
Soutěž nakonec vyhrála Leština, který si tak zajistila právo startovat v 
krajských soutěžích. Fotbalový tým z této obce by ale v OP příští rok chybět 
nemusel, jelikož jejich &quot;B&quot; tým vyhrál III.třídu a měl tak právo postoupit výše. 
Podle všech dostupných informací ale rezerva Leštiny o postup moc nestojí a 
místo ní se tedy do OP po roce vrátí Šlapanov.<br>
<br>
Třetí třída v příštím roce obecně dozná poměrně velkou obměnu, kromě dvou 
příchozích týmů z Okresního přeboru přibudou totiž hned tři mužstva ze čtvrtých 
tříd- mimo vítězů obou skupin, kterými jsou Havlíčkova Borová &quot;B&quot; a Lučice &quot;B&quot; 
postupuje též lepší tým z druhých míst, kterými jsou Hněvkovice z ledečského 
okresu. Nová Ves u Chotěboře, startující v současné sezóně též ve třetí třídě 
totiž tuto soutěž příští rok nepřihlásí (většině hráčů skončí hostování z 
Chotěboře, kde vznikne ve IV.třídě hrající &quot;C&quot;) a uvolní tak další místo ve 
&quot;trojce&quot;. V nové sezóně nás tedy čeká konfrontace s mnoha novými týmy.</p>
<p class="MsoNormal">Děkujeme všem našim fanouškům za neustávající podporu 
v&nbsp;domácích i venkovních zápasech, velmi si vážíme toho, že jste nám zůstali 
věrni v&nbsp;hojném počtu i přes nepříliš lichotivé výsledky. V&nbsp;příští sezóně se vám 
budeme snažit přinést více radosti lepšími výsledky..</p>
<p class="MsoNormal" align="center" style="text-align: left; line-height: normal">
<b>Sobíňovské statistiky- 2011/2012</b><br>
V&nbsp;bráně stál ve většině zápasů P.Veselý (23x), který tam na tři záskoky pustil i 
trenéra týmu Z.Wasserbauera. P.Veselý si připsal též jednu asistenci a stal se 
tak vítězem bodování gólmanů :).<br>
<br>
Všech šestadvacet utkání sezóny odehráli T.Štěrba a V.Starý, o jeden start méně 
má na kontě D.Říčan. Dvacet čtyři zápasů odehrála trojice Z.Němec, J.Petruželka 
a M.Vopršal.<br>
<br>
Nejlepším střelcem se stal s osmi brankami T.Štěrba, o dělené druhé místo se 
sedmi přesnými zásahy dělí P.Kafka a Z.Němec. Šest gólů dokázal vstřelit 
V.Starý.<br>
<br>
Nejvíce přesných finálních přihrávek si do statistik zapsal M.Ondráček, který k 
nim zároveň přidal pět branek a s celkem sedmnácti body(5g+12p) se tak stal 
nejproduktivnějším hráčem mužstva. Na druhém místě ho ve statistice přihrávek a 
stejně tak i ve statistice celkové následuje J.Ondráček s patnácti body (5g+10p). 
Pět přihrávek dokázal ke svým gólům připsat T.Štěrba a stal se tak třetím 
nejproduktivnějším hráčem týmu (8g+5p).&nbsp; <br>
