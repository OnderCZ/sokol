</span></b><span style="line-height: 115%; font-family: Verdana">V chladném 
počasí poznamenaném ranním sněžením začali lépe hosté a hned ve čtvrté minutě se 
dostali do vedení po rychlé křídelní akci, kterou po sklepnutí ze středu 
zakončil nechytatelnou pumelicí zpoza vápna Valenta- 0:1. Lipnice byla 
důraznější a aktivnější po většinu hrací doby, nám se občas zadařila kombinace 
ve středu hřiště, ale do vyložených šancí jsme se nedostávali. Přesto jsme zápas 
vyrovnali, v&nbsp;dvacáté čtvrté minutě dostal více místa na hranici velkého vápna 
Němec, míč přidržel, posunul si ho do středu hřiště a levačkou ho přesně 
zakroutil na vzdálenější tyč- 1:1. Poté se odehrával spíš boj ve středu hřiště, 
ještě do přestávky se však hosté opět dostali do vedení- po špatně rozehraném 
přímém kopu z&nbsp;hloubi naší půli se ve čtyřicáté první minutě celá obrana otevřela 
pro rychlou akci Lipnice, kterou přesně zakončil Procházka- 1:2. <br>
Ve druhé půli hosté celkem v&nbsp;poklidu kontrolovali svůj náskok a nepouštěli 
domácí do žádných šancí, sami se pak snažili ohrožovat bránu Sobíňova především 
po standardních situacích, kterých zahrávali celkem dost. Deset minut před 
koncem však přeci jenom vyrobili okénko v&nbsp;obraně, a Němec se ocitl sám před 
gólmanem, který však dokázal přečíst jeho pokus o lob a naši největší šanci o 
vyrovnání tak dobrým zákrokem zhatil. Ani hosté poté nedokázali několik svých 
velkých šancí po akcích hraných již do otevřené obrany dotáhnout do gólového 
konce, a tak svítil na tabuli i na konci zápasu stav 1:2. Při troše štěstí jsme 
možná mohli myslet na remízu, stejně tak ovšem Lipnice mohla vstřelit více 
branek, a tak konečné skóre asi zhruba odpovídá dění na trávníku.<br>
