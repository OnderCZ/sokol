<p align="center"><b><font size="5">Sezóna 2014/2015, III.třída</font></b></p>
<div align="center">
	<p class="MsoNormal" align="left"><strong>Zhodnocení sezóny 2014/2015</strong></p>
	<p class="auto-style1">Fotbalové mužstvo Sobíňova hrálo v sezóně 
	2014/2015 třetím rokem III.třídu okresu Havlíčkův Brod. Obecně se dá říci, 
	že výkony mužstva zůstaly v sestupné tendenci tak, jak se ukázalo již v 
	jarní části sezóny minulé. <br>Tento fakt je potvrzen i dosaženým bodovým 
	ziskem, neboť v jarní části minulé sezóny 2013/2014 získal tým 16bodů, v 
	podzimní části aktuální sezóny 2014/2015 bodů 15 a v jarní části pak bodů 
	16. <br>S celkovým ziskem 31 bodů z 26&nbsp;zápasů se tak Sobíňov umístil na 
	konečném jedenáctém místě tabulky a dost pravděpodobně nás ve III.třídě 
	zachránila úspěšná bodová série ze začátku jara, kdy jsme ve třech zápasech 
	v řadě zvítězili- nad Lípou &quot;B&quot; (3:0), Leštinou&nbsp;&quot;B&quot; (1:0) a Chotěboří &quot;C&quot; 
	(2:1). Mimo těchto tří zápasů jsme dokázali ubojovat už jen dvě vítězství na 
	domácím hřišti, když jsme porazili Českou Bělou a Hněvkovice, přičemž v obou 
	těchto zápasech to byly výhry dost šťastné. Naopak v podstatě se všemi týmy 
	ze spodku tabulky jsme na jaře prohráli- v Mírovce 2:4, v Tisu 1:3 a s 
	Dolním Městem doma 1:2. Poprvé ve III.třídě také máme pasivní skóre- 42 
	vstřelených vs. 49 obdržených branek (loni 61:51).</p>
	<p class="auto-style1">Důvody těchto výsledků jsou víceméně stále stejné- 
	kostra týmu stárne, přibývají rodinné starosti, výkonost klesá a mladí hráči 
	se zabudovávají hodně pomalu. Jedinou světlou výjimkou je v tomto ohledu 
	Matěj Hochman, který se stal na jaře pravidelným hráčem základní&nbsp; 
	sestavy a většinu zápasů odehrál velmi dobře. Když se k tomu přidá obvyklá 
	série dlouhodobých či krátkodobých zranění (A.Pešek, Z.Němec, O.Vopršal, 
	P.Veselý), či dalších absencí způsobených jinými povinnostmi (P.Havelka, 
	J.Petruželka), stávalo se občas, že se zápasy musely odehrát bez střídání a 
	to se samozřejmě do výsledků promítnout musí. Několikrát nám tak během 
	sezóny musel vypomoci například i David Vrána st., který již aktivně tolik 
	nehraje, za což mu ještě jednou velice děkujeme. Hodně nám samozřejmě chyběl 
	i Jára Ondráček (a to nejen jeho 25 gólů a 17 přihrávek), který celou sezónu 
	hostoval v Chotěboři a kde pravidelně hrál za&nbsp;&quot;A&quot; i &quot;B&quot; tým.</p>
	<p class="auto-style1">Soutěž suverénně ovládlo mužstvo Šmolov, které po 
	loňském postupu ze IV. třídy ještě posílilo a letos tedy ihned zase 
	postoupilo do Okresního přeboru. Povedl se jim tudíž stejný kousek jako 
	Sobíňovu v sezóně 2006/2007. Z&nbsp;Okresního přeboru k nám sestupuje 
	družstvo Šlapanova. Do IV. tříd sestupují týmy 
	Mírovky &quot;B&quot; a Tisu &quot;B&quot;, které nahradí vítězové nižších soutěží- Maleč a Nová 
	Ves u Světlé n.S.</p>
	<p class="auto-style9">Statistický přehled sezóny</p>
	<p class="auto-style1">Na hřišti se objevilo celkem 20 hráčů. Z toho v bráně 
	se vystřídali tři gólmani- 17x P.Veselý, 8x Z.Wasserbauer, 1x D.Vrána a 
	všichni dokázali tým dobrými zákroky velmi podržet.<br>Všech 26 zápasů 
	odehrála dvojice V.Starý a M.Vopršal, pouze jednu absenci si připsali 
	D.Říčan a T.Zrzavý.</p>
	<p class="auto-style1">Kanadské bodování:<br>1. P.Kafka- 13 bodů (8 gólů a 5 
	přihrávek, 19 zápasů)<br>2. M.Ondráček- 12 bodů (6+6, 19 zápasů)<br>3. 
	T.Zrzavý- 10 bodů (6+4, 25 zápasů)</p>
	<p class="auto-style1">Střelci:<br>1. P.Kafka- 8x<br>2-4. M.Ondráček, 
	V.Starý, T.Zrzavý - 6x<br>5. J.Petruželka- 5x</p>
	<p class="auto-style1">kompletní
statistiky týmu: <a target="_blank" href="../dokumenty/statistiky_2014_2015.xls">tady</a></p>
	<p class="auto-style1">Letní pauza bude jako vždy velmi krátká, nová sezóna 
	začně již o víkendu 8-9. srpna 2015.<br>Děkujeme za podporu všem fanouškům, divákům a samozřejmě i sponzorům včetně 
	obce Sobíňov, těšíme 
	se na další společnou sezónu...&nbsp;&nbsp; </p>
