	terénu hrál klasický úvodní zápas sezóny, kdy nikdo hlavně nechtěl udělat 
	chybu. Domácí byli prvních patnáct minut lepší, pak jsme na chvíli převzali 
	iniciativu my, těsně před poločasem se ale do vedení dostali přeci jenom 
	Hněvkovice, když J.Šťastný z přímého kopu doslova prostřelil sobíňovskou 
	špatně postavenou zeď- 1:0.<br>
	I po přestávce se hrál celkem neurovnaný fotbal se spoustou nepřesností na 
	obou stranách. Vyrovnání jsme se dočkali zhruba v šedesáté minutě, kdy se 
	domácí trochu nepochopitelně začali na hřišti dohadovat, čehož využil 
	D.Říčan- po rychlém autovém vhazování se k němu dostal míč, který poslal do 
	vápna přesně na hlavu nabíhajícího J.Petruželky a ten hlavičkoval do 
	protipohybu gólmana- 1:1. O chvíli později hlavičkoval Kafka ve vyložené 
	pozici po rohu V.Starého nad bránu domácích, kteří se pak ale oklepali a 
	snažili se zápas rozhodnout ve svůj prospěch. Většina hněvkovických pokusů však 
	mířila vedle tyče naší brány a to naštěstí platilo i po střele z velmi 
	přísně nařízeného nepřímého kopu uvnitř našeho pokutového území za údajnou 
	malou domů. Jak to tak ve fotbale bývá, zafungovalo i zde pravidlo nedáš - 
	dostaneš. Zhruba šest či sedm minut před koncem zápasu byl střídající 
	Zrzavý faulován v blízkosti velkého vápna domácích, a i když byla střela 
	V.Starého sražena chumlem hráčů, vykutálel se ze skrumáže míč přímo před 
	nohy Kafky, který už neměl problém s jeho uklizením do sítě- 1:2. Domácí se 
	však nevzdali, a zkusili alespoň bod přeci jenom ještě ubojovat, což se jim 
	nakonec podařilo. Ve druhé minutě nastavení napřáhl zpoza vápna M.Geher a 
	míč zřejmě i s přispěním terénu proklouzl gólmanovi Veselému pod tělem do 
	sítě- 2:2. Zápas tak skončil asi zaslouženou remízou, se kterou byli nakonec 
	spokojeni všichni.<br>
