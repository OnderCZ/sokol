sestavě čtveřice hráčů, kteří v minulé či i této sezóně působili v šesté lize 
(či chcete-li 1. A třídě), a 
na hřišti to bylo samozřejmě znát. Sobíňov ale také ukázal svou fotbalovou 
kvalitu a v určitých pasážích jsme se soupeři ve středu hřiště dokázali 
vyrovnat. Škoda jen, že jsme více akcí nedotáhli do koncovky, v obou vápnech byl 
rozdíl mezi týmy přeci jen znát. Ve 38. minutě hosté znovu odskočili do 
