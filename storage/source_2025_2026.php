<p class="MsoNormal">Sobíňovští fotbalisté hráli druhým rokem 8. ligu okresu 
Havlíčkův Brod, tedy bývalý okresní přebor, a v tabulce nakonec skončili na 
šestém místě. Po skvělém a rekordním podzimu, během kterého jsme získali 25 
bodů, přišel na jaře přece jen trochu výsledkový útlum. Bodů jsme získali o něco 
méně, konkrétně 19, ale i tak je našich celkových 44 bodů z historického pohledu 
rekordem – alespoň tedy z pohledu let, která mám pokrytá svými záznamy. V letech 
2007 až 2012, kdy jsme okresní přebor také hrávali, bylo totiž naším rekordem 40 
získaných bodů v sezoně 2008/2009. V loňské sezoně 2024/2025 jsme získali 31 
bodů.<o:p></o:p></p>
<p class="MsoNormal">Velkou měrou se o to postaraly zejména naše bodové zisky ze 
hřišť soupeřů. Z venkovních zápasů jsme si totiž do tabulky přivezli celkem 24 
bodů, což nás v tomto ohledu řadí na celkové třetí místo soutěže. Doma už to 
taková sláva nebyla. Získali jsme 20 bodů, což nás v úspěšnosti domácích zápasů 
řadí až do druhé poloviny tabulky osmé ligy. Velmi podobně jsme na tom byli i 
minulou sezonu, potřebovali bychom tedy doma našim fanouškům dělat radost trochu 
častěji…<o:p></o:p></p>
