<p align="center"><b><font size="5">Sezóna 2012/2013, III.třída</font></b></p>
<p class="MsoNormal"><span lang="PL" style="font-size: 11.0pt"><br>
&nbsp;</span></p>
<div align="center">
	<p class="MsoNormal" align="left"><b>Zhodnocení sezóny 2012/2013<br>
	</b>Fotbalové mužstvo Sobíňova letos účinkovalo po loňském sestupu 
	z&nbsp;Okresního přeboru ve III.třídě Havlíčkobrodska. V&nbsp;konečné tabulce skončilo 
	na čtvrtém místě.<br>
	V&nbsp;podzimní polovině sezóny získali fotbalisté 25 bodů, v&nbsp;jarní části soutěže 
	pak bodů 20, celkem tedy bodů 45 za třináct výher, šest remíz a sedm proher.
	</p>
	<p class="MsoNormal" align="left">Zatímco během první půlky soutěže udržel 
	Sobíňov domácí neporazitelnost s&nbsp;jedinou bodovou ztrátou v&nbsp;podobě remízy 
	s&nbsp;Keřkovem, na jaře doma prohrál hned svůj první zápas s&nbsp;Okrouhlicí (1:3), a 
	remízoval třikrát (Veselý Žďár, Dolní Město, Pohled „B“). Právě tyto ztráty 
	stály za nižším bodovým ziskem z druhé části soutěže. </p>
	<p class="MsoNormal" align="left">Na podzim mužstvo vstřelilo 39 branek a 
	inkasovalo jich 21, na jaře vstřelilo branek 26 a inkasovalo jich 22. 
	Celkové skóre činí tedy na konci sezóny 65 vstřelených a 43 obdržených 
	branek.</p>
	<p class="MsoNormal" align="left">Nejvyšší výhry přišly hned na podzim 
	v&nbsp;zápasech s&nbsp;Havlíčkovou Borovou „B“ a s&nbsp;Tisem „B“, kdy Sobíňov oboje zápasy 
	vyhrál jasným rozdílem 6:0. Nejtěžší porážky připravilo fotbalistům Sokola 
	mužstvo Okrouhlic, které na podzim zvítězilo doma 4:0 a na jaře venku 3:1.</p>
	<p class="MsoNormal" align="left">V&nbsp;dresu Sobíňova se během sezóny 
	představili tři gólmani- největší porci osmnácti zápasů spolehlivě odchytal 
	Petr Veselý, pětkrát se v bráně &nbsp;z&nbsp;pozice hrajícího trenéra objevil Zdeněk 
	Wasserbauer a třikrát se do brány postavila i španělská posila v&nbsp;podobě 
	Asiera Mediavilly, který jinak odehrál čtrnáct zápasů jako útočník, ve 
	kterých vstřelil dvě branky.</p>
	<p class="MsoNormal" align="left">Na hřišti se kromě gólmanů objevilo celkem 
	devatenáct hráčů. Všech šestadvacet zápasů sezóny odehrála trojice hráčů- 
	Daniel Říčan, Michal Vopršal a Ondřej Vopršal. Pouze jednou absentoval Tomáš 
	Štěrba.</p>
	<p class="MsoNormal" align="left">Nejvíce „kanadských“ bodů si za celou 
	sezónu zapsal Jaroslav Ondráček, který vstřelil osm gólů, ke kterým si 
	připsal rekordních deset nahrávek a celkem tak nasbíral 18 bodů. O bod 
	pozadu zůstal Pavel Kafka s&nbsp;devíti góly a osmi asistencemi (17b), na třetím 
	místě se pak v&nbsp;pomyslném žebříčku produktivity nachází Marek Ondráček se 
	šesti góly a devíti asistencemi (15b).</p>
	<p class="MsoNormal" align="left">Korunu nejlepšího střelce sezóny si udržel 
	Zdeněk Němec i přesto, že na jaře se z&nbsp;rodinných důvodů na hřišti kromě 
	jednoho zápasu neobjevil. Na vstřelení devíti branek mu totiž stačilo devět 
	odehraných zápasů. Stejný počet devíti branek zaznamenal i Pavel Kafka a 
	Tomáš Štěrba, ti na to ale potřebovali 24, respektive 25 zápasů.</p>
	<p class="MsoNormal" align="left">Do mužstva se pomalu začínají zabudovávat 
	noví hráči, což je jenom dobře, ale zároveň doufáme, že někteří z těch, 
	kteří dočasně kariéru přerušili se k nám zase co nejdřív vrátí. Kvůli 
	pracovním povinnostem většiny hráčů je potřeba mít co nejširší kádr, abychom 
	příští rok mohli hrát minimálně na stejné úrovni jako letos.</p>
	<p class="MsoNormal" align="left">Děkujeme za podporu všem věrným fanouškům, 
	početným divákům a samozřejmě i sponzorům, &nbsp;těšíme se na další společnou 
	sezónu...</p>
